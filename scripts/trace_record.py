    p.add_argument("--person", action="store_true", help="the checker is a person")
    p.add_argument("--agent", action="store_true",
                   help="the checker is a model; its check is advisory")
    p.add_argument("--by", default="",
                   help="the checker's name; with --person, git config user.name when absent")
    p.add_argument("--recorded-by", dest="recorded_by", default="",
                   help="the agent that records the person's words, by its model id")
    p.add_argument("--said", default="", help="what the checker said, verbatim")
    p.add_argument("--candidate", default="", help="what was checked, as the checker named it")
    p.add_argument("--criterion", default="", help="what it was held against")
    p.add_argument("--examined", default="",
                   help="what the checker looked at or compared: the row's method")
    p.add_argument("--result", default="", help="what the checker found")
    p.add_argument("--limits", default="", help="what the checker did not look at")
    p.add_argument("--source", action="append", default=[], metavar="PATH",
                   help="a source the candidate was checked against; a file here is named with "
                        "its sha256. Repeat for each")
    p.add_argument("--artifact", default="",
                   help="a file that holds the check's evidence; without one, the row's own "
                        "words are the evidence and the artifact is declared")
    p.add_argument("--kind", default="", help="the row's kind; person-check or agent-check by default")
    p.add_argument("--checks-jsonl", dest="checks_jsonl", default="",
                   help="the trace record's checks.jsonl, or its staging copy, to append to")
    p.add_argument("--confirm", action="store_true",
                   help="append the row; without it the draft is printed and nothing is written")
    p.set_defaults(func=cmd_check)

    p = sub.add_parser("registries", help="validate the acceptance, intake and transition registries")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_registries)

    p = sub.add_parser("review-status",
                       help="report which published commits are not yet reviewed")
    p.add_argument("--limit", type=int, default=15, help="how many to list")
    p.set_defaults(func=cmd_review_status)

    p = sub.add_parser("verify", help="check a record, report-only by default")
    p.add_argument("record")
    p.add_argument("--range", help="base..head, to check producer trailers")
    p.add_argument("--json", action="store_true",
                   help="print the findings as JSON instead of the report")
    p.add_argument("--strict", action="store_true",
                   help="exit 1 when the record has problems (default: exit 0)")
    p.set_defaults(func=cmd_verify)

    p = sub.add_parser(
        "keep",
        help="keep the running session's trace record before a commit, in one command",
        description="Keep the running session's trace record before a commit: find the session's "
                    "transcript as `session` does, refresh workspace/record-staging/<id>, cover, screen, "
                    "record the disclosure review, promote to ai/records/<id>, verify and draft the commit "
                    "body. It clears consent only with --cleared and the digest it printed, never writes "
                    "the summary, a decision or a check, and never stages or commits. The model for the "
                    "Execution-agent: trailer is the latest model in this session's transcript; a subagent "
                    "shares its parent's session, so a subagent passes --execution-agent with its own model "
                    "id, and an id the transcript does not name as its latest model is recorded as "
                    "self-reported. Exit 0 kept; 1 staged with something missing and nothing promoted, or promoted with a verify "
                    "problem or no body drafted, as the output says; 2 "
                    "refused or a usage error. Nothing here stops a commit.")
    p.add_argument("--record-id", dest="record_id", default="",
                   help="the record to keep; default the one this session kept last, else the one record "
                        "holding this session's turns, else <date>-<words of --subject>")
    p.add_argument("--transcript", default="",
                   help="the transcript to keep, when `session` cannot say which one runs this")
    p.add_argument("--speaker", default="",
                   help="the person typing the turns; default git config user.name on a first capture, "
                        "unless it reads as a model's name (the record says which)")
    p.add_argument("--cleared", default="", metavar="DIGEST",
                   help="declare that you read every captured turn and metadata field: the digest keep "
                        "printed for the turns as they are now. Consent is cleared only with it, and only "
                        "when the local screen finds nothing")
    p.add_argument("--by", default="",
                   help="who read the record for disclosure; default the Execution-agent: model, marked "
                        "as the executing agent (and as self-reported when it is)")
    p.add_argument("--scope", default="",
                   help="the intended audience of the record; default record_scope in ai/project.json, "
                        f"else \"{KEEP_SCOPE}\"")
    p.add_argument("--exclude", nargs=2, action="append", default=[], metavar=("TURN", "REASON"),
                   help="leave a turn out of the summary, with the reason; kept on later runs. Repeat for each")
    p.add_argument("--redact", nargs=3, action="append", default=[], metavar=("TURN", "TEXT", "CATEGORY"),
                   help="replace TEXT, which must occur once in the turn, with [REDACTED: CATEGORY]")
    p.add_argument("--subject", default=None, help="the commit's subject; without it no body is drafted")
    p.add_argument("--out", default="",
                   help="where the commit body goes; default workspace/record-staging/<id>/commit-message.txt")
    p.add_argument("--execution-agent", dest="execution_agent", action="append", default=None,
                   help="the model id for the Execution-agent: trailer; default the latest model in this "
                        "session's transcript, which a subagent shares with its parent, so a subagent "
                        "passes its own model id here. An id the transcript does not name as its latest "
                        "model is recorded as self-reported")
    p.add_argument("--staging", default="", help="the staging folder; default workspace/record-staging/<id>")
    p.add_argument("--reseed", action="store_true",
                   help="start staging again from the promoted record, deliberately")
    p.add_argument("--json", action="store_true", help="print the outcome as JSON")
    p.set_defaults(func=cmd_keep)

    from trace_story import add_commands
    add_commands(sub, sys.modules[__name__])
    args = parser.parse_args(argv)
    try:
        return args.func(args)
    except (OSError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


