def load_jsonl(path: pathlib.Path) -> list[dict]:
    if not path.exists():
        return []
    return [json.loads(ln) for ln in path.read_text(encoding="utf-8").splitlines() if ln.strip()]


def read_registry(path: pathlib.Path, validator) -> list[dict]:
    """Validate before a status reader classifies rows; retain valid legacy rows."""
    rows = load_jsonl(path)
    problems, _ = validator(rows)
    if problems:
        raise ValueError(f"invalid registry {path}: " + "; ".join(problems))
    return rows


def row_by_id(rows: list, rid: str, name: str) -> dict | None:
    """The one registry row with this id, or None when no row has it.

    Two clones that number a row before syncing can give two rows one id, and
    the union merge keeps both. Picking the first would read, or rewrite, a row
    nobody chose, so a shared id raises instead, listing each row by the fields
    that tell them apart, and which one is meant stays a person's call.
    """
    found = [(n, r) for n, r in enumerate(rows, 1) if isinstance(r, dict) and r.get("id") == rid]
    if len(found) < 2:
        return found[0][1] if found else None
    keys: list[str] = []
    for _, r in found:
        for k in r:
            if k != "id" and k not in keys and len({json.dumps(x.get(k), sort_keys=True) for _, x in found}) > 1:
                keys.append(k)
    lines = [f"{name} id {rid} is on rows {', '.join(str(n) for n, _ in found)}; which row is meant is "
             f"a person's call, so nothing was read or changed:"]
    for n, r in found:
        shown = "; ".join(f"{k} {json.dumps(r[k])[:60] if k in r else '(absent)'}" for k in keys)
        lines.append(f"  row {n}: {shown or 'identical to the others'}")
    lines.append("Edit the file so the id names one row (`registries` says whether these are two rows "
                 "numbered alike or two versions of one), then run this again.")
    raise ValueError("\n".join(lines))


def next_serial(rows: list[dict], prefix: str) -> str:
    n = 0
    for row in rows:
        rid = row.get("id")
        if isinstance(rid, str) and rid.startswith(prefix + "-") and rid[len(prefix) + 1:].isdigit():
            n = max(n, int(rid[len(prefix) + 1:]))
    return f"{prefix}-{n + 1:03d}"


def read_object(text: str) -> tuple[str | None, str]:
    """(sha256, "") when the object is a readable file, else (None, why not).

    A name with a space, or an absolute path, is still a file when one is
    there; until AH-140 the test for "looks like a path" ran first, so such a
    file was recorded with no object and no digest, and nothing said so.
    """
    head = (text or "").strip()
    if not head:
        return None, "no path named"
    path = pathlib.Path(head)
    try:
        if not path.is_file():
            return None, f"no file at {head} in this tree"
        return sha256_file(path), ""
    except (OSError, ValueError) as exc:
        return None, f"{head} could not be read ({type(exc).__name__})"


def resolve_commits(values: list[str]) -> list[str]:
    shas = []
    for value in values or []:
        for part in value.split(","):
            part = part.strip()
            if not part:
                continue
            full = git("rev-parse", "--verify", f"{part}^{{commit}}")
            if not re.fullmatch(r"[0-9a-f]{40}", full):
                raise ValueError(f"not a commit in this repository: {part}")
            shas.append(full)
    return shas


def cmd_intake(args: argparse.Namespace) -> int:
    """Record a decision at the entry boundary: outside material admitted, returned or refused.

    Refuses no entry. The row says who decided and what: the actor's name
    (from --by, or git config user.name, as `accept --person` takes it) and
    kind (declared with --person, --agent or --authorized-by, otherwise read
    as an acceptance row's is), the decision, and the material's version
    beside its digest. A refusal is recorded like an admission, so material
    turned away at entry is in the registry and not only in someone's memory.
    """
    decision = (getattr(args, "decision", "") or "").strip() or DEFAULT_DECISION["intake"]
    if decision not in TRANSITION_DECISIONS["intake"]:
        print(f"--decision for intake must be one of {', '.join(TRANSITION_DECISIONS['intake'])}",
              file=sys.stderr)
        return 1
    person, agent = bool(getattr(args, "person", False)), bool(getattr(args, "agent", False))
    authorized_by = (getattr(args, "authorized_by", "") or "").strip()
    if sum((person, agent, bool(authorized_by))) > 1:
        print("--person records a person's own decision, --agent a model's and --authorized-by a "
              "delegated actor's. Choose one.", file=sys.stderr)
        return 1
    by, name_basis = (args.by or "").strip(), "stated"
    if not by and not agent and not authorized_by:
        # The person at the keyboard decides unless someone else is named, and
        # git already knows their name. The kind is still declared, never read
        # off the name, so a defaulted name without --person stays undeclared.
        by, name_basis = git("config", "user.name").strip(), "git config user.name"
    if not by:
        by, name_basis = "not stated", "not stated"
    if authorized_by:
        kind, kind_basis = "delegated", "declared"
    elif person:
        kind, kind_basis = "human", "declared"
    elif agent:
        kind, kind_basis = "agent", "declared"
    else:
        kind = reviewer_kind("" if by == "not stated" else by)
        kind_basis = "inferred from the name" if kind == "agent" else "not declared"
    rows = load_jsonl(INTAKE)
    # The registry reads an unnamed entry as malformed, so an empty name is
    # written as `transition` writes an unnamed object (AH-141).
    what = (args.what or "").strip() or "(unnamed)"
    row = {
        "id": next_serial(rows, "IN"),
        "what": what,
        "origin": (args.origin or "").strip(),
        # The field keeps its historical name; on a return or refusal it names
        # who decided, since nothing was admitted.
        "admitted_by": by,
        "actor_name_basis": name_basis,
        "actor_kind": kind,
        "actor_kind_basis": kind_basis,
        "at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "checked": (args.checked or "").strip() or "nothing stated",
        "used_for": (args.used_for or "").strip(),
        "authority": (getattr(args, "authority", "") or "").strip() or "nothing stated",
        "decision": decision,
        "version": (getattr(args, "version", "") or "").strip() or "not stated",
    }
    if authorized_by:
        row["authorized_by"] = authorized_by
    # An explicit --path is the object as given, with its digest when the file
    # reads; a missing or unreadable one is said, never refused (AH-140).
    # Without --path, the name is the object only when it is a file.
    explicit = (getattr(args, "path", "") or "").strip()
    digest, why_not = read_object(explicit or what)
    if explicit:
        row["object"] = explicit
    elif digest:
        row["object"] = what
    if digest:
        row["object_sha256"] = digest
    INTAKE.parent.mkdir(parents=True, exist_ok=True)
    with INTAKE.open("a", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(row) + "\n")

    verb = {"admit": "admitted", "return": "returned", "refuse": "refused"}[decision]
    actor = INTAKE_ACTORS[kind] + (f", authorized by {authorized_by}" if authorized_by else "")
    if kind_basis == "inferred from the name":
        actor += ", inferred from the name"
    if name_basis == "git config user.name":
        actor += ", name from git config user.name"
    print(f"{verb}: {row['what']}")
    print(f"  by {row['admitted_by']} ({actor}) at {row['at']}")
    print(f"  checked: {row['checked']}")
    print(f"  version: {row['version']}" + (f", digest {digest[:12]}" if digest else ""))
    if explicit and not digest:
        print(f"  {why_not}; the path is recorded as given, with no digest.")
    if kind == "unknown":
        print("  Who decided is " + ("not stated: --by names them, and " if by == "not stated"
                                     else "named, not declared: ") + "--person, --agent or --authorized-by")
        print("  says which kind of actor it was. Recorded as-is.")
    if decision != "admit":
        # The row records the decision; it moves and deletes nothing, so
        # material already in the tree stays there until someone removes it.
        print(f"  {verb.capitalize()} at entry: nothing was admitted under this row, and it removes nothing")
        print("  already in the tree.")
    elif row.get("object", "").replace("\\", "/").removeprefix("./").startswith(
            incoming_folder().rstrip("/") + "/"):
        # The holding folder is outside the data (rc22): admission is the step
        # after which the material moves, and the digest names it where it goes.
        print(f"  Held in {incoming_folder()}/: move it into the project's data now that it is")
        print("  admitted; the digest on this row names it there.")
    # Recording an unchecked entry is allowed and is the point: the gap is then
    # in the record where someone can act on it, rather than absent from it.
    if row["checked"] == "nothing stated":
        print("\n  No check stated. That is recorded as-is, so the entry can be")
        print("  revisited before anything downstream leans on it.")
    print(f"\nRecorded in {INTAKE}.")
    return 0


def cmd_transition(args: argparse.Namespace) -> int:
    """Record one boundary transition: what moved, under whose authority, checked how.

    Intake, promotion into the shared manuscript and adoption of a default are
    the three transitions Section 4 names. Each row joins the exact object (a
    digest when it is a file), the checks referenced, the actor, the authority
    (a turn id in a trace record, or a standing instruction), the
    decision, the destination and the commits the transition covers. The row
    records; it does not authorize. Refuses nothing except an unknown kind or
    decision, and records "nothing stated" where nothing was.
    """
    kind = (args.kind or "").strip()
    if kind not in TRANSITION_KINDS:
        print(f"--kind must be one of {', '.join(TRANSITION_KINDS)}", file=sys.stderr)
        return 1
    decision = (args.decision or "").strip() or DEFAULT_DECISION[kind]
    if decision not in TRANSITION_DECISIONS[kind]:
        print(f"--decision for {kind} must be one of {', '.join(TRANSITION_DECISIONS[kind])}",
              file=sys.stderr)
        return 1
    try:
        commits = resolve_commits(getattr(args, "commits", None) or [])
    except ValueError as exc:
        print(str(exc), file=sys.stderr)
        return 1

    def stated(value: str, default: str = "nothing stated") -> str:
        return (value or "").strip() or default

    rows = load_jsonl(TRANSITIONS)
    obj = stated(args.object, "(unnamed)")
    digest, why_not = read_object(obj)
    row = {
        "id": next_serial(rows, "TR"),
        "kind": kind,
        "object": obj,
        "object_sha256": (args.digest or "").strip() or digest,
        "checks": stated(getattr(args, "checks", "")),
        "by": stated(getattr(args, "by", ""), "not stated"),
        "authority": stated(getattr(args, "authority", "")),
        "decision": decision,
        "destination": stated(getattr(args, "destination", "")),
        "commits": commits,
        "at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    }
    later = (getattr(args, "later_run", "") or "").strip()
    if kind == "default-adoption":
        row["later_run"] = later or "nothing stated"
    TRANSITIONS.parent.mkdir(parents=True, exist_ok=True)
    with TRANSITIONS.open("a", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(row) + "\n")

    print(f"{row['id']} {kind}: {obj} -> {decision}")
    print(f"  by {row['by']} under {row['authority']}")
    print(f"  checks: {row['checks']}")
    if commits:
        print(f"  covers {len(commits)} commit(s)")
    # The object may be a description; one written as a path (a separator or
    # a file suffix) that no readable file answers to is said (AH-140).
    if not row["object_sha256"] and ("/" in obj or "\\" in obj or pathlib.PurePath(obj).suffix):
        print(f"  {why_not}; the object is recorded as named, with no digest.")
    for field in ("checks", "authority"):
        if row[field] == "nothing stated":
            print(f"  No {field} stated. Recorded as-is, so the gap is in the record.")
    # Only an adopted default governs later work; a returned or refused one
    # adopted nothing, and `later-run` refuses it (AH-139).
    if kind == "default-adoption" and decision == "adopt" and row["later_run"] == "nothing stated":
        print("  No later run yet. A changed default governs later work; when a record")
        print(f"  produced under it exists, add what was observed with: later-run {row['id']}")
        print("  --record <that record> --observed \"...\" --by <observer> (--person or --agent).")
    print(f"\nRecorded in {TRANSITIONS}. This row records the transition; it does not authorize it.")
    return 0


def refused_yet_in_paper(row: dict, commits: list[str] | None = None) -> list[str]:
    """Where a returned or refused row's object is in paper/ at the commits it covers.

    A transition row records a decision and stops nothing, so the work it
    returned or refused can still be in the manuscript. That reads C recorded,
    which is true and incomplete; this says it. The object or destination is
    looked up in each covered commit's tree when it is a file under paper/;
    a folder under paper/ is flagged when the covered commit changes a file in
    it, and a promotion naming no such file or folder when the covered commit
    changes paper/ at all. A fact about the tree, never a judgment of the row.
    """
    decision = row.get("decision")
    if decision not in ("return", "refuse"):
        return []
    paths = []
    for key in ("object", "destination"):
        value = row.get(key)
        if isinstance(value, str):
            value = value.strip().replace("\\", "/").removeprefix("./")
            # A folder may be written with or without its trailing slash; both
            # are read as that folder (0a731a6 F1). paper/ itself is the
            # whole-manuscript reading below.
            value = value.rstrip("/")
            if value.startswith("paper/") and value not in paths:
                paths.append(value)
    if not paths and row.get("kind") != "promotion":
        return []
    covered = [c for c in (row.get("commits") or []) if isinstance(c, str) and SHA_RE.match(c)]
    if commits is not None:
        covered = [c for c in covered if c in commits]
    found = []
    for sha in covered:
        # Only a file is "in paper/" (cf4950e F3). `cat-file -e` holds for a
        # folder too, so a folder named without its trailing slash read as a
        # file in paper/; it is read now as a promotion naming no file is, by
        # what the commit changes, in that folder.
        kinds = {path: git("cat-file", "-t", f"{sha}:{path}") for path in paths}
        files = [path for path, kind in kinds.items() if kind == "blob"]
        folders = [path + "/" for path, kind in kinds.items() if kind == "tree"]
        for path in files:
            found.append(f"{row.get('id', '?')} recorded {decision}, yet {path} is in "
                         f"paper/ at {sha[:12]}")
        if files or (paths and not folders):
            continue
        where = folders or ["paper/"]
        changed = [p for p in git("show", "--format=", "--name-only", sha, "--", *where).splitlines() if p]
        if changed:
            found.append(f"{row.get('id', '?')} recorded {decision}, yet {sha[:12]} changes "
                         f"{len(changed)} file(s) in {', '.join(where)}")
    return found


LATER_RUN_KINDS = ("human", "agent", "delegated")
LATER_RUN_OBSERVERS = {"human": "a person", "agent": "a model", "delegated": "a delegated actor"}


def later_run_candidates(row: dict) -> list[str]:
    """The trace records that could be this adoption's later run, found and not judged.

    A record produced under the adopted instruction carries that file's digest
    in its evidence (`extract` records the instruction files in force), so the
    match is mechanical; whether the run shows the instruction doing what it
    was adopted to do is the observation, and that is stated by someone.
    """
    obj, digest = (row.get("object") or "").strip(), row.get("object_sha256")
    if not digest or not PATHLIKE_RE.match(obj):
        return [f"the object of {row.get('id')} is not a file whose digest the row holds, "
                "so candidates cannot be found mechanically; name the record with --record"]
    same, later = [], []
    adopted = row.get("commits") or []
    for folder in sorted(pathlib.Path("ai/records").glob("*/")):
        evidence = folder / "evidence.json"
        if not evidence.is_file():
            continue
        try:
            data = json.loads(evidence.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        instructions = data.get("instructions") or {}
        files = instructions.get("files") or {}
        if files.get(obj) == digest:
            same.append(folder.name)
        elif obj in files and adopted and instructions.get("base_commit"):
            base = str(instructions["base_commit"])
            if any(subprocess.run(["git", "merge-base", "--is-ancestor", sha, base],
                                  capture_output=True).returncode == 0 for sha in adopted):
                later.append(folder.name)
    def listed(names: list[str]) -> str:
        if not names:
            return "none found"
        newest = sorted(names, reverse=True)
        return ", ".join(newest[:8]) + (f" and {len(newest) - 8} more" if len(newest) > 8 else "")
    out = [f"candidate later runs for {row.get('id')} ({obj} at {str(digest)[:12]}):",
           "  produced under this version of it: " + listed(same),
           "  produced under a later version of it: " + listed(later)]
    out.append("A candidate is found, not judged: link one with --record and say in --observed what the")
    out.append("revised instruction did in that run. No observation, no link.")
    return out


def cmd_later_run(args: argparse.Namespace) -> int:
    """Add a later-run observation to an existing default-adoption row, or list candidates.

    The later record does not exist when the adoption is recorded, so the link
    is added when it does, by whoever observed the run: a person, a model
    (shown as such) or a delegated actor. The observation is the check; a bare
    link would make the report read `recorded` with nobody having looked.
    """
    tid = (args.transition or "").strip()
    rows = load_jsonl(TRANSITIONS)
    try:
        row = row_by_id(rows, tid, "transitions")
    except ValueError as exc:
        print(exc, file=sys.stderr)
        return 1
    if row is None:
        print(f"no transition row {tid} in {TRANSITIONS}", file=sys.stderr)
        return 1
    if row.get("kind") != "default-adoption":
        print(f"{tid} is a {row.get('kind')} row; a later run belongs to a default adoption",
              file=sys.stderr)
        return 1
    if row.get("decision") != "adopt":
        print(f"{tid} records {row.get('decision')}, not an adoption; nothing was adopted "
              "for a later run to check", file=sys.stderr)
        return 1
    record = (getattr(args, "record", "") or "").strip()
    if not record:
        for line in later_run_candidates(row):
            print(line)
        return 0
    observed = (getattr(args, "observed", "") or "").strip()
    if not observed:
        print("say what you observed the revised instruction do in that run, with --observed. "
              "No observation, no link.", file=sys.stderr)
        return 1
    person, agent = bool(getattr(args, "person", False)), bool(getattr(args, "agent", False))
    authorized_by = (getattr(args, "authorized_by", "") or "").strip()
    if sum((person, agent, bool(authorized_by))) != 1:
        print("declare the observer's kind: --person, --agent or --authorized-by \"Full Name\" (one of them)",
              file=sys.stderr)
        return 1
    by = (getattr(args, "by", "") or "").strip()
    if not by and person:
        by = git("config", "user.name").strip()
    if not by:
        print("name the observer with --by", file=sys.stderr)
        return 1
    kind = "delegated" if authorized_by else "human" if person else "agent"
    target = str(record_path(record)).replace("\\", "/")
    on_disk = (pathlib.Path(target) / "evidence.json").is_file()
    previous = row.get("later_run")
    if previous and previous != "nothing stated":
        row.setdefault("later_run_previous", []).append(
            {k: row[k] for k in ("later_run", "later_run_observed", "later_run_by",
                                 "later_run_kind", "later_run_authorized_by", "later_run_at") if k in row})
    row["later_run"] = target
    row["later_run_observed"] = observed
    row["later_run_by"] = by
    row["later_run_kind"] = kind
    if authorized_by:
        row["later_run_authorized_by"] = authorized_by
    else:
        row.pop("later_run_authorized_by", None)
    row["later_run_at"] = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    tmp = TRANSITIONS.with_name(TRANSITIONS.name + ".tmp")
    tmp.write_text("".join(json.dumps(r) + "\n" for r in rows), encoding="utf-8", newline="\n")
    os.replace(tmp, TRANSITIONS)
    print(f"{tid} {row.get('object')}: later run {target}, observed by {by} ({LATER_RUN_OBSERVERS[kind]})")
    print(f"  observed: {observed}")
    if not on_disk:
        print(f"  {target} is not in this tree; the link is recorded as stated.")
    if previous and previous != "nothing stated":
        print(f"  the earlier later run, {previous}, is kept under later_run_previous.")
    if kind == "agent":
        print("  A model's observation is advisory; the report shows it as observed by a model.")
    print(f"\nRecorded in {TRANSITIONS}. This row records an observation; it accepts nothing.")
    return 0


# --- Registries: validated on read ------------------------------------------
#
# Acceptance rows, intake rows and transition rows are appended by their
# commands and were, until 2026-09-15, never checked again. A row with a kind
# nobody declared, or a decision outside the vocabulary, was then read as
# whatever the reporting code assumed. The validators below run in the workflow
# check and in `registries`, so a malformed row is reported where it can be
# fixed rather than silently classified.

SHA_RE = re.compile(r"^[0-9a-f]{40}$")


def _text(row: dict, key: str) -> bool:
    return isinstance(row.get(key), str) and bool(row[key].strip())


def validate_acceptances(rows: list[dict]) -> tuple[list[str], list[str]]:
    problems, notes = [], []
    legacy = from_words = bound = unauthorized = own_work = 0
    for n, row in enumerate(rows, 1):
        where = f"acceptances row {n}"
        if not isinstance(row, dict):
            problems.append(f"{where}: not an object")
            continue
        if "through" in row:
            # The version a decision was bound to (`accept --through`). A row
            # written before the bound existed has no such field and reads as
            # it always did: its covers are what it reached.
            if not (isinstance(row["through"], str) and SHA_RE.match(row["through"])):
                problems.append(f"{where}: through must be a full commit sha")
            else:
                bound += 1
        kind = row.get("kind")
        if kind not in REVIEW_KINDS:
            problems.append(f"{where}: kind {kind!r} is not one of {REVIEW_KINDS}")
        if not _text(row, "reviewer"):
            problems.append(f"{where}: no reviewer")
        covers = row.get("covers")
        if not isinstance(covers, list) or not covers or not all(isinstance(c, str) and SHA_RE.match(c) for c in covers):
            problems.append(f"{where}: covers must be a non-empty list of commit shas")
        if "count" in row and isinstance(covers, list) and row.get("count") != len(covers):
            problems.append(f"{where}: count does not match covers")
        if not _text(row, "at"):
            problems.append(f"{where}: no timestamp")
        if "kind_basis" not in row:
            legacy += 1
        if kind in ACCEPTING_KINDS:
            decision = row.get("decision", "accept")
            if decision not in DECISIONS:
                problems.append(f"{where}: decision {decision!r} is not one of {DECISIONS}")
            if kind == "delegated" and not _text(row, "authorized_by"):
                problems.append(f"{where}: delegated acceptance names no authorizing researcher")
        if "recorded_by" in row:
            # A person's decision an agent typed from the person's words. The
            # words are what make it the person's; without them the row would
            # be an agent's claim about a person.
            if kind != "human":
                problems.append(f"{where}: recorded_by belongs to a person's own decision")
            if not _text(row, "recorded_by"):
                problems.append(f"{where}: recorded_by names nobody")
            if not _text(row, "words"):
                problems.append(f"{where}: recorded_by without the person's words")
            elif kind == "human":
                from_words += 1
        elif kind == "agent":
            if "decision" in row and row["decision"] not in (SELF_REVIEW_DECISION, NO_AUTHORITY_DECISION):
                problems.append(f"{where}: a model review carries no decision")
            if type(row.get("self_review")) is not bool:
                problems.append(f"{where}: self_review must be true or false")
        if "authority" in row:
            # The words that authorized a delegation (`accept --authority`). A
            # row written before the field existed has none and reads as before.
            if not _text(row, "authority"):
                problems.append(f"{where}: authority must be the authorization's words, or 'not stated'")
            elif not _text(row, "authorized_by"):
                problems.append(f"{where}: authority without the researcher who gave it (authorized_by)")
            elif row["authority"] == AUTHORITY_NOT_STATED:
                unauthorized += 1
        if "own_work" in row:
            # Commits the deciding person typed, named on a person's decision.
            own = row["own_work"]
            if kind != "human":
                problems.append(f"{where}: own_work belongs to a person's own decision")
            elif (not isinstance(own, list) or not own or not all(isinstance(c, str) for c in own)
                  or not set(own) <= set(c for c in (covers if isinstance(covers, list) else [])
                                         if isinstance(c, str))):
                problems.append(f"{where}: own_work must list covered commits")
            else:
                own_work += 1
    if legacy:
        notes.append(f"{legacy} acceptance row(s) predate declared actor kinds and are read as written")
    if from_words:
        notes.append(f"{from_words} acceptance row(s) a person decided and an agent recorded from their words")
    if bound:
        notes.append(f"{bound} acceptance row(s) bound to a stated version with --through")
    if unauthorized:
        notes.append(f"{unauthorized} delegation(s) recorded with authority not stated, read as advisory")
    if own_work:
        notes.append(f"{own_work} acceptance row(s) a person decided about commits they typed (own_work)")
    return problems, notes


def validate_intake(rows: list[dict]) -> tuple[list[str], list[str]]:
    problems, notes = [], []
    legacy = undeclared_era = turned_away = 0
    for n, row in enumerate(rows, 1):
        where = f"intake row {n}"
        if not isinstance(row, dict):
            problems.append(f"{where}: not an object")
            continue
        for key in ("what", "admitted_by", "at", "checked"):
            if not _text(row, key):
                problems.append(f"{where}: no {key}")
        if "decision" in row and row["decision"] not in TRANSITION_DECISIONS["intake"]:
            problems.append(f"{where}: decision {row['decision']!r} is not one of {TRANSITION_DECISIONS['intake']}")
        if "id" not in row:
            legacy += 1
        # The actor's kind and the material's version came in rc22; a row
        # without them predates them and is read as written.
        if "actor_kind" not in row:
            undeclared_era += 1
        elif row["actor_kind"] not in INTAKE_ACTOR_KINDS:
            problems.append(f"{where}: actor_kind {row['actor_kind']!r} is not one of {INTAKE_ACTOR_KINDS}")
        elif row["actor_kind"] == "delegated" and not _text(row, "authorized_by"):
            problems.append(f"{where}: a delegated intake decision names no authorizing researcher")
        if "version" in row and not _text(row, "version"):
            problems.append(f"{where}: version is empty; an unstated version is written as 'not stated'")
        if row.get("decision") in ("return", "refuse"):
            turned_away += 1
    if legacy:
        notes.append(f"{legacy} intake row(s) predate identifiers and are read as written")
    if undeclared_era:
        notes.append(f"{undeclared_era} intake row(s) predate the recorded actor kind and are read as written")
    if turned_away:
        notes.append(f"{turned_away} intake row(s) record material returned or refused at entry")
    shared_problems, shared_notes = ids_found_twice(rows, "intake")
    problems.extend(shared_problems)
    notes.extend(shared_notes)
    return problems, notes


LATER_RUN_FIELDS = ("later_run", "later_run_observed", "later_run_by", "later_run_kind",
                    "later_run_authorized_by", "later_run_at", "later_run_previous")


def ids_found_twice(rows: list, name: str) -> tuple[list[str], list[str]]:
    """Say which row ids two rows share, which a sync of two clones can produce.

    Each clone numbers a new row from the last one it has, so two people who
    both write before syncing give their rows the same id, and the union merge
    in .gitattributes keeps both. Neither row is wrong, so that is a note; a
    lookup by the id refuses to pick one. Rows that differ only in their later-run
    fields are two versions of one row: `later-run` rewrote it in one clone
    while the other appended, and the union kept the old version beside the
    new. That is a problem, because a reader would count one row twice.
    """
    seen: dict[str, list[int]] = {}
    for n, row in enumerate(rows, 1):
        if isinstance(row, dict) and isinstance(row.get("id"), str):
            seen.setdefault(row["id"], []).append(n)
    problems, notes = [], []
    for rid, at in seen.items():
        if len(at) < 2:
            continue
        where = ", ".join(map(str, at))
        bodies = {json.dumps({k: v for k, v in rows[n - 1].items() if k not in LATER_RUN_FIELDS}, sort_keys=True)
                  for n in at}
        if len(bodies) == 1:
            problems.append(f"{name} rows {where} are versions of one row {rid}, kept by a sync after one clone "
                            f"updated it in place while another appended; keep the version with the latest "
                            f"later_run_at and delete the others")
        else:
            notes.append(f"{name} id {rid} is on rows {where}, numbered in two places before a sync; "
                         f"each row stands, and a lookup by {rid} refuses to pick one")
    return problems, notes


def validate_transitions(rows: list[dict]) -> tuple[list[str], list[str]]:
    problems, notes = [], []
    for n, row in enumerate(rows, 1):
        where = f"transitions row {n}"
        if not isinstance(row, dict):
            problems.append(f"{where}: not an object")
            continue
        kind = row.get("kind")
        if kind not in TRANSITION_KINDS:
            problems.append(f"{where}: kind {kind!r} is not one of {TRANSITION_KINDS}")
            continue
        for key in ("id", "object", "by", "authority", "checks", "decision", "at"):
            if not _text(row, key):
                problems.append(f"{where}: no {key}")
        if row.get("decision") not in TRANSITION_DECISIONS[kind]:
            problems.append(f"{where}: decision {row.get('decision')!r} is not one of {TRANSITION_DECISIONS[kind]}")
        commits = row.get("commits", [])
        if not isinstance(commits, list) or not all(isinstance(c, str) and SHA_RE.match(c) for c in commits):
            problems.append(f"{where}: commits must be a list of commit shas")
        if "later_run_kind" in row:
            # A later run with a declared observer carries the observation; a
            # link alone is what the report must never read as recorded.
            if row.get("later_run_kind") not in LATER_RUN_KINDS:
                problems.append(f"{where}: later_run_kind {row.get('later_run_kind')!r} is not one of {LATER_RUN_KINDS}")
            for key in ("later_run", "later_run_observed", "later_run_by"):
                if not _text(row, key):
                    problems.append(f"{where}: a later run with a declared observer has no {key}")
            if row.get("later_run_kind") == "delegated" and not _text(row, "later_run_authorized_by"):
                problems.append(f"{where}: a delegated later-run observer names no authorizing researcher")
    shared_problems, shared_notes = ids_found_twice(rows, "transitions")
    problems.extend(shared_problems)
    notes.extend(shared_notes)
    return problems, notes


def commits_off_history(rows: list) -> list[str]:
    """Say which transition rows name a commit the checked-out history does not hold.

    A row written before its commit was pushed names a sha that a rebasing
    Sync then rewrites. The clone that rebased keeps the old commit in its
    object store, unreachable from HEAD; every other clone cannot resolve it.
    Either way the row joins no commit in the branch, and the commit that
    replaced the old one reads C missing. The row is well formed and
    correcting the sha is a person's edit, so these are notes. A shallow clone
    cannot see past its boundary, so there a sha outside the fetched history is
    counted as unchecked, not reported as stale, even when the object is held.
    """
    # A malformed `commits` is the row validator's problem to report, not this check's.
    named = [(n, row.get("id", "?"), sha) for n, row in enumerate(rows, 1)
             if isinstance(row, dict) and isinstance(row.get("commits"), list)
             for sha in row["commits"] if isinstance(sha, str) and SHA_RE.match(sha)]
    if not named or not git("rev-parse", "--verify", "-q", "HEAD"):
        return []
    reachable = set(git("rev-list", "HEAD").split())
    shallow = git("rev-parse", "--is-shallow-repository") == "true"
    notes, unchecked = [], 0
    for n, rid, sha in named:
        if sha in reachable:
            continue
        if shallow:
            unchecked += 1
        elif subprocess.run(["git", "cat-file", "-e", f"{sha}^{{commit}}"], capture_output=True).returncode == 0:
            notes.append(f"transitions row {n} ({rid}) names {sha[:12]}, which this repository holds outside "
                         f"the checked-out history: rewritten by a rebase, or on another branch")
        else:
            notes.append(f"transitions row {n} ({rid}) names {sha[:12]}, which is not in this repository: "
                         f"rewritten by a rebase in another clone, or never pushed")
    if unchecked:
        notes.append(f"{unchecked} transition commit reference(s) not checked: this clone is shallow, and a "
                     f"commit outside the history it fetched may still be in the branch")
    return notes


# Curly quotes read as straight ones, so words a chat client curled still match.
QUOTE_FOLD = str.maketrans({"\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"'})


def words_in_human_turns(rows: list, records: pathlib.Path = pathlib.Path("ai/records")) -> list[str]:
    """Say, for each decision an agent recorded from a person's words, where those words were captured.

    Every record is searched, because a decision is usually said in a later
    session than the record it decides about. Only human turns count; a turn an
    agent or a harness wrote, or one relabelled as such, never does. In a turn
    answering the question dialog, only what the person supplied is searched,
    each answer and note, and never the agent's question or the options left
    unpicked, which that turn's text also carries (AH-280); a match there is
    said to be in an answer given through the dialog. Whitespace, case and curly
    quotes are folded, and the first turn holding the words is named: the words
    occur there, which for a short reply does not show they were said there. Not
    found is not a fault: the session they were said in may not be captured yet,
    or the words were redacted. These are notes, and they change no state.
    """
    def fold(text: str) -> str:
        return " ".join(text.translate(QUOTE_FOLD).split()).casefold()

    wanted = [(n, fold(row["words"])) for n, row in enumerate(rows, 1)
              if isinstance(row, dict) and row.get("kind") == "human"
              and _text(row, "recorded_by") and _text(row, "words")]
    if not wanted:
        return []
    folders = sorted(p for p in records.iterdir() if p.is_dir()) if records.is_dir() else []
    turns = []
    for folder in folders:
        for turn in record_turns(folder):
            # A legacy turn has no speaker_kind and was always the human's.
            if turn.get("speaker_kind", "human") != "human":
                continue
            name = f"{folder.as_posix()} {turn.get('id', '?')}"
            if isinstance(turn.get("dialog"), list):
                supplied = [entry.get(key) for entry in turn["dialog"] if isinstance(entry, dict)
                            for key in ("answer", "note")]
                turns.append((name, [fold(t) for t in supplied if isinstance(t, str)], True))
            elif isinstance(turn.get("text"), str):
                turns.append((name, [fold(turn["text"])], False))
    notes = []
    for n, words in wanted:
        found = next(((name, dialog) for name, texts, dialog in turns
                      if any(words in text for text in texts)), None)
        if found and found[1]:
            notes.append(f"acceptances row {n}: the person's words occur in an answer given through "
                         f"the question dialog, {found[0]}")
        elif found:
            notes.append(f"acceptances row {n}: the person's words occur in a captured human turn, {found[0]}")
        else:
            notes.append(f"acceptances row {n}: the person's words occur in no captured human turn; "
                         f"the session they were said in may not be captured yet, or the words redacted")
    return notes


def validate_registries(acceptances: pathlib.Path | None = None, intake: pathlib.Path | None = None,
                        transitions: pathlib.Path | None = None) -> dict:
    """Read the three appended registries and say what is wrong with each row."""
    out = {"problems": [], "notes": [], "rows": {}}
    for name, path, fn in (("acceptances", acceptances or ACCEPTANCES, validate_acceptances),
                           ("intake", intake or INTAKE, validate_intake),
                           ("transitions", transitions or TRANSITIONS, validate_transitions)):
        try:
            rows = load_jsonl(path)
        except (OSError, json.JSONDecodeError) as exc:
            out["problems"].append(f"{name}: unreadable ({exc})")
            out["rows"][name] = None
            continue
        problems, notes = fn(rows)
        if name == "transitions":
            notes.extend(commits_off_history(rows))
        elif name == "acceptances":
            notes.extend(words_in_human_turns(rows))
        out["problems"].extend(problems)
        out["notes"].extend(notes)
        out["rows"][name] = len(rows)
    out["ok"] = not out["problems"]
    return out


def cmd_registries(args: argparse.Namespace) -> int:
    """Validate the appended registries. Exit 1 on a malformed row."""
    result = validate_registries()
    if getattr(args, "json", False):
        print(json.dumps(result))
        return 0 if result["ok"] else 1
    for name, count in result["rows"].items():
        print(f"  {name:<13}{'unreadable' if count is None else f'{count} row(s)'}")
    for note in result["notes"]:
        print(f"  note  {note}")
    for problem in result["problems"]:
        print(f"  FAIL  {problem}")
    print("registries valid" if result["ok"] else f"{len(result['problems'])} problem(s)")
    return 0 if result["ok"] else 1


# Version 2 trace records require each check to identify the candidate,
# criterion and limits. Historical records without a version remain readable as
# version 1 and validate those fields only when present. Procedure and durable
# defect/recheck references belong to the shared skill-run handoff and remain
# optional because not every mechanical check is performed through a skill.
CHECK_TEXT_OPTIONAL = ("candidate", "criterion", "limits", "procedure",
                       "procedure_version")
CHECK_LIST_OPTIONAL = ("defect_ids", "recheck_evidence")
CHECK_REQUIRED_V2 = ("candidate", "criterion", "limits")
STABLE_ID_RE = re.compile(r"^[A-Z][A-Z0-9]*-[0-9]+$")
PATHLIKE_RE = re.compile(r"^[A-Za-z0-9_.@~-][^\s]*$")
SKILL_NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
# `sha256:` and at least twelve hex characters of the digest. The convention in
# this repository writes all sixty-four; a prefix is compared as a prefix.
DERIVED_VERSION_RE = re.compile(r"^sha256:[0-9a-f]{12,64}$")
SHA256_RE = re.compile(r"^[0-9a-f]{64}$")
# What a check row says for a field nobody stated. It fills a required field and
# is not a statement, so it binds nothing (rc22).
CHECK_NOT_STATED = "not stated"


# --- Sources a check names (R) ------------------------------------------------
#
# A check row may say what it checked the candidate against: `sources`, a list of
# {path, sha256}, with `snapshot` when the file came from a verified snapshot. It
# is optional, because rows written before rc22 carry none, and a source that is
# not a file here (a printed book, a page seen once) is named without a digest.

def check_field_stated(value) -> bool:
    """Whether a check row's text field says something, rather than `not stated`."""
    return isinstance(value, str) and bool(value.strip()) \
        and value.strip().lower() != CHECK_NOT_STATED


def source_problems(value) -> list[str]:
    """What is wrong with a check row's `sources`, as phrases; empty when nothing is."""
    if not isinstance(value, list) or not value:
        return ["sources must be a non-empty list"]
    problems = []
    for n, entry in enumerate(value, 1):
        if not isinstance(entry, dict) or not isinstance(entry.get("path"), str) \
                or not entry["path"].strip():
            problems.append(f"source {n} must be an object with a path")
            continue
        for key in ("sha256", "snapshot"):
            if key in entry and not (isinstance(entry[key], str) and SHA256_RE.fullmatch(entry[key])):
                problems.append(f"source {n} has a {key} that is not a sha256 digest")
    return problems


def check_sources(row: dict) -> list[str]:
    """The sources a check row names, as `path (sha256 abc123456789)`, with the
    snapshot a source was taken from and whether it verified; empty for none."""
    value = row.get("sources")
    if not isinstance(value, list):
        return []
    out = []
    for entry in value:
        if not isinstance(entry, dict) or not isinstance(entry.get("path"), str):
            continue
        said = [f"sha256 {entry['sha256'][:12]}"] if entry.get("sha256") else []
        if isinstance(entry.get("snapshot"), str):
            said.append(f"verified snapshot {entry['snapshot'][:12]}")
        if entry.get("snapshot_unverified"):
            said.append(f"its snapshot did not verify: {entry['snapshot_unverified']}")
        out.append(f"{entry['path']} ({', '.join(said) or 'no digest'})")
    return out


# --- Snapshots a source is taken from (R) -------------------------------------
#
# `shared_folder.py snapshot` writes a verified copy of shared data under
# workspace/snapshots/<dataset>/, whose identifier is the digest of its manifest.
# A source in one is named with that identifier once `shared_snapshot.py` has
# checked the snapshot's files against the manifest. `agentic_review.py --source`
# and `check --source` share this, so a check a person reports and a review run
# say the same of the same snapshot (rc22; until then `check` hashed a file in a
# snapshot and neither verified the snapshot nor named it).

SNAPSHOTS = "workspace/snapshots"
_STARTER_SCRIPTS: dict[str, object] = {}


def starter_script(name: str):
    """A script the starter ships beside this one, loaded once: here in an installed
    project, under starter/files/scripts/ in the kit's own repository, and None
    where neither holds it."""
    if name in _STARTER_SCRIPTS:
        return _STARTER_SCRIPTS[name]
    import importlib.util
    here = pathlib.Path(__file__).resolve().parent
    module = None
    for base in (here, here.parent / "starter" / "files" / "scripts"):
        path = base / f"{name}.py"
        if path.is_file():
            spec = importlib.util.spec_from_file_location(f"trace_record_{name}", path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            break
    _STARTER_SCRIPTS[name] = module
    return module


def snapshot_parts(rel: str) -> tuple[str, str | None] | None:
    """(store, snapshot id or None) for a path in a snapshot store that
    `shared_folder.py snapshot` writes, workspace/snapshots/<dataset>/: the store
    itself, or any path inside one of its snapshots' folders
    (snapshots/<id>/, its data folder and what is below it); None for anything else.

    Until rc22's review (f1ca7a5 F001) only a path below a snapshot's data folder
    was read as that snapshot, so naming the snapshot's folder or its data folder
    took the files without checking them against the manifest.
    """
    parts, prefix = rel.rstrip("/").split("/"), SNAPSHOTS.split("/")
    if parts[:len(prefix)] != prefix or len(parts) == len(prefix):
        return None
    store, rest = "/".join(parts[:len(prefix) + 1]), parts[len(prefix) + 1:]
    if not rest:
        return store, None
    if len(rest) >= 2 and rest[0] == "snapshots" and rest[1]:
        return store, rest[1]
    return None


def verify_snapshot(store: pathlib.Path, ident: str | None) -> tuple[str, pathlib.Path]:
    """(snapshot id, data folder) once `shared_snapshot.py` has checked the snapshot's
    files against its manifest: the store's current one, or the one named.
    ValueError, saying why, when it does not verify."""
    module = starter_script("shared_snapshot")
    if module is None:
        raise ValueError(f"{store} is a snapshot store, and scripts/shared_snapshot.py is not in "
                         "this project to verify it")
    try:
        found = (module.snapshot(pathlib.Path(store).resolve(), ident) if ident
                 else module.verify_store(pathlib.Path(store)))
    except (module.SnapshotError, OSError, ValueError) as exc:
        raise ValueError(f"the snapshot in {store} does not verify ({exc}); take a new one with "
                         "scripts/shared_folder.py snapshot") from None
    return found["snapshot"], pathlib.Path(found["data"])


def incoming_folder() -> str:
    """Where outside material waits for a decision, relative to the project root, as
    `shared_folder.py` reads it: `incoming_root` in ai/project.json, else incoming/
    inside the shared folder (rc22)."""
    module = starter_script("shared_folder")
    return module.incoming_path(pathlib.Path(".")) if module else "workspace/shared/incoming"


def named_sources(paths: list[str]) -> list[dict]:
    """`sources` for the paths a check names: each file here with its sha256, and
    anything that is not a file here by name alone.

    A path in a snapshot store is checked against the snapshot's manifest as
    `agentic_review.py --source` checks it: the store stands for its current
    snapshot, any path inside a snapshot's folder for that snapshot, and the entry names
    the snapshot it verified. One that does not verify is recorded, with the
    reason in `snapshot_unverified`, rather than refused: the check happened, and
    the row says what its source was.
    """
    out = []
    for name in paths:
        name = name.strip()
        if not name:
            continue
        path = pathlib.Path(name)
        entry = {"path": name}
        if path.is_file():
            entry["sha256"] = sha256_file(path)
        rel = name.replace("\\", "/").removeprefix("./")
        if path.is_absolute():
            try:
                rel = path.resolve().relative_to(pathlib.Path(".").resolve()).as_posix()
            except ValueError:
                rel = ""
        parts = snapshot_parts(rel) if rel else None
        if parts and (parts[1] or (path / "current.json").is_file()):
            try:
                entry["snapshot"] = verify_snapshot(pathlib.Path(parts[0]), parts[1])[0]
            except ValueError as exc:
                entry["snapshot_unverified"] = str(exc)
        out.append(entry)
    return out


def draft_check(args: argparse.Namespace) -> dict:
    """A check row from what the checker said. Nothing is inferred: a field the
    checker did not state reads `not stated`, and the words are kept verbatim."""
    person = bool(args.person)
    by = (args.by or "").strip() or (git("config", "user.name").strip() if person else "")
    say = lambda v: (v or "").strip() or CHECK_NOT_STATED  # noqa: E731
    recorder = (args.recorded_by or "").strip()
    runner = f"{by} ({'person' if person else 'model, advisory'})"
    if recorder:
        runner += f", recorded by {recorder}"
    artifact = (args.artifact or "").strip()
    row = {"kind": (args.kind or "").strip() or ("person-check" if person else "agent-check"),
           "runner": runner, "method": say(args.examined), "result": say(args.result),
           "artifact": artifact or "the checker's words, kept in this row",
           "reference": "path" if artifact else "declared",
           "candidate": say(args.candidate), "criterion": say(args.criterion),
           "limits": say(args.limits),
           "checker": by, "checker_kind": "human" if person else "model"}
    if recorder:
        row["recorded_by"] = recorder
    if args.source:
        row["sources"] = named_sources(args.source)
    if args.said:
        row["words"] = {"checker_said": args.said, "kept": "verbatim, as said to the recorder"}
    return row


def cmd_check(args: argparse.Namespace) -> int:
    """Record a check a person, or an agent, says they made: drafted from their own
    words, printed back field by field, and appended only with --confirm.

    A and E already record a person's words through the agent (`accept --words`,
    `defect_ledger.py draft-recheck --said`); R had no such command, so a person's
    check left only free text in `runner` (rc22).
    """
    if bool(args.person) == bool(args.agent):
        print("declare the checker's kind: --person or --agent (one of them)", file=sys.stderr)
        return 2
    row = draft_check(args)
    if not row["checker"]:
        print("name the checker with --by", file=sys.stderr)
        return 2
    target = pathlib.Path(args.checks_jsonl) if args.checks_jsonl else None
    print(f"{'check row' if args.confirm else 'draft check row, to confirm before it is recorded'}")
    for label, key in (("candidate", "candidate"), ("criterion", "criterion"),
                       ("examined", "method"), ("result", "result"), ("limits", "limits")):
        print(f"  {label:<10}: {row[key]}")
    print(f"  {'sources':<10}: {', '.join(check_sources(row)) or 'none named'}")
    if any(entry.get("snapshot_unverified") for entry in row.get("sources") or []):
        print(f"  {'':<10}  a snapshot named as a source did not verify against its manifest; the "
              "row says why and is recorded as-is")
    print(f"  {'checker':<10}: {row['checker']} ({row['checker_kind']})"
          + (f", recorded by {row['recorded_by']}" if row.get("recorded_by") else ""))
    print(f"  {'artifact':<10}: {row['artifact']} ({row['reference']})")
    if args.said:
        print(f"  {'said':<10}: {args.said}")
    if not args.confirm:
        where = target or "the record's checks.jsonl, named with --checks-jsonl"
        print(f"\nNothing is written. Read it back to the checker; when they confirm, run the same "
              f"command with --confirm to append it to {where}.")
        print("A field that reads 'not stated' is recorded that way; nobody is asked for more "
              "than they said.")
        return 0
    if target is None:
        print("--confirm appends to a trace record's checks.jsonl: name it with --checks-jsonl",
              file=sys.stderr)
        return 2
    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("a", encoding="utf-8", newline="\n") as handle:
        handle.write(json.dumps(row, ensure_ascii=False) + "\n")
    print(f"\nrecorded: appended to {target}"
          + ("; a model's check is advisory" if not args.person else ""))
    return 0


def skill_file(name: str, root: pathlib.Path | None = None) -> pathlib.Path | None:
    """Where a project keeps a named skill, in either shape it uses."""
    if not isinstance(name, str) or not SKILL_NAME_RE.fullmatch(name):
        return None
    base = pathlib.Path(root or ".") / ".skills"
    for candidate in (base / name / "SKILL.md", base / f"{name}.md"):
        if candidate.is_file():
            return candidate
    return None


def procedure_text_version(name: str, root: pathlib.Path | None = None) -> str | None:
    """The procedure version derivable from a skill file this project holds now.

    A hand-typed version number says only that somebody typed it. This reads the
    version off the text instead, which is what a check row should record at the
    time it runs.
    """
    path = skill_file(name, root)
    return None if path is None else "sha256:" + sha256_file(path)


def recorded_procedure_digest(evidence: dict, name: str) -> tuple[str | None, str | None]:
    """The digest this record itself kept for that procedure's file, and its path.

    `extract` writes the digest of every `.skills/**/*.md` file as it stood when
    the turns were captured, so that is what a version claim is checked against,
    not the working tree. A skill edited after a run must not retroactively
    contradict a record made under the earlier text; equally, a row claiming a
    digest the same record's own provenance contradicts is a record at odds with
    itself, which is worth reporting.

    Returns (None, None) when the record holds no digest for that name, which is
    the ordinary case for a globally installed procedure outside `.skills/`.
    """
    if not isinstance(name, str) or not SKILL_NAME_RE.fullmatch(name):
        return None, None
    files = (evidence.get("instructions") or {}).get("files") or {}
    for shape in (f".skills/{name}/SKILL.md", f".skills/{name}.md"):
        if isinstance(files.get(shape), str):
            return files[shape], shape
    return None, None


def earlier_procedure_digests(evidence: dict, name: str) -> list[str]:
    """The digests the record kept for that procedure's file before a refresh.

    A refresh of the staging record recomputes the instruction digests; when
    they changed, the earlier sets stay in `instructions_earlier` (rc23), so a
    check row written under the skill as it stood earlier in the session still
    matches the record's own provenance.
    """
    if not isinstance(name, str) or not SKILL_NAME_RE.fullmatch(name):
        return []
    found = []
    for earlier in evidence.get("instructions_earlier") or []:
        files = (earlier.get("files") or {}) if isinstance(earlier, dict) else {}
        for shape in (f".skills/{name}/SKILL.md", f".skills/{name}.md"):
            if isinstance(files.get(shape), str):
                found.append(files[shape])
    return found


def ledger_ids() -> set[str] | None:
    """Every id the project's defect ledger holds, or None when there is none.

    `STABLE_ID_RE` accepts any `PREFIX-000` shape, so it accepts an audit's
    internal `CLM-001` as readily as a ledger's `AH-031`. The shape is not the
    claim: the claim is that the id names a defect somebody can look up. This
    reads the ledger so that claim can be checked, and returns None rather than
    an empty set when the project has no ledger, because "nothing is recorded
    there" and "there is nowhere to record it" are different states.
    """
    from defect_ledger import ledger_path
    path = ledger_path()
    if not path.is_file():
        return None
    found = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict) and isinstance(row.get("id"), str):
            found.add(row["id"])
    return found


