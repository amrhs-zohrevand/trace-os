def resolve_artifact(artifact: str, reference: str | None = None,
                     record: pathlib.Path | None = None) -> str:
    """Where a check row's artifact reference leads.

      resolved     a file or directory at that path exists
      declared     the row says the reference is not a file, or it reads as
                   prose or a URL rather than a path
      unavailable  a path under an ignored or untracked location (a shared
                   archive, a temporary review directory), so this checkout
                   cannot see it
      nonexistent  reads as a path in this tree and nothing is there

    A resolved artifact shows that the referenced thing exists. It does not show
    that the check examined the intended candidate against an adequate criterion.
    """
    text = artifact.strip()
    if reference == "declared":
        return "declared"
    explicit_path = reference == "path"
    if not text:
        return "nonexistent" if explicit_path else "declared"
    if not explicit_path and text.startswith(("http://", "https://")):
        return "declared"
    # Explicit paths are literal, including spaces and punctuation. Heuristics
    # remain for legacy references that did not declare whether they were files.
    head = text if explicit_path else re.split(r"[\s#(,;]", text, maxsplit=1)[0]
    if not explicit_path and (not PATHLIKE_RE.match(head) or ("/" not in head and "." not in head)):
        return "declared"
    path = pathlib.Path(head.rstrip("/"))
    if path.exists() or (record is not None and (pathlib.Path(record) / head).exists()):
        return "resolved"
    # A glob such as paper/sections/0*.tex resolves when it matches anything.
    if not explicit_path and any(ch in head for ch in "*?[") and list(pathlib.Path(".").glob(head)):
        return "resolved"
    # A bare name with no directory is a label ("stdout", "session.log"), not a
    # claim about a location in this tree, so it is read as declared.
    if not explicit_path and "/" not in head:
        return "declared"
    ignored = subprocess.run(["git", "check-ignore", "-q", "--", head], capture_output=True)
    if ignored.returncode == 0 or head.startswith(("workspace/shared/", ".agent-reviews/",
                                                  "workspace/record-staging/", "build/")):
        return "unavailable"
    return "nonexistent"


# --- What a decision used and what it produced -------------------------------
#
# Track records keeps, for each unit of work, the inputs and the resulting
# versions. A decision row names its resulting work in `artifacts` and, since
# 2026-10-14, what it used in the optional `inputs`. `verify` says where each
# leads, as information: a file moved or deleted since, and every row written
# before `inputs` existed, stays a valid record.

INTAKE_ID_RE = re.compile(r"^IN-[0-9]+$")


def record_commit_shas(record: pathlib.Path) -> list[str]:
    """The commits on this history whose body names the record, newest first.

    Only a record under ai/records/ is named by a commit, so a staging
    directory or a snapshot has none; outside a repository the list is empty.
    """
    key = record_key(str(record))
    if not key.startswith("ai/records/"):
        return []
    found = git("log", "-F", f"--grep={pathlib.Path(key).name}", "--format=%x1e%H%x00%B")
    shas = []
    for entry in found.split("\x1e"):
        sha, _, body = entry.strip().partition("\x00")
        if sha and key in commit_records(body):
            shas.append(sha)
    return shas


def paths_at_commits(shas: list[str], paths: list[str]) -> set[str]:
    """The paths that exist in the tree of at least one of these commits.

    Only a relative path inside the repository can be in a commit's tree; one
    outside it (`../other-repo`, `~/...`) would make git refuse the whole list.
    """
    inside = [p for p in paths if p and not p.startswith(("/", "~"))
              and ".." not in pathlib.PurePosixPath(p).parts]
    found: set[str] = set()
    for sha in shas:
        wanted = [p for p in inside if p not in found]
        if not wanted:
            break
        listed = git("--literal-pathspecs", "ls-tree", "-z", "--name-only", sha, "--", *wanted)
        found.update(name for name in listed.split("\x00") if name in wanted)
    return found


def decision_object_notes(record: pathlib.Path, decisions: list[dict]) -> list[str]:
    """Where each decision's inputs and resulting work lead, as notes for `verify`.

    A path is found in the tree or at a commit naming this record (the version
    the record produced, even when the file has moved since); an intake row in
    sources/intake.jsonl; an earlier record under ai/records/. What is found
    nowhere is counted and named, never a problem.
    """
    from collections import Counter
    from trace_story import decision_inputs

    def head(text: str) -> str:
        # The path part of a reference, as resolve_artifact reads it.
        return re.split(r"[\s#(,;]", text.strip(), maxsplit=1)[0].rstrip("/")

    artifacts = [a for entry in decisions for a in entry.get("artifacts") or []
                 if isinstance(a, str) and a.strip()]
    inputs = [i for entry in decisions for i in decision_inputs(entry)]
    intake_ids = set()
    if INTAKE.exists() and any(INTAKE_ID_RE.fullmatch(value) for value in inputs):
        for line in INTAKE.read_text(encoding="utf-8").splitlines():
            try:
                row = json.loads(line) if line.strip() else None
            except json.JSONDecodeError:
                continue
            if isinstance(row, dict) and isinstance(row.get("id"), str):
                intake_ids.add(row["id"])
    artifact_state = {a: resolve_artifact(a, None, record) for a in dict.fromkeys(artifacts)}
    input_state = {}
    for value in dict.fromkeys(inputs):
        if INTAKE_ID_RE.fullmatch(value):
            input_state[value] = "intake row" if value in intake_ids else "not found"
        elif (value.startswith("ai/records/") and not pathlib.PurePosixPath(value).suffix) or (
                "/" not in value and (pathlib.Path("ai/records") / value).is_dir()):
            input_state[value] = "earlier record" if record_path(value).is_dir() else "not found"
        else:
            input_state[value] = resolve_artifact(value, None, record)
    missing = [head(v) for v, state in {**artifact_state, **input_state}.items() if state == "nonexistent"]
    at_commits = paths_at_commits(record_commit_shas(record), missing) if missing else set()

    def named(state: str, value: str) -> str:
        if state == "resolved":
            return "in the tree"
        if state == "nonexistent":
            return "at the record's commits" if head(value) in at_commits else "not found"
        return state

    notes = []
    if artifact_state:
        counts = Counter(named(state, value) for value, state in artifact_state.items())
        notes.append(f"decision artifacts: {len(artifact_state)} named, " + ", ".join(
            f"{counts[k]} {k}" for k in ("in the tree", "at the record's commits", "declared",
                                         "unavailable", "not found")) + " (reported, never required)")
    with_inputs = sum(bool(decision_inputs(entry)) for entry in decisions)
    notes.append(f"{with_inputs} of {len(decisions)} decisions name their inputs (optional)")
    if input_state:
        counts = Counter(named(state, value) for value, state in input_state.items())
        notes.append(f"decision inputs: {len(input_state)} named, " + ", ".join(
            f"{counts[k]} {k}" for k in ("in the tree", "at the record's commits", "intake row",
                                         "earlier record", "declared", "unavailable", "not found"))
            + " (reported, never required)")
    lost = [v for v, s in {**artifact_state, **input_state}.items() if named(s, v) == "not found"]
    if lost:
        notes.append("decision artifacts or inputs not found: "
                     + ", ".join(trimmed(v, 60) for v in lost[:3])
                     + (f" and {len(lost) - 3} more" if len(lost) > 3 else ""))
    return notes


def evaluate_record(record: pathlib.Path, rev_range: str | None = None, check_publication: bool = True,
                    strict_artifacts: bool = False) -> dict:
    """Check one trace record and hand back what was found, as data.

    Split out of `cmd_verify` on 2026-09-07.
    The printed report was the only thing this produced, and the exit code was
    zero whether or not it said FAIL, so every caller that wanted to act on a
    broken record had to scrape reassuring prose.
    The findings are the structure now, and the report is rendered from it, so
    the two cannot disagree.

    Returns record (path as text), range, notes, problems, and ok.
    Mechanical only: it says nothing about whether a check was adequate.
    """
    problems, notes = [], []
    from record_privacy import safe_record_files, publication_problems
    safe_record_files(record)

    evidence = load_evidence(record)
    record_version = evidence.get("record_schema_version", 1)
    if type(record_version) is not int or record_version not in (1, 2):
        problems.append("unsupported or invalid trace record schema version")
        record_version = 1
    turns = evidence["turns"]
    notes.append(f"{len(turns)} human turns captured")
    if len({t["id"] for t in turns}) != len(turns):
        problems.append("duplicate input turn IDs")

    if evidence.get("consent", {}).get("third_party_review") != "cleared":
        problems.append("consent.third_party_review is not 'cleared'")

    redactions = sum(len(REDACTION_RE.findall(t["text"])) for t in turns)
    notes.append(f"{redactions} declared redactions")

    # Coverage: every turn accounted for, and the summary unchanged since.
    cov_path = record / "coverage.json"
    if not cov_path.exists():
        problems.append("no coverage.json; run `cover`")
    else:
        cov = json.loads(cov_path.read_text(encoding="utf-8"))
        ids = {t["id"] for t in turns}
        # A malformed entry is reported and set aside; indexing it raised a
        # KeyError out of `verify` instead (AH-145).
        listed = cov.get("turns") if isinstance(cov, dict) else None
        if not isinstance(listed, list):
            problems.append("coverage.json holds no list of turns")
            listed = []
        if not isinstance(cov, dict):
            cov = {}
        entries = []
        for n, entry in enumerate(listed, 1):
            if isinstance(entry, dict) and isinstance(entry.get("turn"), str):
                entries.append(entry)
            else:
                problems.append(f"coverage entry {n} names no turn")
        covered = {e["turn"] for e in entries}
        if ids - covered:
            problems.append(f"turns missing from coverage: {sorted(ids - covered)}")
        if covered - ids:
            problems.append(f"coverage names absent turns: {sorted(covered - ids)}")
        if len(covered) != len(entries):
            problems.append("duplicate turns in coverage")
        for entry in entries:
            if entry.get("status") not in {"summarized", "excluded", "UNCOVERED"}:
                problems.append(f"unknown coverage status for {entry['turn']}")
            if entry.get("status") == "excluded" and not str(entry.get("reason") or "").strip():
                problems.append(f"exclusion needs a reason: {entry['turn']}")
        bad = [e["turn"] for e in entries if e.get("status") == "UNCOVERED"]
        if bad:
            problems.append(f"turns neither summarized nor excluded: {bad}")
        summary_path = record / "summary.md"
        if summary_path.exists():
            summary = summary_path.read_text(encoding="utf-8")
            actual = sha256_text(summary)
            if actual != cov.get("summary_sha256"):
                problems.append("summary.md changed since coverage was built; "
                                "rerun `cover`")
            cited = {f"T{n}" for n in TURN_REF_RE.findall(summary)}
            for entry in entries:
                if entry.get("status") == "summarized" and entry["turn"] not in cited:
                    problems.append(f"summary does not cite {entry['turn']}")
        else:
            problems.append("no summary.md")
        if "evidence_sha256" in cov:
            if cov["evidence_sha256"] != sha256_text((record / "evidence.json").read_text(encoding="utf-8")):
                problems.append("evidence.json changed since coverage was built; rerun `cover`")
        else:
            notes.append("legacy coverage does not pin the captured input bytes")
        decisions_path = record / "decisions.jsonl"
        actual_decisions = sha256_text(decisions_path.read_text(encoding="utf-8")) if decisions_path.exists() else None
        if actual_decisions != cov.get("decisions_sha256"):
            if actual_decisions and "decisions_sha256" not in cov:
                problems.append("coverage does not bind decisions.jsonl; review the account and run `cover`")
            else:
                problems.append("decisions.jsonl changed since coverage was built; rerun `cover`")
        notes.append(f"{len(listed)} turns in coverage manifest")
        checks_path = record / "checks.jsonl"
        if "checks_sha256" in cov:
            actual = sha256_text(checks_path.read_text(encoding="utf-8")) if checks_path.exists() else None
            if actual != cov["checks_sha256"]:
                problems.append("checks.jsonl changed since coverage was built; rerun `cover`")

    # Checks: schema, plus where each artifact reference leads. Whether a check
    # was adequate is not verifiable here.
    checks_path = record / "checks.jsonl"
    if not checks_path.exists():
        problems.append("no checks.jsonl")
    else:
        required = {"kind", "runner", "method", "result", "artifact"}
        if record_version >= 2:
            required.update(CHECK_REQUIRED_V2)
        kinds, resolution = [], {"resolved": 0, "declared": 0, "unavailable": 0, "nonexistent": 0}
        bound = procedures = defect_links = recheck_links = sourced = 0
        derived_versions = declared_versions = unresolved_versions = 0
        known_defects = ledger_ids()
        unknown_defect_ids: list[str] = []
        for n, line in enumerate(checks_path.read_text(encoding="utf-8").splitlines(), 1):
            if not line.strip():
                continue
            try:
                entry = json.loads(line)
            except json.JSONDecodeError:
                problems.append(f"checks.jsonl line {n} is not valid JSON")
                continue
            if not isinstance(entry, dict):
                problems.append(f"checks.jsonl line {n} must be an object")
                continue
            missing = required - entry.keys()
            if missing:
                problems.append(f"checks.jsonl line {n} missing {sorted(missing)}")
            empty = [key for key in required & entry.keys()
                     if not isinstance(entry[key], str) or not entry[key].strip()]
            if empty:
                problems.append(f"checks.jsonl line {n} empty or non-text fields {sorted(empty)}")
            for key in CHECK_TEXT_OPTIONAL:
                if key in entry and (not isinstance(entry[key], str) or not entry[key].strip()):
                    problems.append(f"checks.jsonl line {n} has an empty {key}")
            for key in CHECK_LIST_OPTIONAL:
                if key in entry and (not isinstance(entry[key], list) or not entry[key]
                                     or any(not isinstance(value, str) or not value.strip()
                                            for value in entry[key])):
                    problems.append(f"checks.jsonl line {n} has invalid {key}")
            if isinstance(entry.get("defect_ids"), list):
                invalid = [value for value in entry["defect_ids"]
                           if isinstance(value, str) and not STABLE_ID_RE.fullmatch(value)]
                if invalid:
                    problems.append(f"checks.jsonl line {n} has unstable defect ids {invalid}")
            if "reference" in entry and entry["reference"] not in ("path", "declared"):
                problems.append(f"checks.jsonl line {n} reference must be 'path' or 'declared'")
            if "sources" in entry:
                for found in source_problems(entry["sources"]):
                    problems.append(f"checks.jsonl line {n}: {found}")
                if not source_problems(entry["sources"]):
                    sourced += 1
            # A field that reads `not stated` fills the slot and binds nothing.
            if check_field_stated(entry.get("candidate")) and check_field_stated(entry.get("criterion")):
                bound += 1
            if isinstance(entry.get("procedure"), str) and entry["procedure"].strip() \
                    and isinstance(entry.get("procedure_version"), str) \
                    and entry["procedure_version"].strip():
                procedures += 1
                # A `sha256:` version claims to be read off the procedure text,
                # so it is checked against the digest this record itself kept for
                # that file. Any other value is a label somebody typed, counted
                # as such rather than contradicted, which keeps older rows
                # readable; an unresolvable name is reported, not failed.
                recorded = entry["procedure_version"].strip()
                name = entry["procedure"].strip()
                actual, where = recorded_procedure_digest(evidence, name)
                if not DERIVED_VERSION_RE.fullmatch(recorded):
                    declared_versions += 1
                elif actual is None:
                    unresolved_versions += 1
                elif any(digest.startswith(recorded[len("sha256:"):])
                         for digest in [actual, *earlier_procedure_digests(evidence, name)]):
                    derived_versions += 1
                else:
                    problems.append(
                        f"checks.jsonl line {n} records procedure_version {recorded} for "
                        f"{name}, but this record's own instruction provenance digests "
                        f"{where} as sha256:{actual}")
            if isinstance(entry.get("defect_ids"), list) and entry["defect_ids"]:
                defect_links += len(entry["defect_ids"])
                if known_defects is not None:
                    missing = [value for value in entry["defect_ids"]
                               if isinstance(value, str) and value not in known_defects]
                    if missing:
                        unknown_defect_ids.extend(missing)
                        problems.append(
                            f"checks.jsonl line {n} names defect id(s) {missing} that the "
                            "project's defect ledger does not hold; open the finding with "
                            "defect_ledger.py open and carry the returned id")
            if isinstance(entry.get("recheck_evidence"), list) and entry["recheck_evidence"]:
                recheck_links += len(entry["recheck_evidence"])
            if isinstance(entry.get("artifact"), str) and entry["artifact"].strip():
                status = resolve_artifact(entry["artifact"], entry.get("reference"), record)
                resolution[status] += 1
                if status == "nonexistent" and strict_artifacts:
                    problems.append(f"checks.jsonl line {n} names an artifact that does not exist: "
                                    f"{entry['artifact'][:80]} (mark reference 'declared' if it is not a file)")
            kinds.append(str(entry.get("kind", "unknown")))
        notes.append(f"{len(kinds)} checks recorded: {', '.join(sorted(set(kinds)))}")
        notes.append(f"{bound} of {len(kinds)} checks bind a candidate and a criterion")
        notes.append(f"{sourced} of {len(kinds)} checks name the sources they compared")
        notes.append(f"{procedures} of {len(kinds)} checks name a procedure and version")
        if procedures:
            notes.append(f"procedure versions: {derived_versions} matching this record's own "
                         f"digest of the skill file, {declared_versions} declared without a "
                         f"derivable version, {unresolved_versions} not resolvable to a skill "
                         f"file this record digested")
        notes.append(f"{defect_links} defect links and {recheck_links} recheck evidence links recorded")
        if defect_links:
            notes.append("defect links resolved against the project ledger"
                         if known_defects is not None and not unknown_defect_ids else
                         "defect links not resolvable: this project has no defect ledger"
                         if known_defects is None else
                         f"{len(unknown_defect_ids)} defect link(s) name no ledger row")
        notes.append("artifacts: " + ", ".join(f"{v} {k}" for k, v in resolution.items()))

    from trace_story import load_decisions, reason_stated
    from input_provenance import annotation_problems
    problems.extend(annotation_problems(evidence))
    if check_publication:
        problems.extend(publication_problems(record))
    if not (record / "publication.json").exists():
        notes.append("no file-bound disclosure review; required before a new promotion")
    try:
        decisions = load_decisions(record, evidence)
        if decisions:
            notes.append(f"{len(decisions)} evidence-linked decisions recorded")
            # Information, never a problem: rows written before the field
            # existed, and new rows nobody gave a reason, read "not stated".
            unreasoned = sum(not reason_stated(entry) for entry in decisions)
            notes.append(f"{unreasoned} of {len(decisions)} decisions state no reason "
                         "for the choice (reported, never required)")
            notes.extend(decision_object_notes(record, decisions))
    except (ValueError, OSError, KeyError, TypeError) as exc:
        problems.append(str(exc))

    # What the commit messages in the range claim. A missing trailer is a
    # count (a person typed it), never a problem.
    if rev_range:
        checked, exempt, found, untrailed = check_range(rev_range)
        for problem in found:
            problems.append(problem.split(".")[0])
        note = f"{checked} commit messages read over {rev_range}"
        if exempt:
            note += f" ({exempt} exempt, predating the rule)"
        if untrailed:
            note += f"; {untrailed} with no execution trailer, read as typed by a person"
        notes.append(note)

    return {
        "record": str(record),
        "range": rev_range,
        "notes": notes,
        "problems": problems,
        "ok": not problems,
    }


def cmd_verify(args: argparse.Namespace) -> int:
    """Report on a record. Report-only by default; `--strict` makes it fail.

    The default stays exit 0 with problems printed, because a human running this
    over the seven tracked records wants the whole picture rather than a stop at
    the first broken one.
    A caller that must not proceed on a broken record passes `--strict`, and one
    that wants to decide for itself passes `--json`.
    """
    result = evaluate_record(pathlib.Path(args.record), getattr(args, "range", None))
    strict = bool(getattr(args, "strict", False))

    if getattr(args, "json", False):
        print(json.dumps(result))
        return 1 if strict and not result["ok"] else 0

    print(f"RECORD {result['record']}")
    for note in result["notes"]:
        print(f"  ok    {note}")
    for problem in result["problems"]:
        print(f"  FAIL  {problem}")
    print()
    if result["problems"]:
        if strict:
            print(f"{len(result['problems'])} problem(s). Strict mode: exiting 1.")
            return 1
        print(f"{len(result['problems'])} problem(s). Report-only: nothing was blocked.")
    else:
        print("All mechanical checks pass. This does not prove the record is "
              "complete, the attribution honest, or the checks adequate.")
    return 0


# --- keep: the record routine in one command, before each commit ---------------
#
# rc23, 15 October 2026: the rule that an agent session which commits work
# keeps a trace record holds for every agent, and the researcher who set it
# said it cannot be optional. The routine was seven commands, and in the
# agent-parity matrix of that day the agents that skipped it were the ones
# that had to find their transcript and run the steps by hand. `keep` runs the
# steps for the running session and stops only where the agent's judgment is
# needed: a turn the summary does not account for, a missing check, and the
# disclosure read, which the agent confirms by passing back the digest `keep`
# printed. It never writes the summary, a decision or a check, never clears
# consent on its own, and never stages or commits.

KEEP_SCOPE = "this repository's collaborators, through Git"
KEEP_SESSIONS = pathlib.Path("workspace/record-staging/.sessions")
KEEP_DIGESTS = ".keep-digests.json"
KEEP_MESSAGE = "commit-message.txt"
KEEP_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$")
KEEP_CHAT_KINDS = ("chat", "question-dialog")
KEEP_NO_STOP = "Nothing here stops a commit."
KEEP_NO_RECORD = (
    "Nothing was written. Nothing here stops a commit: commit with a body that says no trace "
    "record was kept and why, with no Record: line, and an Execution-agent: line naming the "
    "model id you were told you run as, the id alone, said in the body to be self-reported.")


class KeepStop(Exception):
    """`keep` stops here with this exit code and these lines."""

    def __init__(self, code: int, *lines: str):
        super().__init__(lines[0] if lines else "")
        self.code, self.lines = code, list(lines)


def turn_span(ids) -> str:
    """Turn ids as a short list, runs of consecutive ids joined: T1 to T4, T7."""
    numbers = sorted({int(str(t)[1:]) for t in ids if re.fullmatch(r"T\d+", str(t))})
    parts, start = [], None
    for i, n in enumerate(numbers):
        if start is None:
            start = n
        if i + 1 == len(numbers) or numbers[i + 1] != n + 1:
            parts.append(f"T{start}" if start == n else f"T{start} to T{n}")
            start = None
    return ", ".join(parts) or "none"


def chat_sessions(evidence: dict) -> set[str]:
    """The transcript files a record's chat and dialog turns were captured from."""
    found = set()
    for turn in evidence.get("turns") or []:
        source = turn.get("source") if isinstance(turn, dict) else None
        if isinstance(source, dict) and source.get("kind") in KEEP_CHAT_KINDS and source.get("session"):
            found.add(source["session"])
    return found


def read_json_file(path: pathlib.Path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def records_from_transcript(name: str) -> list[str]:
    """The records, promoted or staged, holding turns captured from this transcript."""
    found = []
    for base in (pathlib.Path("ai/records"), pathlib.Path("workspace/record-staging")):
        if not base.is_dir():
            continue
        for folder in sorted(base.iterdir()):
            data = read_json_file(folder / "evidence.json") if folder.is_dir() else None
            if isinstance(data, dict) and name in chat_sessions(data) and folder.name not in found:
                found.append(folder.name)
    return found


def keep_session(args: argparse.Namespace) -> tuple[pathlib.Path, str | None, str]:
    """The transcript to keep, the model read off it as running now, and how it was found.

    The model is the latest one in the session's transcript. A subagent runs
    under its parent's session (CLAUDE_CODE_SESSION_ID), so for a subagent
    this is the parent's model, and nothing here can tell the two apart
    (AH-350): a subagent passes --execution-agent with its own model id.
    """
    found = current_session()
    if args.transcript:
        transcript = pathlib.Path(args.transcript).expanduser()
        if not transcript.is_file():
            raise KeepStop(2, f"keep: transcript not found: {transcript}", KEEP_NO_STOP)
        basis = "named with --transcript"
    elif not found["runner"]:
        if found["ambiguous"]:
            raise KeepStop(2, f"keep: which agent session runs this is ambiguous: {found['basis']} "
                              f"({', '.join(found['ambiguous'])}). Nothing was written. Pass "
                              "--transcript with the path of this session's transcript.", KEEP_NO_STOP)
        raise KeepStop(2, "keep: no supported agent session found: neither CLAUDE_CODE_SESSION_ID "
                          "nor CODEX_THREAD_ID is set, so there is no transcript to keep.", KEEP_NO_RECORD)
    elif not found["transcript"]:
        raise KeepStop(2, f"keep: the {found['runner']} session {found['session']} has no transcript "
                          "under the CLI's home (a session run without persistence keeps none).",
                       KEEP_NO_RECORD)
    else:
        transcript = pathlib.Path(found["transcript"])
        basis = f"the running {found['runner']} session; {found['basis']}"
    rows = read_transcript(transcript)
    used = codex_models_used(rows) if is_codex_rollout(rows) else models_used(rows)
    latest = max(used, key=lambda e: e["last"] or "")["model"] if used else None
    # The model running now executes the commit, as `session` reads it; the
    # kept transcript's latest model when the running session cannot be read.
    running = found["model"] if found["runner"] and found["model"] else latest
    return transcript, running, basis


def keep_record_id(args: argparse.Namespace, transcript: pathlib.Path) -> tuple[str, str]:
    """Which record this session keeps, and how that was decided."""
    if args.record_id:
        return args.record_id, "named with --record-id"
    pointer = KEEP_SESSIONS / f"{transcript.stem}.json"
    data = read_json_file(pointer) if pointer.is_file() else None
    if isinstance(data, dict) and isinstance(data.get("record_id"), str) and KEEP_ID_RE.fullmatch(data["record_id"]):
        return data["record_id"], f"the record this session kept last, as {pointer.as_posix()} says"
    found = records_from_transcript(transcript.name)
    if len(found) == 1:
        return found[0], "the one record holding turns of this session's transcript"
    if found:
        raise KeepStop(2, "keep: several records hold turns of this session's transcript ("
                          + ", ".join(found) + ") and no pointer says which one this session keeps. "
                          "Nothing was written. Pass --record-id.", KEEP_NO_STOP)
    if not args.subject:
        raise KeepStop(2, "keep: this session has no record yet. Name it with --record-id <id>, or "
                          "give --subject and keep names it from the date and the subject's words. "
                          "Nothing was written.", KEEP_NO_STOP)
    words, slug = re.findall(r"[a-z0-9]+", args.subject.lower()), ""
    for word in words:
        if len(slug) + len(word) + 1 > 48:
            break
        slug = f"{slug}-{word}" if slug else word
    record_id = f"{dt.date.today():%Y%m%d}-{slug or 'session'}"
    if (pathlib.Path("ai/records") / record_id).exists() or \
            (pathlib.Path("workspace/record-staging") / record_id / "evidence.json").exists():
        raise KeepStop(2, f"keep: a record named {record_id} exists already and holds no turn of this "
                          "session. Nothing was written. Pass --record-id with another id.", KEEP_NO_STOP)
    return record_id, "made from the date and --subject"


def keep_speaker(args: argparse.Namespace, refresh: bool, prior: dict) -> tuple[str | None, str]:
    """Who typed the turns, and the basis the record states for it."""
    if args.speaker:
        return args.speaker, "named with --speaker"
    if refresh:
        return None, (prior.get("own_turns_basis")
                      or "the speaker the earlier extraction of this transcript named, kept for its later turns")
    name = git("config", "user.name").strip()
    if not name:
        return None, "no --speaker and no git config user.name, so the speaker stays unknown"
    if MACHINE_NAMES.search(name):
        return None, (f"git config user.name ({name}) reads as a model's name, so the speaker stays "
                      "unknown; pass --speaker with the person's name")
    return name, "git config user.name in this repository, taken as the person typing since no --speaker was given"


def changed_since_promotion(dest: pathlib.Path) -> tuple[list[str], str]:
    """The files of a promoted record that differ from what its promotion bound,
    and what they were compared with.

    With a disclosure receipt, its file digests say. A record promoted before
    receipts existed is compared with the record's last commit, the newest
    commit naming it, so a hand edit committed since then is seen as well as
    one left uncommitted (AH-352). A record no commit names is compared with
    the working tree only, through the one status read `keep` makes, which
    takes no optional lock (another session may be committing); that sees an
    uncommitted change and not a committed one, and the basis says so.
    """
    from record_privacy import RECEIPT, file_hashes
    receipt = dest / RECEIPT
    if receipt.is_file():
        data = read_json_file(receipt)
        files = data.get("files") if isinstance(data, dict) else None
        if not isinstance(files, dict):
            return [f"{RECEIPT} (unreadable)"], "its disclosure receipt"
        now = file_hashes(dest)
        return (sorted(name for name in set(files) | set(now) if files.get(name) != now.get(name)),
                "the file digests of its disclosure receipt")
    shas = record_commit_shas(dest)
    if shas:
        key = record_key(str(dest))

        def text(raw: bytes | None) -> bytes | None:
            return None if raw is None else raw.replace(b"\r\n", b"\n")

        changed = []
        for name in PROMOTED_NAMES:
            shown = subprocess.run(["git", "show", f"{shas[0]}:{key}/{name}"], capture_output=True)
            then = shown.stdout if shown.returncode == 0 else None
            now = (dest / name).read_bytes() if (dest / name).is_file() else None
            if text(then) != text(now):
                changed.append(name)
        return changed, f"the record's last commit, {shas[0][:8]}"
    result = subprocess.run(["git", "--no-optional-locks", "status", "--porcelain", "--", dest.as_posix()],
                            capture_output=True, text=True, encoding="utf-8", errors="replace")
    return ([line[3:] for line in result.stdout.splitlines() if line.strip()],
            "the working tree only, since it has no disclosure receipt and no commit names it, so a "
            "change committed since its promotion is not seen")


def only_added_redactions(old: str, new: str) -> bool:
    """True when `new` is `old` with some passages replaced by [REDACTED: ...] markers."""
    pieces = re.split(r"(\[REDACTED: [^\]]+\])", new)
    pattern = "".join(re.escape(piece) if i % 2 == 0 else f"(?:{re.escape(piece)}|.+?)"
                      for i, piece in enumerate(pieces))
    return re.fullmatch(pattern, old, re.DOTALL) is not None


def nonempty_lines(path: pathlib.Path) -> list[str]:
    return [line for line in path.read_text(encoding="utf-8").splitlines() if line.strip()] \
        if path.is_file() else []


def keep_containment(promoted: pathlib.Path, staged: pathlib.Path) -> tuple[list[str], list[str]]:
    """What the promoted record holds that staging does not, and redactions staging added.

    Staging contains the promoted record when each promoted turn is there with
    its id and captured-text digest (its text changed at most by added
    redactions) and the promoted decisions and checks are the first rows of
    staging's, so promoting staging loses nothing that was committed.
    """
    held = read_json_file(promoted / "evidence.json") or {}
    staged_turns = {t.get("id"): t for t in (read_json_file(staged / "evidence.json") or {}).get("turns") or []
                    if isinstance(t, dict)}
    problems, redacted = [], []
    for turn in held.get("turns") or []:
        if not isinstance(turn, dict):
            continue
        tid, other = turn.get("id"), staged_turns.get(turn.get("id"))
        digest = lambda t: (t.get("source") or {}).get("text_sha256") or sha256_text(t.get("text") or "")  # noqa: E731
        if other is None:
            problems.append(f"{tid} is in the promoted record and not in staging")
        elif digest(other) != digest(turn):
            problems.append(f"{tid} was captured from other text in staging")
        elif other.get("text") != turn.get("text"):
            if only_added_redactions(turn.get("text") or "", other.get("text") or ""):
                redacted.append(tid)
            else:
                problems.append(f"{tid} reads differently in staging, beyond added redactions")
    for name in ("decisions.jsonl", "checks.jsonl"):
        promoted_rows, staged_rows = nonempty_lines(promoted / name), nonempty_lines(staged / name)
        if staged_rows[:len(promoted_rows)] != promoted_rows:
            problems.append(f"{name}: the promoted rows are not the first rows of staging's")
    return problems, redacted


def seed_staging(dest: pathlib.Path, staging: pathlib.Path) -> None:
    """Start staging again from the promoted record, file for file."""
    from record_privacy import safe_record_files
    safe_record_files(dest)
    safe_record_files(staging)
    for name in PROMOTED_NAMES:
        target = staging / name
        if (dest / name).is_file():
            target.write_text((dest / name).read_text(encoding="utf-8"), encoding="utf-8")
        elif target.exists():
            target.unlink()


def summarized_elsewhere(record_id: str, turns: list[dict], candidates: set[str]) -> dict[str, str]:
    """Uncited turns that another promoted record summarizes, with the checkable reason.

    The same transcript file, row and captured-text digest, cited by that
    record's summary and marked summarized in its coverage. Never a turn that
    record excludes too, and never a record that is only in staging.
    """
    wanted = {}
    for turn in turns:
        source = turn.get("source") or {}
        if turn["id"] in candidates and source.get("kind") in KEEP_CHAT_KINDS and isinstance(turn.get("row"), int):
            wanted[(source.get("session"), turn["row"], source.get("text_sha256"))] = turn["id"]
    found: dict[str, str] = {}
    base = pathlib.Path("ai/records")
    if not wanted or not base.is_dir():
        return found
    for folder in sorted(base.iterdir()):
        if folder.name == record_id or not folder.is_dir():
            continue
        evidence, coverage = read_json_file(folder / "evidence.json"), read_json_file(folder / "coverage.json")
        if not isinstance(evidence, dict) or not isinstance(coverage, dict):
            continue
        status = {e.get("turn"): e.get("status") for e in coverage.get("turns") or [] if isinstance(e, dict)}
        summary = folder / "summary.md"
        cited = {f"T{n}" for n in TURN_REF_RE.findall(summary.read_text(encoding="utf-8"))} \
            if summary.is_file() else set()
        for turn in evidence.get("turns") or []:
            if not isinstance(turn, dict):
                continue
            source = turn.get("source") or {}
            key = (source.get("session"), turn.get("row"), source.get("text_sha256"))
            mine = wanted.get(key)
            if mine and mine not in found and status.get(turn.get("id")) == "summarized" \
                    and turn.get("id") in cited:
                found[mine] = (f"summarized in ai/records/{folder.name} as {turn['id']} (the same "
                               f"transcript row {turn['row']} with the same captured-text digest)")
    return found


def keep_baseline(dest: pathlib.Path) -> dict | None:
    """What the record held at its last commit, for a body that adds only what is new."""
    shas = record_commit_shas(dest)
    if not shas:
        return None
    key = record_key(str(dest))

    def shown(name: str) -> str:
        result = subprocess.run(["git", "show", f"{shas[0]}:{key}/{name}"], capture_output=True,
                                text=True, encoding="utf-8", errors="replace")
        return result.stdout if result.returncode == 0 else ""

    from trace_story import check_identity
    try:
        turns = json.loads(shown("evidence.json") or "{}").get("turns") or []
    except ValueError:
        turns = []
    decisions = set()
