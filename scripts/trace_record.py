# Transcript rows carry role "user" for tool results and harness injections as
# well as for the person typing, so extraction is a filter, not a field lookup.
#
# Two failure modes, both found by running this on a real session:
#   - a wrapper can be PREPENDED to a real prompt (the editor's open-file notice
#     rides along with what the person typed), so dropping the row loses human
#     text. These are stripped, and whatever remains is kept.
#   - a whole row can be machine content in the user role (a skill definition
#     loaded by the harness, a slash-command echo), which no amount of stripping
#     makes human. These are dropped outright.
WRAPPERS = (
    "ide_opened_file", "ide_selection", "system-reminder",
    "local-command-caveat", "local-command-stdout",
    "command-name", "command-message", "command-args",
    # A background task reporting back arrives in the user role. On the second
    # real run (2026-09-01) it accounted for 50 of 112 "human turns".
    "task-notification",
)
# Only the run of wrappers at the row's start is the harness's. Matching them
# anywhere, and an unclosed tag up to the next `<`, cut a person's sentence
# that quoted a tag (AH-133); in the local transcripts every wrapper that was
# not quoted sat at the start and was closed.
WRAPPER_RE = re.compile(
    r"\A(?:\s*<(" + "|".join(WRAPPERS) + r")>.*?</\1>)+",
    re.DOTALL,
)
# Whole-row rejects: machine content wearing the user role. Each is read at the
# start of the row, after any wrappers, for the same reason (AH-133).
NOT_HUMAN_AT_ALL = (
    "Base directory for this skill:",   # harness loading a skill definition
    "[Request interrupted",             # interrupt marker, not typed content
    "Caveat: The messages below were generated by the user while running",
    # The summary a compaction writes is the model's prose, injected as a user
    # row; the row also carries `isCompactSummary`, checked separately.
    "This session is being continued from a previous conversation",
)
# A bare slash command is an instruction to the harness, not human direction.
BARE_COMMAND_RE = re.compile(r"^/[A-Za-z][\w:-]*$")

REDACTION_RE = re.compile(r"\[REDACTED: ([^\]]+)\]")
TURN_REF_RE = re.compile(r"\bT(\d+)\b")


# The commit-attribution rule took effect immediately after this commit
# (AGENTS.md, HN-035). Anything reachable from it is exempt: a rule cannot be
# broken before it exists, and rewriting that history would need a rebase, which
