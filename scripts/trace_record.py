@contextlib.contextmanager
def keep_lock(record_id: str):
    """One `keep` run per record at a time; O_EXCL works on every platform."""
    KEEP_SESSIONS.mkdir(parents=True, exist_ok=True)
    path = KEEP_SESSIONS / f"{record_id}.lock"
    try:
        handle = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
    except FileExistsError:
        raise KeepStop(2, f"keep: another keep run holds {path.as_posix()}. When none is running, "
                          "delete that file and run keep again.", KEEP_NO_STOP)
    try:
        os.write(handle, f"{os.getpid()} {dt.datetime.now(dt.timezone.utc).isoformat()}\n".encode())
        os.close(handle)
        yield
    finally:
        path.unlink(missing_ok=True)


def keep_run(args: argparse.Namespace, say) -> tuple[int, dict]:
    """The routine for the running session; `say` collects what is printed."""
    from record_privacy import (private_capture_target, safe_record_files, scan_record,
                                publication_problems, write_receipt, RECEIPT)
    from trace_story import draft_message, digest as story_digest, reason_stated
    api = sys.modules[__name__]
    data: dict = {}

    root = git("rev-parse", "--show-toplevel")
    if not root:
        raise KeepStop(2, "keep: not inside a Git repository.", KEEP_NO_STOP)
    if pathlib.Path.cwd().resolve() != pathlib.Path(root).resolve():
        raise KeepStop(2, f"keep: run it from the repository's top folder, {root}.", KEEP_NO_STOP)
    for tid, reason in args.exclude or []:
        if not reason.strip():
            raise KeepStop(2, f"keep: --exclude {tid} needs a reason: why the turn is left out of the "
                              "summary.", KEEP_NO_STOP)
    for tid, text, category in args.redact or []:
        if not text or not category.strip() or "]" in category:
            raise KeepStop(2, f"keep: --redact {tid} needs the exact text and a category without ']'.",
                           KEEP_NO_STOP)
    if args.subject is not None and (not args.subject.strip() or "\n" in args.subject or "\r" in args.subject):
        raise KeepStop(2, "keep: --subject must be one nonempty line.", KEEP_NO_STOP)
    if args.record_id and not KEEP_ID_RE.fullmatch(args.record_id):
        raise KeepStop(2, "keep: --record-id takes letters, digits, '.', '_' and '-' only.", KEEP_NO_STOP)

    transcript, read_model, how_found = keep_session(args)
    # An id passed with --execution-agent that the transcript does not name as
    # its latest model is the agent's own account, and keep says so wherever
    # it writes the id: the model line, the clearance, the disclosure receipt
    # and the commit body (AH-349). An id equal to the model read changes nothing.
    claimed = list(dict.fromkeys(args.execution_agent or []))
    self_reported = [agent for agent in claimed if agent != read_model]
    running = claimed[0] if claimed else read_model
    agents = claimed or ([running] if running else [])
    read_as = f"names {read_model} as its latest model" if read_model else "names no model"
    executing = None
    if running and running not in self_reported:
        executing = f"{running} (executing agent)"
        model_line = (f"{running} (the latest model in this session's transcript, for the Execution-agent: "
                      "trailer; a subagent shares its parent's session, so a subagent passes "
                      "--execution-agent with its own model id)")
    elif running:
        executing = f"{running} (executing agent, self-reported)"
        model_line = (f"{running} (self-reported with --execution-agent, and recorded as self-reported; "
                      f"this session's transcript {read_as})")
    else:
        model_line = ("not stated in the transcript; pass --execution-agent with your model id, which keep "
                      "records as self-reported")
    also = [agent for agent in self_reported if agent != running]
    if also:
        model_line += f"; also self-reported with --execution-agent: {', '.join(also)}"
    record_id, how_named = keep_record_id(args, transcript)
    staging = pathlib.Path(args.staging) if args.staging else pathlib.Path("workspace/record-staging") / record_id
    dest = pathlib.Path("ai/records") / record_id
    out = pathlib.Path(args.out) if args.out else staging / KEEP_MESSAGE
    for name, path in (("--staging", staging), ("--out", out)):
        try:
            path.resolve().relative_to(pathlib.Path(root).resolve())
        except ValueError:
            raise KeepStop(2, f"keep: {name} must be inside the repository.", KEEP_NO_STOP)
    data.update(record_id=record_id, staging=staging.as_posix(), record=dest.as_posix(),
                transcript=str(transcript), execution_agent=running, self_reported=self_reported)
    say(f"record:     {record_id} ({how_named})",
        f"transcript: {transcript} ({how_found})",
        f"model:      {model_line}")

    with keep_lock(record_id):
        # The capture check creates the staging folder, so it runs under the
        # lock: a run the lock refuses writes nothing to staging.
        try:
            private_capture_target(staging)
        except ValueError as exc:
            raise KeepStop(2, f"keep: {exc}.", KEEP_NO_STOP)
        # Section 3 of the design: staging must be this record of this session,
        # and a promoted record is updated only from a staging copy that holds
        # everything it holds.
        staged = read_json_file(staging / "evidence.json") if (staging / "evidence.json").exists() else None
        if staged is not None:
            if not isinstance(staged, dict) or staged.get("record_id") != record_id:
                other = staged.get("record_id") if isinstance(staged, dict) else "an unreadable record"
                raise KeepStop(2, f"keep: {staging.as_posix()} holds the record {other}, not {record_id}. "
                                  "Nothing was changed. Pass --staging with a folder of this record.",
                               KEEP_NO_STOP)
            others = chat_sessions(staged) - {transcript.name}
            if others:
                raise KeepStop(2, f"keep: {staging.as_posix()} holds turns of another session's "
                                  f"transcript ({', '.join(sorted(others))}), not of this one "
                                  f"({transcript.name}). Nothing was changed. Pass another --record-id.",
                               KEEP_NO_STOP)
        promoted = (dest / "evidence.json").is_file()
        if promoted:
            safe_record_files(dest)
            others = chat_sessions(read_json_file(dest / "evidence.json") or {}) - {transcript.name}
            if others:
                raise KeepStop(2, f"keep: {dest.as_posix()} holds turns of another session's transcript "
                                  f"({', '.join(sorted(others))}), not of this one ({transcript.name}). "
                                  "Nothing was changed. Pass another --record-id.", KEEP_NO_STOP)
            changed, compared = changed_since_promotion(dest)
            if changed and not args.reseed:
                raise KeepStop(2, f"keep: {dest.as_posix()} changed after its promotion ("
                                  + ", ".join(changed) + f"), compared with {compared}; keep does not "
                                  "overwrite it. Nothing was "
                                  f"changed. Bring the change into {staging.as_posix()} and run keep "
                                  "again, or pass --reseed to start staging again from the promoted "
                                  "record.", KEEP_NO_STOP)
            empty = not any((staging / name).exists() for name in PROMOTED_NAMES)
            if empty or args.reseed:
                seed_staging(dest, staging)
                say(f"staging:    started from {dest.as_posix()}"
                    + (" (--reseed)" if args.reseed and not empty else ", as staging held no record"))
            problems, _ = keep_containment(dest, staging)
            if problems:
                raise KeepStop(2, f"keep: {dest.as_posix()} holds what {staging.as_posix()} does not: "
                                  + "; ".join(problems) + ". Nothing was changed. Bring it into staging, "
                                  "or pass --reseed to start staging again from the promoted record.",
                               KEEP_NO_STOP)
        baseline = keep_baseline(dest) if promoted else None

        prior = read_json_file(staging / "evidence.json") if (staging / "evidence.json").exists() else None
        prior_consent = (prior.get("consent") or {}) if isinstance(prior, dict) else {}
        speaker, speaker_basis = keep_speaker(args, isinstance(prior, dict), prior_consent)
        try:
            extracted = extract_into(transcript, staging, record_id, speaker)
        except RecordRefused as exc:
            raise KeepStop(2, f"keep: {exc}.", KEEP_NO_STOP)
        KEEP_SESSIONS.mkdir(parents=True, exist_ok=True)
        (KEEP_SESSIONS / f"{transcript.stem}.json").write_text(json.dumps(
            {"record_id": record_id, "transcript": transcript.name,
             "at": dt.datetime.now(dt.timezone.utc).isoformat()}, indent=2) + "\n",
            encoding="utf-8", newline="\n")
        evidence = extracted["evidence"]
        consent = {"own_turns_by": evidence["consent"]["own_turns_by"], "own_turns_basis": speaker_basis,
                   "third_party_review": "PENDING"}
        # The last clearance stays named, so it carries over while the turns it
        # read are the turns captured now.
        for field in ("cleared_by", "cleared_at", "cleared_digest"):
            if prior_consent.get(field):
                consent[field] = prior_consent[field]
        evidence["consent"] = consent
        evidence_path = staging / "evidence.json"

        def write_evidence() -> None:
            evidence_path.write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

        # Written at once, so a stop later in this run keeps the last clearance named.
        write_evidence()
        ids = {t["id"] for t in evidence["turns"]}
        say(f"staging:    {staging.as_posix()}: {len(evidence['turns'])} human turns"
            + (f", {turn_span(extracted['added'])} added" if extracted["added"] else ", none added"),
            f"speaker:    {consent['own_turns_by']} ({speaker_basis})")

        for tid, _text, _category in args.redact or []:
            if tid not in ids:
                raise KeepStop(2, f"keep: --redact names {tid}, which this record does not hold.", KEEP_NO_STOP)
        for tid, _reason in args.exclude or []:
            if tid not in ids:
                raise KeepStop(2, f"keep: --exclude names {tid}, which this record does not hold.", KEEP_NO_STOP)
        turns = {t["id"]: t for t in evidence["turns"]}
        for tid, text, category in args.redact or []:
            turn, marker = turns[tid], f"[REDACTED: {category.strip()}]"
            count = turn["text"].count(text)
            if count == 1:
                turn["text"] = turn["text"].replace(text, marker)
                say(f"redacted:   one passage of {tid} now reads {marker}")
                annotation = turn.get("annotation")
                if isinstance(annotation, dict) and annotation.get("text_sha256") != sha256_text(turn["text"]):
                    say(f"            the annotation of {tid} no longer matches its text: annotate it again "
                        "(annotate-input)")
            elif count == 0 and marker in turn["text"]:
                say(f"redacted:   {tid} already reads {marker}; nothing replaced")
            elif count == 0:
                raise KeepStop(2, f"keep: --redact {tid}: that text is not in the turn; give it exactly as "
                                  "captured.", KEEP_NO_STOP)
            else:
                raise KeepStop(2, f"keep: --redact {tid}: that text occurs {count} times in the turn; give "
                                  "a passage that occurs once.", KEEP_NO_STOP)
        write_evidence()
        if promoted:
            _, redacted = keep_containment(dest, staging)
            for tid in redacted:
                say(f"            {tid} is redacted in staging; its earlier text stays in Git history")

        # Consent (design section 4): cleared only on the agent's declaration,
        # the digest of the turns as they are now, and a clean local screen.
        digest = story_digest(evidence["turns"])[:16]
        per_turn = {t["id"]: story_digest(t)[:16] for t in evidence["turns"]}
        memory = keep_digests(staging)
        memory["printed"][digest] = per_turn
        while len(memory["printed"]) > 50:
            memory["printed"].pop(next(iter(memory["printed"])))
        (staging / KEEP_DIGESTS).write_text(json.dumps(memory, indent=1) + "\n", encoding="utf-8", newline="\n")
        findings = scan_record(staging)
        data["digest"] = digest
        say(f"digest:     {digest} (of the captured turns, after this run's refresh and redactions)")
        if args.cleared and args.cleared == digest and not findings:
            consent.update(third_party_review="cleared", cleared_digest=digest,
                           cleared_at=dt.datetime.now(dt.timezone.utc).isoformat(),
                           cleared_by=args.by or executing or "the executing agent, model id not stated")
            say(f"consent:    cleared by {consent['cleared_by']}, who declared reading the turns of digest "
                f"{digest}")
        elif not args.cleared and consent.get("cleared_digest") == digest and not findings:
            consent["third_party_review"] = "cleared"
            say(f"consent:    carries over: the captured turns are the ones {consent.get('cleared_by')} "
                f"cleared at {consent.get('cleared_at')} (digest {digest})")
        evidence["consent"] = consent
        write_evidence()
        missing: list[str] = []
        if consent["third_party_review"] != "cleared":
            if findings:
                places = sorted({f"{f['file']} ({f['category']})" for f in findings})
                reason = ("the local screen found possible sensitive content: " + ", ".join(places)
                          + "; inspect it locally and redact it (--redact)")
            else:
                base, since = None, ""
                if args.cleared and args.cleared in memory["printed"]:
                    base, since = memory["printed"][args.cleared], f" since digest {args.cleared}"
                elif consent.get("cleared_digest") in memory["printed"]:
                    base, since = memory["printed"][consent["cleared_digest"]], " since the last clearance"
                unread = [tid for tid, value in per_turn.items() if base is None or base.get(tid) != value]
                reason = (f"read {'every turn' if base is None else 'the turns added or changed' + since} "
                          f"({turn_span(unread)}) and every metadata field of {evidence_path.as_posix()}, "
                          "redact what may not be shared (--redact <turn> \"<text>\" <category>), then run "
                          f"keep again with --cleared {digest}")
                if args.cleared and args.cleared != digest:
                    reason = (f"the digest passed, {args.cleared}, is not the digest of the turns now, "
                              f"{digest}; " + reason)
            missing.append(f"consent is pending: {reason}")
            say("consent:    pending (never cleared without --cleared and the digest above)")
        data["consent"] = consent["third_party_review"]

        # Coverage (design section 2): the agent's exclusions, and the checkable
        # one keep makes itself; every other uncited turn stays uncovered.
        summary_path = staging / "summary.md"
        summary = summary_path.read_text(encoding="utf-8") if summary_path.exists() else ""
        cited = {f"T{n}" for n in TURN_REF_RE.findall(summary)}
        explicit = {tid: reason.strip() for tid, reason in args.exclude or []}
        existing = read_json_file(staging / "coverage.json") or {}
        held = {e.get("turn") for e in existing.get("turns") or []
                if isinstance(e, dict) and e.get("status") == "excluded" and e.get("reason")}
        candidates = ids - cited - held - set(explicit)
        automatic = summarized_elsewhere(record_id, evidence["turns"], candidates)
        entries, uncovered = build_coverage(staging, {**automatic, **explicit})
        say(f"coverage:   {len(entries) - len(uncovered)} of {len(entries)} turns covered")
        for entry in entries:
            if entry.get("status") == "excluded":
                say(f"  excluded  {entry['turn']}: {entry.get('reason')}")
        decisions = record_rows(staging, "decisions.jsonl")
        if uncovered:
            directed = {}
            for row in decisions:
                for ref in row.get("human_inputs") or []:
                    directed.setdefault(ref, []).append(str(row.get("id")))
            named = [f"{tid} (a human input of {', '.join(directed[tid])})" if tid in directed else tid
                     for tid in uncovered]
            missing.append("turns neither cited in summary.md nor excluded: " + ", ".join(named)
                           + ". Cite each in summary.md, or run keep with --exclude <turn> \"<reason>\"")
        if not summary_path.exists():
            missing.append(f"no summary.md: write {summary_path.as_posix()}, citing the turn ids each "
                           "entry rests on")
        if not (staging / "checks.jsonl").exists():
            missing.append("no checks.jsonl: record each check that ran, for example python3 "
                           "scripts/trace_record.py check --agent --by <model> --candidate \"...\" "
                           "--criterion \"...\" --examined \"...\" --result \"...\" --limits \"...\" "
                           f"--checks-jsonl {(staging / 'checks.jsonl').as_posix()} --confirm")
        new_decisions = [row for row in decisions if not baseline or row.get("id") not in baseline["decisions"]]
        say(f"decisions:  {len(decisions)} rows, {sum(not reason_stated(r) for r in decisions)} stating no "
            f"reason, {len(new_decisions)} new since the record's last commit (reported, never required)")
        explained = ("consent.third_party_review is not 'cleared'", "turns neither summarized nor excluded",
                     "no summary.md", "no checks.jsonl")
        result = evaluate_record(staging, check_publication=False, strict_artifacts=True)
        missing += [p for p in dict.fromkeys(result["problems"]) if not p.startswith(explained)]
        if consent["third_party_review"] == "cleared" and findings:
            missing.append("the local screen found possible sensitive content: "
                           + ", ".join(sorted({f"{f['file']} ({f['category']})" for f in findings})))
        if args.subject and not agents:
            missing.append("no model is stated in the transcript yet: pass --execution-agent with the model "
                           "id you were told you run as, the id alone; keep records it as self-reported")
        data["missing"] = missing
        if missing:
            say(f"\nStaged in {staging.as_posix()}; nothing was promoted. Missing:")
            say(*(f"  - {item}" for item in missing))
            say(f"{KEEP_NO_STOP} Do what is listed and run keep again, or commit with a body that says "
                "why no record was kept.")
            return 1, data

        by = args.by or executing or "the executing agent"
        config = project_config() or {}
        scope = args.scope or (config.get("record_scope") if isinstance(config.get("record_scope"), str)
                               and config["record_scope"].strip() else KEEP_SCOPE)
        if publication_problems(staging, required=True):
            try:
                write_receipt(api, staging, by, scope)
            except ValueError as exc:
                raise KeepStop(1, f"keep: the disclosure review was not recorded: {exc}. Nothing was "
                                  "promoted.", KEEP_NO_STOP)
            say(f"review:     disclosure review recorded by {by}, for {scope}")
        else:
            receipt = read_json_file(staging / RECEIPT) or {}
            say(f"review:     the files are unchanged since the disclosure review by {receipt.get('by')} "
                f"at {receipt.get('at')}")

        def guard(snapshot: pathlib.Path) -> None:
            if promoted:
                problems, _ = keep_containment(dest, snapshot)
                if problems:
                    raise PromotionRefused("the promoted record holds what the snapshot does not: "
                                           + "; ".join(problems))

        try:
            promote_record(staging, dest, force=promoted, guard=guard)
        except (RecordRefused, ValueError) as exc:
            raise KeepStop(2, f"keep: promotion refused: {exc}", KEEP_NO_STOP)
        checked = evaluate_record(dest)
        if not checked["ok"]:
            say(f"verify:     {dest.as_posix()} was promoted, and verify reports: "
                + "; ".join(checked["problems"]))
            return 1, data
        say(f"verify:     {dest.as_posix()}: all mechanical checks pass")

        if not args.subject:
            say("\nKept. No commit body drafted: run keep again with --subject \"<the commit's subject>\".",
                "keep stages and commits nothing.")
            return 0, data
        notes = []
        if self_reported:
            several = len(self_reported) > 1
            notes.append(f"The Execution-agent id{'s' if several else ''} {', '.join(self_reported)} "
                         f"{'are' if several else 'is'} self-reported: passed with --execution-agent, "
                         f"while this session's transcript {read_as}.")
        try:
            draft_message(api, dest, args.subject, out, agents, baseline, notes=notes)
        except ValueError as exc:
            raise KeepStop(1, f"keep: {dest.as_posix()} is kept; the commit body was not drafted: {exc}.",
                           KEEP_NO_STOP)
        data["commit_message"] = out.as_posix()
        say(f"body:       {out.as_posix()}"
            + (f" (what is new since {baseline['commits'][0][:8]}, the record's last commit)" if baseline else ""),
            "\nKept. Read the body, then commit the record with the work it records:",
            f"  git add {dest.as_posix()} <the files this commit changes>",
            f"  git commit --file {out.as_posix()}",
            "keep stages and commits nothing.")
        return 0, data


def cmd_keep(args: argparse.Namespace) -> int:
    """Keep the running session's trace record before a commit, in one command.

    Exit 0: kept, and the commit body drafted when --subject is given. Exit 1:
    staged, with what is missing named and nothing promoted, or promoted when
    verify reports a problem or the body is not drafted, as the output says.
    Exit 2: refused,
    or a usage error. No exit stops a commit; keep never stages or commits.
    """
    lines: list[str] = []
    try:
        code, data = keep_run(args, lambda *more: lines.extend(more))
    except KeepStop as stop:
        code, data = stop.code, {}
        lines.extend(stop.lines)
    if args.json:
        print(json.dumps({"exit": code, **data, "messages": lines}, indent=2, ensure_ascii=False))
    else:
        print("\n".join(lines))
    return code


