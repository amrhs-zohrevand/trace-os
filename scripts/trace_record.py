def brief_group(path: str, watched: tuple[str, ...]) -> str:
    """Which of the five groups a changed file belongs to; the manuscript is its
    own group, apart from the standing instructions (rc22)."""
    if is_manuscript(path):
        return "manuscript"
    if any(path == p.rstrip("/") or path.startswith(p) for p in watched):
        return "instructions"
    if path.startswith(("ai/records/", "sources/intake.jsonl",
                        "sources/transitions.jsonl", "ai/defects.jsonl")):
        return "records"
    if path.startswith(("scripts/", "tests/")) or path.endswith((".py", ".sh")):
        return "code"
    return "docs"


def brief_changes(shas: list[str], watched: tuple[str, ...]) -> tuple[dict, int]:
    """Added and removed lines per file, grouped, from `git log --numstat`."""
    files: dict[str, list[int]] = {}
    for start in range(0, len(shas), 200):
        chunk = shas[start:start + 200]
        for line in git("log", "--no-walk=unsorted", "--format=", "--numstat",
                        *chunk, check=True).splitlines():
            parts = line.split("\t")
            if len(parts) != 3:
                continue
            added, removed, path = parts
            entry = files.setdefault(path, [0, 0])
            entry[0] += int(added) if added.isdigit() else 0
            entry[1] += int(removed) if removed.isdigit() else 0
    grouped: dict[str, list[tuple[str, int, int]]] = {}
    for path, (added, removed) in sorted(files.items()):
        grouped.setdefault(brief_group(path, watched), []).append((path, added, removed))
    return grouped, len(files)


def brief_added_lines(shas: list[str], paths: list[str], cap: int = 40) -> tuple[list[str], int]:
    """The lines these commits added to the given files (the instruction files,
    or the manuscript), capped.

    A person accepting a change to a standing instruction is being asked about
    the words themselves, so the words are here rather than a file name.
    """
    if not paths:
        return [], 0
    added = []
    for start in range(0, len(shas), 200):
        chunk = shas[start:start + 200]
        diff = git("log", "--no-walk=unsorted", "--format=", "-p", "--unified=0",
                   *chunk, "--", *paths, check=True)
        for line in diff.splitlines():
            if line.startswith("+") and not line.startswith("+++") and line[1:].strip():
                added.append(line[1:].rstrip())
    return added[:cap], max(0, len(added) - cap)


def check_checker(row: dict) -> str:
    """Who made a check, as its row says: the checker and their kind for a row
    `check` wrote, with who recorded it; otherwise the row's runner."""
    checker = row.get("checker")
    if isinstance(checker, str) and checker.strip():
        kind = {"human": "person", "model": "model, advisory"}.get(row.get("checker_kind"), "kind not stated")
        said = f"{checker.strip()} ({kind})"
        if row.get("recorded_by"):
            said += f", recorded by {row['recorded_by']}"
        return said
    return str(row.get("runner") or "not stated")


def brief_wrapped(label: str, text: str, indent: int = 6, width: int = 110) -> list[str]:
    """`label: text` in full, wrapped under the label, for a field a cut would
    hide: a choice's reason, or the file names a check compared with (rc22; the
    reason was cut at 110 characters and the sources at 100)."""
    import textwrap
    lead = " " * indent + f"{label}: "
    return textwrap.wrap(" ".join(str(text).split()), width=width, initial_indent=lead,
                         subsequent_indent=" " * len(lead), break_on_hyphens=False,
                         break_long_words=False) or [lead.rstrip()]


def brief_lines(record: str, limit_turns: int = 8, limit_choices: int = 6,
                limit_checks: int = 6, limit_files: int = 4) -> list[str]:
    """One trace record on one screen. Every line comes from the record or from git."""
    path = record_path(record)
    identifier = path.name
    index = review_index()
    shas = record_commits(str(path))
    turns = record_turns(path)
    decisions = record_rows(path, "decisions.jsonl")
    checks = record_rows(path, "checks.jsonl")
    watched = queue_paths()
    rows = _log_rows(shas, with_files=True)
    states = {sha: commit_state(sha, index) for sha in shas}
    accepted = sum(1 for state in states.values() if state == "accepted")
    # The label and the decision cells come from the commits nobody has
    # accepted, the set `queue` reads, so the brief opens with the queue's
    # row (AH-143: an accepted change to AGENTS.md made the brief say `needs
    # you` beside a queue row saying `routine`). CHANGES and the COMMANDS
    # line keep the whole record, which is what `accept --record` covers.
    pending = [row for row in rows if states.get(row["commit"]) != "accepted"]
    if pending:
        label, reasons = queue_label(path, pending)
    elif rows:
        label, reasons = "nothing waiting", ["every commit naming this record is accepted, "
                                             "so it is not in the queue"]
    else:
        label, reasons = "routine", ["no commit names this record"]
    cells = pending or rows

    out = [f"{identifier}    {len(shas)} commit(s), {accepted} accepted, "
           f"{len(pending)} awaiting a decision    {label}",
           f"  {path}    {'; '.join(reasons)}"]
    bound = ""
    if shas:
        # The version this brief shows, in a line the agent can read back to
        # the person; a decision recorded with --through it covers these
        # commits and none that lands after the person read them.
        bound, merged = version_bound(shas)
        if merged:
            out.append(f"  version:  covers {len(shas)} commit(s) through {bound[:12]}, the commit "
                       "checked out, because the record's commits sit on more than one line of history")
        else:
            subject = next((row["subject"] for row in rows if row["commit"] == bound), "")
            out.append(f"  version:  covers {len(shas)} commit(s) through {bound[:12]}, "
                       f"\"{trimmed(subject, 60)}\", the newest naming this record")
    out.append("")
    if not path.is_dir():
        out.append(f"  {path} is not in this tree; what follows comes from git alone.")
        out.append("")

    over = (f"the {len(pending)} commit(s) awaiting a decision, as queue reads them" if pending
            else f"all {len(rows)} commit(s)")
    out.append(f"THE DECISION  (three sentences from the record, git and the registries, over {over})")
    out.append(f"  decide:    {decision_sentence(path, cells)}")
    out.append(f"  hangs on:  {hangs_on_sentence(path, cells, reasons, label)}")
    out.append(f"  agent:     {agent_choices_sentence(path)}")
    out.append(f"  from:      {origin_sentence(turns, cells, (path / 'evidence.json').exists(), decisions, path)}")
    out.append(f"  owners:    {owners_text(*record_owners(path))}")
    out.append("")

    out.append(f"YOUR WORDS  ({len(turns)} turn(s), verbatim in {path}/evidence.json)")
    if not turns:
        out.append("  none recorded")
    for turn in turns[:limit_turns]:
        speaker = turn.get("speaker", "unknown")
        out.append(f'  {turn.get("id", "?")} {speaker}: "{trimmed(turn.get("text", ""), 200)}"')
    if len(turns) > limit_turns:
        out.append(f"  ... and {len(turns) - limit_turns} more turn(s) in evidence.json")
    out.append("")

    out.append(f"CHOICES  ({len(decisions)} recorded in {path}/decisions.jsonl)")
    if not decisions:
        out.append("  none recorded")
    from trace_story import decision_inputs, decision_reason, human_direction
    seen_direction = {}
    for n, row in enumerate(decisions[:limit_choices], 1):
        selector = row.get("selected_by") or {}
        who = selector.get("name", "unknown") if isinstance(selector, dict) else str(selector)
        kind = selector.get("kind", "unknown") if isinstance(selector, dict) else "unknown"
        out.append(f"  D{n} {trimmed(row.get('question', '(no question recorded)'), 100)}")
        out.append(f"      chose: {trimmed(row.get('choice', '(no choice recorded)'), 100)}")
        out.append(f"      {row.get('status', 'unknown')} by {who} ({kind})")
        # The selector's reason for the choice, as the row states it, in full; a
        # row written before the field existed, or with none given, says so.
        out.extend(brief_wrapped("reason", decision_reason(row)))
        # What the choice used, when the row names it (optional since
        # 2026-10-14); a row naming none adds no line to the screen.
        if decision_inputs(row):
            out.append(f"      inputs: {trimmed(', '.join(decision_inputs(row)), 110)}")
        # The human direction the choice answers is not its reason, so it
        # carries its own label (it read "why:" until 2026-10-14). A row
        # citing no human input shows the authority it was taken under.
        direction = human_direction(row)
        label, text = ("direction", direction) if direction else ("authority", row.get("authority") or "")
        if text and text in seen_direction:
            # Several choices under one instruction cite the same words. The
            # screen says them once; decisions.jsonl keeps them on every row.
            pass
        elif text:
            seen_direction[text] = n
            out.append(f"      {label}: {trimmed(text, 110)}")
    if len(decisions) > limit_choices:
        out.append(f"  ... and {len(decisions) - limit_choices} more in decisions.jsonl")
    out.append("")

    grouped, total = brief_changes(shas, watched) if shas else ({}, 0)
    out.append(f"CHANGES  ({total} file(s) over {len(shas)} commit(s))")
    listed_whole = ("instructions", "manuscript")
    for group in ("instructions", "manuscript", "records", "code", "docs"):
        entries = grouped.get(group, [])
        if not entries:
            continue
        added = sum(e[1] for e in entries)
        removed = sum(e[2] for e in entries)
        line = f"  {group:<13}{len(entries):>3} file(s)  +{added} -{removed}"
        if group not in listed_whole:
            # One screen cannot hold every path. The largest file stands for the
            # group; the instruction and manuscript files are listed in full below,
            # because a change to either is the thing a person is asked about.
            big = max(entries, key=lambda e: e[1] + e[2])
            line += f"   largest {trimmed(big[0], 44)} +{big[1]} -{big[2]}"
        out.append(line)
        if group not in listed_whole:
            continue
        for name, plus, minus in entries[:limit_files + 2]:
            out.append(f"      {name}  +{plus} -{minus}")
        if len(entries) > limit_files + 2:
            out.append(f"      ... and {len(entries) - limit_files - 2} more")
    # The words added to the standing instructions first, then to the manuscript,
    # each under its own heading, sharing the forty lines one screen holds.
    budget = 40
    for group, heading in (("instructions", "the instruction files"), ("manuscript", "the manuscript")):
        files = [e[0] for e in grouped.get(group, [])]
        quoted, rest = brief_added_lines(shas, files, cap=budget)
        budget -= len(quoted)
        if quoted or rest:
            out.append("")
            out.append(f"  lines these commits added to {heading}:")
            for line in quoted:
                out.append(f"    | {trimmed(line, 110)}")
            if rest:
                out.append(f"    ... and {rest} more added line(s)")
    out.append("")

    out.append(f"CHECKS  ({len(checks)} row(s) in {path}/checks.jsonl)")
    if not checks:
        out.append("  none recorded")
    for row in checks[:limit_checks]:
        out.append(f"  {trimmed(row.get('kind', 'unstated'), 20):<20}{trimmed(row.get('result', 'nothing stated'), 70)}")
        # What the check was run on and held against, as the row states them, so a
        # person can see the coverage and not only the outcome (rc22). A row
        # written before version 2 states neither and says so.
        out.append(f"      candidate: {trimmed(str(row.get('candidate') or 'not stated'), 100)}")
        out.append(f"      criterion: {trimmed(str(row.get('criterion') or 'not stated'), 100)}")
        # Who checked and what they looked at, so a passing result is read with
        # its checker and its method (rc22). A row from `check` names the checker
        # and its kind; any other row names who ran it.
        out.append(f"      checker: {trimmed(check_checker(row), 100)}")
        out.append(f"      examined: {trimmed(str(row.get('method') or 'not stated'), 100)}")
        named = check_sources(row)
        if named:
            # In full: a cut hid the file name a check was held against (rc22).
            out.extend(brief_wrapped("sources", ", ".join(named)))
        limits = row.get("limits")
        if limits:
            out.append(f"      limits: {trimmed(limits, 100)}")
    if len(checks) > limit_checks:
        out.append(f"  ... and {len(checks) - limit_checks} more in checks.jsonl")
    out.append("")

    through = f" --through {bound[:12]}" if bound else ""
    out.append("COMMANDS  (nothing above has decided anything)")
    out.append(f'  python3 scripts/trace_record.py accept --record {identifier} --person{through}')
    out.append(f'  python3 scripts/trace_record.py accept --record {identifier} --person{through} \\')
    out.append('      --decision return --objections "what has to change"')
    out.append("  --by defaults to your git config user.name; --scope to the brief of this record.")
    if accepted:
        out.append(f"  accept --record covers all {len(shas)} commit(s) naming this record, "
                   f"the {accepted} already accepted included.")
    if bound:
        out.append(f"  --through {bound[:12]} binds the decision to this version: a commit naming the "
                   "record that lands later is not covered and stays in queue.")
    out.append("  Or say the decision to your agent in your own words, naming this record;")
    out.append(f"  it records it in your name with --recorded-by <its id> --words \"what you said\"{through}.")
    return out


def cmd_brief(args: argparse.Namespace) -> int:
    """Put one trace record on one screen, so a person can decide about it."""
    text = "\n".join(brief_lines(args.record)) + "\n"
    if getattr(args, "out", ""):
        out = pathlib.Path(args.out)
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out}")
        return 0
    print(text, end="")
    return 0


