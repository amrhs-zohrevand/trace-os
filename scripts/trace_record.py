#!/usr/bin/env python3
"""Build and verify the TRACE trace record: human direction and machine execution.

Companion to `ai/RECORD-CONVENTION.md`. Answers one question from the repository
alone: what direction did the human give, and what was checked before the work
was accepted?

The record has two layers, and the second never replaces the first:

  1. evidence.json   the human's own prompts, verbatim, subject to declared
                     redactions. This is the primary artifact.
  2. summary.md      a digest of the direction those prompts gave, authored on top
                     of the raw layer, every entry citing the turn ids it rests
                     on.

A summary can mislead by omission even when everything it says is true, so
`coverage.json` maps every raw turn to either a summary entry or an explicit
exclusion reason. `checks.jsonl` records the verification actions (agent
reviews, builds, clarity gates, citation audits) that ran before acceptance.

Subcommands:
  extract   pull your own turns out of a session transcript into UNTRACKED
            staging, for review before promotion
  promote   move a reviewed staging directory into ai/records/<id>/
  cover     build or refresh coverage.json from evidence.json + summary.md
  verify    check a record's integrity and completeness (report-only
            unless --strict; --json hands the findings to another program)
  keep      run the routine above for the running session before a commit:
            extract, cover, the disclosure review, promote, verify and the
            commit body, stopping only where the agent's judgment is needed

What `verify` checks is mechanical: hashes, ids, coverage, schema, and the
producer trailer on each commit in a range. What it cannot check is stated in
`ai/RECORD-CONVENTION.md` under "What this does not prove".

stdlib only; no install step.
"""

