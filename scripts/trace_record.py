def project_config() -> dict | None:
    """Optional project-local configuration; absence retains the research defaults."""
    path = pathlib.Path("ai/project.json")
    if not path.exists():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or type(data.get("schema_version")) is not int or data["schema_version"] != 1:
        raise ValueError("ai/project.json: unsupported project configuration")
    return data


def project_epoch(field: str, fallback: str | None) -> str:
    config = project_config()
    value = config.get(field) if config is not None else fallback
    if not isinstance(value, str) or not re.fullmatch(r"[0-9a-f]{40}", value):
        raise ValueError(f"{field} is not initialized; complete the project setup")
    # Bad project configuration must not turn an unreadable history into zero work.
    if config is not None:
        result = subprocess.run(["git", "merge-base", "--is-ancestor", value, "HEAD"],
                                capture_output=True)
        if result.returncode:
            raise ValueError(f"{field} is not a commit in this project's HEAD history")
    return value

AI_COAUTHOR_RE = re.compile(
    r"^Co-Authored-By:\s*([^<\n]*(?:Claude|GPT|Copilot|Gemini|Codex|Cursor|Devin)[^<\n]*)",
    re.IGNORECASE | re.MULTILINE,
)
MADE_BY_RE = re.compile(r"^Made-by:", re.IGNORECASE | re.MULTILINE)
# Git reads a trailer key in any case; `accept` always did, and the readers
# below agree with it (`Execution-Agent: gpt-9` is a declaration).
EXECUTION_AGENT_RE = re.compile(r"^Execution-agent:\s*(\S+)", re.IGNORECASE | re.MULTILINE)
# The value is a bare model id. A `vendor:` or `agent:` prefix is noise that says
# nothing the field name has not already said, and two concurrent sessions in one
# clone drifted to different forms within an hour because the first version of
# this check accepted any non-empty value. Pin the format or it forks.
AGENT_PREFIX_RE = re.compile(r"^[A-Za-z][\w-]*:")
TRAILER_LINE_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9-]*:\s")


def trailer_block(message: str) -> str:
    """The part of a commit message that holds its trailers.

    That is the last paragraph after the subject, plus any paragraphs directly
    above it made of trailer lines only (`Record:` and `Execution-agent:` are
    often a paragraph each). Reading the whole message took a wrapped line of
    a commit's explanation that began `Execution-agent: <model-id>` for the
    declaration (AH-123). Git's own rule, a last paragraph of trailers only,
    is stricter than this history: ten commits end in a paragraph that also
    holds `Human inputs: T2` or a sentence, or put the trailer right under the
    subject, and would read as undeclared.
    """
    rest = message.strip().partition("\n")[2]
    paragraphs = [p for p in re.split(r"\n[ \t\r]*\n", rest.strip()) if p.strip()]
    if not paragraphs:
        return ""
    block = [paragraphs.pop()]
    while paragraphs and all(TRAILER_LINE_RE.match(line) for line in paragraphs[-1].splitlines()):
        block.insert(0, paragraphs.pop())
    return "\n\n".join(block)


def declared_agents(message: str) -> list[str]:
    """Every model id the message's trailers declare, as `classify` reads one.

    `Execution-agent: none` (six hand-typed commits here, any case) declares
    that no machine executed the commit, so it names no agent; a real
    declaration beside it in the same block is still read (AH-137).
    """
    agents = (AGENT_PREFIX_RE.sub("", agent, count=1)
              for agent in EXECUTION_AGENT_RE.findall(trailer_block(message)))
    return [agent for agent in agents if agent.lower() != "none"]


def commit_message_problems(message: str) -> list[str]:
    """Report what a commit message claims. Nothing here blocks a commit.

    A message with no `Execution-agent:` trailer is not a problem: a person
    typed it, and nobody is asked to type a field to say so. The trailer is
    the machine's declaration, and the standing instruction is what produces
    it (zero omissions in about 540 agent commits, including a month with no
    hook installed). A commit-msg hook that rejected the missing trailer was
    removed on 2026-09-19: the commits it stopped or turned CI red on were a
    person's Overleaf-editor and hand edits and one merge the sync script
    made, never a model forgetting. What is still reported is a false claim (AI
    co-authorship) and a drifted trailer format, and `verify-range` prints
    both as counts.
    """
    problems, message = [], trailer_block(message)
    if AI_COAUTHOR_RE.search(message):
        problems.append(
            "claims AI co-authorship. Authorship carries accountability a model "
            "cannot hold; ICMJE, COPE, Nature and Science all rule it out. "
            "Use `Execution-agent: <model-id>` instead (AGENTS.md)."
        )
    if MADE_BY_RE.search(message):
        problems.append(
            "claims the model made the work (`Made-by:`). A model executes "
            "instructions; write `Execution-agent: <model-id>` (AGENTS.md)."
        )
    match = EXECUTION_AGENT_RE.search(message)
    if match and AGENT_PREFIX_RE.match(match.group(1)):
        problems.append(
            f"`Execution-agent: {match.group(1)}` carries a redundant prefix. The "
            f"field already says it is the executing agent. Write the bare model "
            f"id: `{AGENT_PREFIX_RE.sub('', match.group(1), count=1)}`."
        )
    return problems


def sha256_file(path: pathlib.Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(65536), b""):
            h.update(block)
    return h.hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def raw_text(row: dict) -> str:
    """The row's text content, before any filtering."""
    content = row.get("message", {}).get("content")
    if isinstance(content, str):
        return content.strip()
    if isinstance(content, list):
        return " ".join(b.get("text", "") for b in content
                        if isinstance(b, dict) and b.get("type") == "text").strip()
    return ""


def queued_text(row: dict) -> str | None:
    """Text from a message sent while the assistant was still working.

    These do not appear as user rows at all. They are attachments of type
    `queued_command`, and missing them silently drops real human input, which is
    how the first version of this script lost four turns.

    The shape has changed under us (AH-125): Claude Code 2.1.181 to 2.1.201
    wrote no `origin`, and 2.1.222 wrote `prompt` as a plain string. Both were
    dropped without notice. As for typed rows, a stated origin other than
    `human` excludes the message, an absent one does not, and the text filters
    decide the rest; the harness's own `isMeta` flag excludes it too (AH-124).
    """
    if row.get("type") != "attachment":
        return None
    att = row.get("attachment", {})
    if att.get("type") != "queued_command":
        return None
    if (att.get("origin") or {}).get("kind") not in (None, "human") or att.get("isMeta"):
        return None
    prompt = att.get("prompt") or []
    if isinstance(prompt, str):
        return prompt.strip() or None
    parts = [b.get("text", "") for b in prompt
             if isinstance(b, dict) and b.get("type") == "text"]
    return " ".join(parts).strip() or None


def filtered(text: str) -> str | None:
    """The human's words in a piece of user-role text, or None.

    One filter for typed and queued text alike. The first version applied it
    only to typed rows, so a queued message kept its editor wrapper and a queued
    `/compact` was recorded as human input.
    """
    stripped = WRAPPER_RE.sub("", text, count=1).strip()
    if not stripped or stripped.startswith(NOT_HUMAN_AT_ALL) or BARE_COMMAND_RE.match(stripped):
        return None
    return stripped


def human_text(row: dict) -> str | None:
    """What the person actually typed in this row, or None.

    Returns the text with harness wrappers stripped. A row that is entirely
    machine content returns None, as does a row that is only a wrapper.
    """
    queued = queued_text(row)
    if queued is not None:
        return filtered(queued)
    # A tool's result is never typed text. Answers given through the question
    # dialog are a tool result too, and `dialog_entries` reads them (AH-274).
    if row.get("type") != "user" or "toolUseResult" in row:
        return None
    # The harness states who sent a row, as it does for queued text. A peer
    # agent session's message (kind "peer": a <cross-session-message> or
    # <agent-message> element between lines of the harness's own) is not the
    # person, and stripping the element would leave those lines behind as a
    # human turn. Older transcripts state no origin and still go through the
    # text filters.
    if (row.get("origin") or {}).get("kind") not in (None, "human"):
        return None
    if row.get("isCompactSummary"):
        return None
    # The harness flags the rows it writes itself (a cross-session notice, an
    # image placeholder, "Continue from where you left off.", a loaded skill)
    # `isMeta`, and states no origin on them. 119 sat in 25 tracked records as
    # the person's turns (AH-124).
    if row.get("isMeta"):
        return None
    text = raw_text(row)
    if not text:
        return None
    return filtered(text)


# --- Answers given through the question dialog ---------------------------------
# When an agent asks through Claude Code's question dialog (the AskUserQuestion
# tool), the person's answers come back as that tool's result: a `user` row whose
# `toolUseResult` holds the questions asked and the answers given. Every row
# carrying a `toolUseResult` was dropped as a tool result, so 13 answers in 12
# sessions of this project, each one a decision, reached no trace record
# (AH-274). The row is recognized by its shape, not by the tool's name. The
# option wording is the agent's and only the choice is the person's, so the
# turn's text says, per answer, which of the two the words are.
#
# The dialog stores one string per question and records no click, so every
# kind is read off that string and asserts no more than it shows (AH-279).
# `selected` means the answer equals an offered label, or for a multi-select
# nothing but offered labels: a match of the stored string. When an answer
# opens with offered labels and goes on, the words after them are certainly
# the person's, while the labels may have been picked or typed, and the text
# says exactly that.
DIALOG_SELECTED = "[selected from the agent's options]"
DIALOG_TYPED = "[typed in answer]"
DIALOG_OPENS_WITH_OPTIONS = "[opens with the agent's options, picked or typed]"
DIALOG_AND_TYPED = "[and typed]"
DIALOG_QUESTION = "[to the question]"
DIALOG_NOTE = "[note]"


def dialog_result(row: dict) -> dict | None:
    """The `toolUseResult` of a row holding answers to the question dialog, or None.

    The exclusions that apply to a typed row apply here too: a stated origin
    other than `human`, and the harness's own `isMeta` flag. Any other tool's
    result stays out.
    """
    if row.get("type") != "user":
        return None
    result = row.get("toolUseResult")
    if not isinstance(result, dict):
        return None
    answers, questions = result.get("answers"), result.get("questions")
    if not (isinstance(answers, dict) and answers and isinstance(questions, list)):
        return None
    if (row.get("origin") or {}).get("kind") not in (None, "human") or row.get("isMeta"):
        return None
    return result


def label_run(answer: str, labels: list[str]) -> tuple[list[str], str]:
    """The longest run of offered labels, joined by ", ", that opens `answer`,
    and the text after it.

    A multi-select answer is the picked labels joined by ", ", with anything the
    person typed after them; the same string can also be typed whole, so a run
    found here is a match of the text, not evidence of a pick. Labels can hold
    ", " themselves, so labels are matched whole rather than the answer split
    at its commas.
    """
    ordered = sorted({label for label in labels if label}, key=len, reverse=True)
    best: tuple[list[str], int] = ([], 0)

    def walk(at: int, picked: list[str]) -> bool:
        nonlocal best
        for label in ordered:
            if not answer.startswith(label, at):
                continue
            end = at + len(label)
            if end == len(answer):
                best = (picked + [label], end)
                return True
            if answer.startswith(", ", end):
                if end > best[1]:
                    best = (picked + [label], end)
                if walk(end + 2, picked + [label]):
                    return True
        return False

    walk(0, [])
    picked, end = best
    rest = answer[end:]
    return picked, rest[2:] if rest.startswith(", ") else rest


def dialog_entries(row: dict) -> list[dict] | None:
    """One entry per answered question in a question-dialog row, or None.

    `answer_kind` is `selected` when the answer equals one offered label, or for
    a multi-select question nothing but offered labels, a match of the stored
    string since the dialog records no click; `options-and-typed` when a
    multi-select answer opens with offered labels (`options_matched`, picked or
    typed) and goes on in the person's own words (`typed`); anything else is
    `typed`.
    """
    result = dialog_result(row)
    if result is None:
        return None
    answers = result["answers"]
    notes = result.get("annotations") if isinstance(result.get("annotations"), dict) else {}
    entries = []
    for question in result["questions"]:
        if not isinstance(question, dict) or not isinstance(question.get("question"), str):
            continue
        asked = question["question"]
        answer = answers.get(asked)
        if isinstance(answer, list):
            answer = ", ".join(a for a in answer if isinstance(a, str))
        if not isinstance(answer, str) or not answer.strip():
            continue
        options = [o["label"] for o in question.get("options") or []
                   if isinstance(o, dict) and isinstance(o.get("label"), str)]
        given = answer.strip()
        entry = {"question": asked, "options": options, "answer": answer}
        if given in options:
            entry["answer_kind"] = "selected"
        elif question.get("multiSelect"):
            picked, rest = label_run(given, options)
            if picked and not rest.strip():
                entry["answer_kind"] = "selected"
            elif picked:
                entry.update({"answer_kind": "options-and-typed", "options_matched": picked,
                              "typed": rest.strip()})
            else:
                entry["answer_kind"] = "typed"
        else:
            entry["answer_kind"] = "typed"
        note = notes.get(asked)
        note = note.get("notes") if isinstance(note, dict) else note
        if isinstance(note, str) and note.strip():
            entry["note"] = note.strip()
        entries.append(entry)
    return entries or None


def dialog_text(entries: list[dict]) -> str:
    """The turn's text: one self-describing line per answered question.

    Every reader that prints a turn's text as the person's words stays truthful
    without change, because the brackets say which words match the agent's
    options and which the person typed.
    """
    lines = []
    for entry in entries:
        kind = entry["answer_kind"]
        if kind == "selected":
            said = f"{DIALOG_SELECTED} {entry['answer'].strip()}"
        elif kind == "options-and-typed":
            said = (f"{DIALOG_OPENS_WITH_OPTIONS} {', '.join(entry['options_matched'])} "
                    f"{DIALOG_AND_TYPED} {entry['typed']}")
        else:
            said = f"{DIALOG_TYPED} {entry['answer'].strip()}"
        line = f"{said} {DIALOG_QUESTION} {entry['question'].strip()}"
        if entry.get("note"):
            line += f" {DIALOG_NOTE} {entry['note']}"
        lines.append(line)
    return "\n".join(lines)


def dialog_tool_use_id(row: dict) -> str | None:
    """The id of the tool call a result row answers."""
    content = row.get("message", {}).get("content")
    if isinstance(content, list):
        for block in content:
            if isinstance(block, dict) and block.get("type") == "tool_result" and block.get("tool_use_id"):
                return block["tool_use_id"]
    return None


def tool_use_models(rows: list[dict]) -> dict[str, str]:
    """Each tool call's id, mapped to the model of the assistant row that made it."""
    models: dict[str, str] = {}
    for row in rows:
        if row.get("type") != "assistant":
            continue
        model = row.get("message", {}).get("model")
        content = row.get("message", {}).get("content")
        if not is_model_id(model) or not isinstance(content, list):
            continue
        for block in content:
            if isinstance(block, dict) and block.get("type") == "tool_use" and block.get("id"):
                models[block["id"]] = model
    return models


# Claude Code writes the model `<synthetic>` on assistant rows the harness made
# itself (a session-limit or API-error message). A bracketed placeholder names
# no model, and it reached commits as `Execution-agent: <synthetic>` (AH-126).
PLACEHOLDER_MODEL_RE = re.compile(r"^<.*>$")


def is_model_id(model) -> bool:
    """True for a model name an execution trailer may carry."""
    return isinstance(model, str) and bool(model.strip()) and not PLACEHOLDER_MODEL_RE.match(model.strip())


def models_used(rows: list[dict]) -> list[dict]:
    """Which models actually executed, read off the transcript.

    An agent asking itself which model it is will answer from its own system
    prompt, which names the model the session STARTED with. That answer survives
    a mid-session `/model` switch and is then wrong. In the session this project
    was built in, the agent declared `claude-fable-5` while `claude-opus-5` had
    executed 330 of 340 messages.

    So the executing model is evidence to be read, not a fact to be self-reported,
    which is the same rule the rest of the record follows.
    """
    counts: dict[str, dict] = {}
    for row in rows:
        if row.get("type") != "assistant":
            continue
        model = row.get("message", {}).get("model")
        if not is_model_id(model):
            continue
        stamp = row.get("timestamp")
        entry = counts.setdefault(model, {"model": model, "messages": 0,
                                          "first": stamp, "last": stamp})
        entry["messages"] += 1
        entry["last"] = stamp
    return sorted(counts.values(), key=lambda e: -e["messages"])


# --- Codex rollouts -----------------------------------------------------------
# A Codex session is a different file: rows carry a `payload`, the human's
# messages are `response_item` rows with role `user`, and the model is stated
# per turn in `turn_context`, not per message. Two rows in the user role are
# injections and never the person: the desktop app's plugin advertisement and
# the harness loading the repository's instruction files.
CODEX_INJECTIONS = (
    "<recommended_plugins>",
    "<environment_context>",
)
# The instruction header comes with a path or bare; 32 local rows had the bare
# form and read as the person's turn (AH-199). The whole first line must be the
# header, so a person who begins with these words is still recorded.
CODEX_AGENTS_HEADER_RE = re.compile(r"\A# AGENTS\.md instructions(?: for [^\n]*)?[ \t]*(?:\n|\Z)")
# The two wrappers are stripped as a leading run too: stripped anywhere, a
# person quoting one lost the words inside it (AH-206).
CODEX_WRAPPER_RE = re.compile(
    r"\A(?:\s*<(recommended_plugins|environment_context)>.*?</\1>)+", re.DOTALL)
# Machine payloads Codex posts in the user role as a closed element at the
# row's start: a subagent reporting back, a turn abort, an automation
# re-sending its instructions, and an edit notice. 149 local rows, each read as
# the person's turn (AH-130). Only the leading run is stripped, so a person's
# words after one stay and a person quoting one keeps the quote.
CODEX_PAYLOAD_RE = re.compile(
    r"\A(?:\s*<(subagent_notification|turn_aborted|heartbeat|"
    r"external_codex_apps_writing_block_edits)>.*?</\1>)+", re.DOTALL)


def is_codex_rollout(rows: list[dict]) -> bool:
    return any(r.get("type") in ("session_meta", "turn_context") for r in rows[:20])


def codex_human_text(row: dict) -> str | None:
    if row.get("type") != "response_item":
        return None
    payload = row.get("payload", {})
    if payload.get("type") != "message" or payload.get("role") != "user":
        return None
    text = " ".join(c.get("text", "") for c in payload.get("content", [])
                    if isinstance(c, dict) and c.get("type") == "input_text").strip()
    if not text:
        return None
    stripped = text
    # A leading run of wrappers and payloads, in whatever order they came.
    while match := CODEX_WRAPPER_RE.match(stripped) or CODEX_PAYLOAD_RE.match(stripped):
        stripped = stripped[match.end():].strip()
    if (not stripped or any(stripped.startswith(m) for m in CODEX_INJECTIONS)
            or CODEX_AGENTS_HEADER_RE.match(stripped)):
        return None
    return stripped


def codex_models_used(rows: list[dict]) -> list[dict]:
    """Each assistant message is credited to the model of the turn it sits in."""
    counts: dict[str, dict] = {}
    current = None
    for row in rows:
        payload = row.get("payload", {})
        if row.get("type") == "turn_context":
            current = payload.get("model") or current
            continue
        if (row.get("type") == "response_item" and payload.get("type") == "message"
                and payload.get("role") == "assistant" and current):
            stamp = row.get("timestamp")
            entry = counts.setdefault(current, {"model": current, "messages": 0,
                                                "first": stamp, "last": stamp})
            entry["messages"] += 1
            entry["last"] = stamp
    return sorted(counts.values(), key=lambda e: -e["messages"])


# --- The running agent's own session ------------------------------------------
# Each supported CLI tells the commands it runs which session they belong to:
# Claude Code sets CLAUDE_CODE_SESSION_ID and writes <config>/projects/<dir>/<id>.jsonl,
# and Codex sets CODEX_THREAD_ID (CODEX_SESSION_ID in some versions) and writes
# $CODEX_HOME/sessions/<y>/<m>/<d>/rollout-<stamp>-<id>.jsonl. Without this,
# finding one's own transcript and model id was left to each model: in the
# agent-parity matrix of 2026-10-15 a Codex agent found its rollout from its
# environment and recorded the session, while Claude agents, given the same
# instructions, recorded none and wrote "No turn ID was extracted".
SESSION_SOURCES = (
    ("claude-code", ("CLAUDE_CODE_SESSION_ID",)),
    ("codex", ("CODEX_THREAD_ID", "CODEX_SESSION_ID")),
)


def _session_transcript(runner: str, session: str, env) -> pathlib.Path | None:
    if runner == "claude-code":
        roots = [pathlib.Path(env["CLAUDE_CONFIG_DIR"])] if env.get("CLAUDE_CONFIG_DIR") else []
        roots.append(pathlib.Path.home() / ".claude")
        pattern = f"projects/*/{session}.jsonl"
    else:
        roots = [pathlib.Path(env["CODEX_HOME"])] if env.get("CODEX_HOME") else []
        roots.append(pathlib.Path.home() / ".codex")
        pattern = f"sessions/**/rollout-*{session}.jsonl"
    for root in roots:
        found = sorted(root.glob(pattern), key=lambda f: f.stat().st_mtime, reverse=True)
        if found:
            return found[0]
    return None


def _process_chain(pid: int, limit: int = 40) -> list[list[str]]:
    """The command lines of this process's ancestors, nearest first; empty where
    the platform does not say (Windows) or a parent cannot be read."""
    chain = []
    for _ in range(limit):
        try:
            proc = pathlib.Path(f"/proc/{pid}")
            if proc.exists():
                args = [a for a in (proc / "cmdline").read_bytes().split(b"\0") if a]
                fields = (proc / "stat").read_text().rsplit(")", 1)[1].split()
                parent = int(fields[1])
                argv = [a.decode(errors="replace") for a in args]
            else:
                out = subprocess.run(["ps", "-o", "ppid=", "-o", "command=", "-p", str(pid)],
                                     capture_output=True, text=True, timeout=5).stdout.strip()
                if not out:
                    break
                ppid, _, command = out.partition(" ")
                parent, argv = int(ppid), command.split()
        except (OSError, ValueError, IndexError, subprocess.SubprocessError):
            break
        chain.append(argv)
        # Process 1 is read too: inside Codex's sandbox the command runs in its own
        # process namespace, where the sandbox program itself is process 1.
        if pid <= 1 or parent == pid or parent < 1:
            break
        pid = parent
    return chain


def _agent_cli(argv: list[str]) -> str | None:
    """Which supported agent CLI a command line runs, read off its program and,
    for a node launcher, its script; never off directory names, which may say
    anything."""
    names = [pathlib.PurePath(a).name.lower() for a in argv[:2]]
    if any(n == "codex" or n.startswith("codex-") for n in names):
        return "codex"
    if any(n == "claude" for n in names) or any("@anthropic-ai/claude-code" in a for a in argv[:2]):
        return "claude-code"
    return None


def nearest_agent_cli(chain: list[list[str]] | None = None) -> str | None:
    """The agent CLI nearest above this command in the process tree."""
    for argv in (_process_chain(os.getppid()) if chain is None else chain):
        found = _agent_cli(argv)
        if found:
            return found
    return None


def current_session(env=None, chain=None) -> dict:
    """Which agent CLI is running this command, its session id, its transcript and
    the model its transcript says executed the latest turn, from the runtime's own
    files rather than the model's account of itself.

    An agent started from another agent's shell inherits the outer one's variable:
    a Codex reviewer launched from Claude Code, as agentic_review.py does, sees
    CLAUDE_CODE_SESSION_ID too. In the agent-parity matrix that made a Codex run
    sign its commit with the outer Claude model. So the nearest agent CLI in the
    process tree decides, and when it cannot be read and two are set, the answer
    is that it is ambiguous, not the first one found.
    """
    env = os.environ if env is None else env
    present = {}
    for runner, names in SESSION_SOURCES:
        for name in names:
            if env.get(name) and runner not in present:
                present[runner] = name
    empty = {"runner": None, "session": None, "variable": None, "transcript": None,
             "model": None, "models": [], "basis": None, "ambiguous": []}
    if not present:
        return empty
    nearest = nearest_agent_cli(chain)
    if nearest in present:
        runner, basis = nearest, "the nearest agent program above this command"
    elif len(present) == 1 and nearest is None:
        runner, basis = next(iter(present)), "the only agent session variable set"
    else:
        return {**empty, "ambiguous": sorted(present),
                "basis": (f"the nearest agent program is {nearest}, whose session variable is not set"
                          if nearest else "two agent sessions are set and the process tree does not say which runs this")}
    name = present[runner]
    session = env[name]
    path = _session_transcript(runner, session, env)
    found = {**empty, "runner": runner, "session": session, "variable": name,
             "transcript": str(path) if path else None, "basis": basis}
    if path:
        rows = []
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                rows.append(json.loads(line))
            except ValueError:
                continue
        used = codex_models_used(rows) if is_codex_rollout(rows) else models_used(rows)
        found["models"] = used
        if used:
            # The latest model to execute, not the most frequent one:
            # a commit made now is executed by the model running now.
            found["model"] = max(used, key=lambda e: e["last"] or "")["model"]
    return found


def cmd_session(args: argparse.Namespace) -> int:
    found = current_session()
    if getattr(args, "json", False):
        print(json.dumps(found))
        return 0
    if not found["runner"]:
        why = (f"ambiguous: {found['basis']} ({', '.join(found['ambiguous'])})"
               if found["ambiguous"] else
               "no supported agent session found: neither CLAUDE_CODE_SESSION_ID nor "
               "CODEX_THREAD_ID is set")
        print(f"{why}. Pass the transcript to extract by path. In Execution-agent: and "
              "--recorded-by put the model id you were told you run as, the id alone, and tell "
              "the person it is self-reported.")
        return 1
    print(f"runner:     {found['runner']} ({found['variable']}={found['session']}; {found['basis']})")
    print(f"transcript: {found['transcript'] or 'not found under the CLI home'}")
    if found["model"]:
        print(f"model:      {found['model']}  (read off the transcript; use it in "
              "Execution-agent: and --recorded-by)")
    else:
        print("model:      not stated in the transcript yet; put the model id you were "
              "told you run as in those fields, the id alone, and tell the person it is "
              "self-reported")
    return 0 if found["transcript"] else 1


# ai/review-prose-rules.md shapes the reviewer's prompt and is protected as an
# instruction path, so a record names its digest too (f1ca7a5 F004).
INSTRUCTION_FILES = ("AGENTS.md", "CLAUDE.md", "WORKFLOW.md", "ai/RECORD-CONVENTION.md",
                     "scripts/INPUT-PROVENANCE.md", "ai/review-prose-rules.md")
INSTRUCTION_BASIS = ("file state at extraction time, read from the working tree; "
                     "not proof of what the agent loaded or read")
TRACE_RECORD_SCHEMA_VERSION = 2


def instruction_provenance(root: pathlib.Path | None = None) -> dict:
    """Which standing instructions governed this run, as far as the tree shows.

    Section 4 of the paper asks the record to identify the standing instructions
    that governed a run. The digests here are of the instruction files as they
    stood when the turns were extracted, plus the commit the tree was on. That
    is evidence about the versions in force, and it is labelled as such: a file
    digest cannot show that the agent read the file.
    """
    root = pathlib.Path(root or ".")
    files: dict[str, str] = {}
    for name in INSTRUCTION_FILES:
        path = root / name
        if path.is_file():
            files[name] = sha256_file(path)
    skills = root / ".skills"
    if skills.is_dir():
        for path in sorted(skills.rglob("*.md")):
            if path.is_file():
                files[path.relative_to(root).as_posix()] = sha256_file(path)
    head = subprocess.run(["git", "-C", str(root), "rev-parse", "HEAD"],
                          capture_output=True, text=True)
    return {
        "base_commit": head.stdout.strip() if head.returncode == 0 and head.stdout.strip() else None,
        "files": files,
        "basis": INSTRUCTION_BASIS,
    }


class RecordRefused(ValueError):
    """A step of the record routine refused. The message is the one its own
    command prints when it stops, so `extract`, `promote` and `keep` say the same."""


class PromotionRefused(RecordRefused):
    """`promote` refused; `cmd_promote` turns it into its exit, `keep` reports it."""


def read_transcript(src: pathlib.Path) -> list[dict]:
    """The rows of a transcript, skipping lines that do not parse."""
    rows = []
    with src.open(encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError:
                    continue
    return rows


def extract_into(src: pathlib.Path, out_dir: pathlib.Path, record_id: str,
                 named_speaker: str | None) -> dict:
    """Capture the human turns of one transcript into a staging directory.

    The core of `extract`, lifted so that `keep` runs the same refresh: it
    raises `RecordRefused` with the message `extract` prints where it used to
    exit, and hands back what it wrote for the caller to report.
    """
    if not src.exists():
        raise RecordRefused(f"transcript not found: {src}")
    rows = read_transcript(src)

    codex = is_codex_rollout(rows)
    extract_text = codex_human_text if codex else human_text
    speaker = named_speaker or "unknown"
    turns = []
    # Claude Code can write the same user rows twice, uuid and all, after a
    # compaction or a resume; the second copy is not a further turn (AH-229).
    # Codex rows carry no uuid, and a row without one is never a repeat.
    seen_uuids: set[str] = set()
    repeated_rows: set[int] = set()
    # Answers given through the question dialog arrive as a tool result and
    # become a turn of their own kind (AH-274); a Codex rollout has no such row.
    asked_by = {} if codex else tool_use_models(rows)
    for i, row in enumerate(rows):
        dialog = None if codex else dialog_entries(row)
        text = dialog_text(dialog) if dialog else extract_text(row)
        if text is not None:
            uuid = None if codex else row.get("uuid")
            if uuid:
                if uuid in seen_uuids:
                    repeated_rows.add(i)
                    continue
                seen_uuids.add(uuid)
            turn = {
                "id": f"T{len(turns) + 1}",
                "row": i,
                "timestamp": row.get("timestamp"),
                "speaker": speaker,
                "speaker_kind": "human",
                "text": text,
                "source": {"kind": "question-dialog" if dialog else "chat", "session": src.name,
                           "text_sha256": sha256_text(text)},
            }
            if dialog:
                turn["dialog"] = dialog
                model = asked_by.get(dialog_tool_use_id(row))
                if model:
                    turn["asked_by"] = model
            turns.append(turn)

    if not turns:
        raise RecordRefused("no human turns found; check the transcript path")

    out_dir.mkdir(parents=True, exist_ok=True)
    # Refresh a session without deleting captured comments or prior redactions.
    prior_path = out_dir / "evidence.json"
    prior = {}
    added = [t["id"] for t in turns]
    if prior_path.exists():
        prior = load_evidence(out_dir)
        if prior.get("record_id") != record_id:
            raise RecordRefused("record ID differs; use a fresh staging directory")
        previous_chat = {t["row"]: t for t in prior["turns"] if "row" in t}
        for turn in turns:
            old = previous_chat.get(turn["row"])
            if old:
                old_source = old.get("source", {})
                if (old_source.get("session", src.name) != src.name or
                        old_source.get("text_sha256", sha256_text(old["text"])) != sha256_text(turn["text"])):
                    raise RecordRefused("captured source changed; preserve this record and extract to fresh staging")
        # A record extracted before AH-229 may hold a repeated row as a turn;
        # it stays, under the id it was given, rather than being dropped.
        fresh_rows = {t["row"] for t in turns} | repeated_rows
        if set(previous_chat) - fresh_rows:
            raise RecordRefused("previously captured turns are absent; use fresh staging to preserve this record")
        # A refresh in the middle of a session, run so that a decision can cite
        # the turn that directed it, often omits --speaker. The transcript is
        # the one already read, so its later turns keep the speaker the earlier
        # extraction named rather than becoming unknown, which would leave the
        # decision citing them with no owner.
        if not named_speaker:
            named = {t.get("speaker") for t in previous_chat.values()}
            if len(named) == 1 and next(iter(named)) not in (None, "", "unknown", "unattributed", "?"):
                speaker = next(iter(named))
        next_id = max((int(t["id"][1:]) for t in prior["turns"]), default=0) + 1
        merged = list(prior["turns"])
        added = []
        for turn in turns:
            if turn["row"] not in previous_chat:
                turn["id"] = f"T{next_id}"
                turn["speaker"] = speaker
                next_id += 1
                merged.append(turn)
                added.append(turn["id"])
        turns = merged
    instructions = instruction_provenance()
    evidence = {
        **prior,
        "record_schema_version": prior.get("record_schema_version", 1) if prior
        else TRACE_RECORD_SCHEMA_VERSION,
        "record_id": record_id,
        "source_sha256": sha256_file(src),
        "source_rows": len(rows),
        "extractor": f"scripts/trace_record.py@{sha256_file(pathlib.Path(__file__))[:12]}",
        "capture": "verbatim, subject to declared redactions",
        "completeness": "turns after the extraction time are not in the transcript yet",
        "transcript_format": "codex-rollout" if codex else "claude-code",
        "execution_agents": codex_models_used(rows) if codex else models_used(rows),
        "instructions": instructions,
        "consent": {
            "own_turns_by": speaker,
            "third_party_review": "PENDING",
        },
        "turns": turns,
    }
    # A refresh recomputes the instruction digests, so a check row written
    # under a skill that was edited later in the session would no longer match
    # the record's provenance and promotion would refuse it (rc23 design,
    # section 9). The earlier sets are kept, and `verify` accepts any of them.
    earlier = prior.get("instructions")
    if isinstance(earlier, dict) and earlier.get("files") != instructions["files"]:
        kept = [e for e in prior.get("instructions_earlier") or [] if isinstance(e, dict)]
        if earlier not in kept:
            kept.append(earlier)
        evidence["instructions_earlier"] = kept
    path = out_dir / "evidence.json"
    path.write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return {"evidence": evidence, "path": path, "rows": len(rows), "repeated": len(repeated_rows),
            "refreshed": bool(prior), "speaker": speaker, "added": added}


def cmd_extract(args: argparse.Namespace) -> int:
    from record_privacy import private_capture_target
    private_capture_target(pathlib.Path(args.out))
    if args.session == "current":
        found = current_session()
        if not found["transcript"]:
            sys.exit("extract current: no transcript found for this agent session "
                     "(trace_record.py session says why); pass the transcript's path")
        args.session = found["transcript"]
    try:
        result = extract_into(pathlib.Path(args.session), pathlib.Path(args.out), args.record_id,
                              getattr(args, "speaker", None))
    except RecordRefused as exc:
        sys.exit(str(exc))
    evidence, path, speaker = result["evidence"], result["path"], result["speaker"]
    turns = evidence["turns"]

    print(f"{len(turns)} human turns from {result['rows']} transcript rows -> {path}")
    if result["refreshed"] and speaker != "unknown" and not getattr(args, "speaker", None):
        print(f"later turns keep the speaker the earlier extraction named: {speaker}")
    dialogs = sum(1 for t in turns if (t.get("source") or {}).get("kind") == "question-dialog")
    if dialogs:
        print(f"{dialogs} of them from the question dialog")
    if result["repeated"]:
        print(f"{result['repeated']} repeated row(s) skipped: same uuid as a row already read")
    print("executed by (from the transcript, not self-report):")
    for entry in evidence["execution_agents"]:
        print(f"  {entry['model']:<24} {entry['messages']:>4} messages")
    print("\nSTAGED, NOT TRACKED. Before promoting, read every turn and:")
    print("  1. replace private or unauthorized third-party material with [REDACTED: category]")
    print("  2. replace secrets or personal data the same way")
    print("  3. set consent.third_party_review to 'cleared'")
    # cover binds evidence.json by its digest, so the order matters: an edit to
    # evidence.json after cover (consent included) makes promote refuse until
    # cover and the disclosure review are run again (rc22).
    print("Then write the summary and checks, and run cover, privacy-check and publication-review,")
    print("in that order, after the last edit to evidence.json. An edit after cover (consent, a")
    print("redaction, another extract) needs cover, privacy-check and publication-review again.")
    return 0


def load_evidence(record: pathlib.Path) -> dict:
    path = record / "evidence.json"
    if not path.exists():
        sys.exit(f"no evidence.json in {record}")
    return json.loads(path.read_text(encoding="utf-8"))


PROMOTED_NAMES = ("evidence.json", "summary.md", "coverage.json", "checks.jsonl", "decisions.jsonl",
                  "publication.json")


def promote_record(staging: pathlib.Path, dest: pathlib.Path, force: bool = False,
                   guard=None) -> dict:
    """Copy a reviewed staging directory into its record, from one screened snapshot.

    The core of `promote`, lifted for `keep`: each refusal `promote` exits with
    is raised as `PromotionRefused`, with the same message. `guard`, when given,
    is called with the snapshot after every other check and before anything is
    written, so `keep` can test the bytes being promoted rather than staging.
    """
    from record_privacy import safe_record_files, require_screened, publication_problems, RECEIPT
    import tempfile
    safe_record_files(staging)
    names = PROMOTED_NAMES[:-1] + (RECEIPT,)
    # Capture once, inspect this snapshot, and copy only these exact normalized
    # bytes. A concurrent edit to staging cannot enter after screening.
    payload = {name: (staging / name).read_text(encoding="utf-8")
               for name in names if (staging / name).exists()}
    with tempfile.TemporaryDirectory(prefix="record-promotion-") as directory:
        snapshot = pathlib.Path(directory)
        for name, text in payload.items():
            (snapshot / name).write_text(text, encoding="utf-8")
        evidence = load_evidence(snapshot)
        if evidence.get("consent", {}).get("third_party_review") != "cleared":
            raise PromotionRefused("refusing to promote: consent.third_party_review is not 'cleared'.\n"
                                   "Read all record files, redact private material, then clear it.")
        result = evaluate_record(snapshot, strict_artifacts=True)
        problems = result["problems"] + publication_problems(snapshot, required=True)
        if problems:
            # Setting consent by hand after cover is the usual way here: say the
            # way back, since the refusal alone names only the stale digest (rc22).
            stale = any("changed since coverage was built" in p for p in problems)
            raise PromotionRefused(
                "refusing to promote: " + "; ".join(dict.fromkeys(problems))
                + ("\nTo recover: run cover again, then privacy-check and publication-review, "
                   "then promote. cover binds the files as it read them, so it runs after the "
                   "last edit to evidence.json, consent included." if stale else ""))
        require_screened(snapshot)
        if guard is not None:
            guard(snapshot)
    safe_record_files(dest)
    if dest.exists() and not force:
        raise PromotionRefused(f"{dest} exists; pass --force to overwrite")
    stale = [name for name in names if (dest / name).exists() and name not in payload]
    if stale:
        raise PromotionRefused("destination has record members absent from staging; use a fresh destination")
    dest.mkdir(parents=True, exist_ok=True)
    for name, text in payload.items():
        (dest / name).write_text(text, encoding="utf-8")
    redactions = sum(len(REDACTION_RE.findall(t["text"])) for t in evidence["turns"])
    return {"turns": len(evidence["turns"]), "redactions": redactions}


def cmd_promote(args: argparse.Namespace) -> int:
    staging, dest = pathlib.Path(args.staging), pathlib.Path(args.dest)
    try:
        result = promote_record(staging, dest, bool(args.force))
    except PromotionRefused as exc:
        sys.exit(str(exc))
    print(f"promoted {staging} -> {dest} ({result['turns']} turns, "
          f"{result['redactions']} declared redactions)")
    return 0


def build_coverage(record: pathlib.Path, exclusions: dict[str, str] | None = None) -> tuple[list[dict], list[str]]:
    """Write coverage.json for a record and return its entries and the uncovered turns.

    The core of `cover`, lifted for `keep`. `exclusions` maps a turn id to the
    reason somebody gave for leaving it out of the summary; each is written as
    an exclusion with that reason, and any other turn is covered as `cover`
    covers it.
    """
    from record_privacy import safe_record_files
    safe_record_files(record)
    evidence = load_evidence(record)
    summary_path = record / "summary.md"
    summary = summary_path.read_text(encoding="utf-8") if summary_path.exists() else ""

    cited = {f"T{n}" for n in TURN_REF_RE.findall(summary)}
    cov_path = record / "coverage.json"
    existing = {}
    if cov_path.exists():
        existing = {e["turn"]: e for e in json.loads(cov_path.read_text(encoding="utf-8"))["turns"]}

    entries, uncovered = [], []
    for turn in evidence["turns"]:
        tid = turn["id"]
        if exclusions and tid in exclusions:
            entries.append({"turn": tid, "status": "excluded", "reason": exclusions[tid]})
        # An exclusion somebody wrote, with its reason, stands even when the
        # summary names the turn, as a summary does to say why it is excluded;
        # re-covering once turned 35 such turns into summarized (AH-224).
        elif tid in existing and existing[tid].get("status") == "excluded" and existing[tid].get("reason"):
            entries.append(existing[tid])
        elif tid in cited:
            entries.append({"turn": tid, "status": "summarized"})
        elif tid in existing and existing[tid].get("status") == "excluded":
            entries.append(existing[tid])
        else:
            entries.append({"turn": tid, "status": "UNCOVERED",
                            "reason": "no summary entry cites this turn"})
            uncovered.append(tid)

    cov_path.write_text(json.dumps(
        {"record_id": evidence["record_id"],
         "summary_sha256": sha256_text(summary),
         "evidence_sha256": sha256_text((record / "evidence.json").read_text(encoding="utf-8")),
         "decisions_sha256": sha256_text((record / "decisions.jsonl").read_text(encoding="utf-8")) if (record / "decisions.jsonl").exists() else None,
         "checks_sha256": sha256_text((record / "checks.jsonl").read_text(encoding="utf-8")) if (record / "checks.jsonl").exists() else None,
         "turns": entries}, indent=2) + "\n", encoding="utf-8")
    return entries, uncovered


def cmd_cover(args: argparse.Namespace) -> int:
    """Map every raw turn to a summary entry or an explicit exclusion.

    A summary can be true in everything it says and still mislead by leaving
    things out. This makes omission visible rather than invisible.
    """
    entries, uncovered = build_coverage(pathlib.Path(args.record))
    print(f"coverage: {len(entries) - len(uncovered)}/{len(entries)} turns covered")
    if uncovered:
        print("UNCOVERED (cite them in summary.md, or set status 'excluded' "
              "with a reason):")
        for tid in uncovered:
            print(f"  {tid}")
    return 0


def is_exempt(sha: str) -> bool:
    """True if the commit predates the attribution rule."""
    result = subprocess.run(
        ["git", "merge-base", "--is-ancestor", sha, project_epoch("policy_epoch", POLICY_EPOCH)],
        capture_output=True,
    )
    return result.returncode == 0


def classify(body: str, exempt: bool) -> tuple[str, str]:
    """Who executed this commit, and on what basis.

    Pre-rule history is not simply out of scope. The vendor's old
    `Co-Authored-By: <model>` trailer, wrong as an authorship claim, is still
    evidence that a machine executed the work, so it can be read as a signal
    rather than discarded. Three classes, and the difference between the first
    two is never collapsed:

      declared       the commit says so itself, under the current rule
      inferred       read off the old trailer; probably right, not self-declared
      unknown        pre-rule, no signal either way. Stated as unknown, not guessed.
      none-declared  post-rule, no trailer: no machine declared itself. Read
                     as a commit a person typed, since under the rule a machine
                     declares and a person is asked to type nothing. That
                     reading is stated as the default it is, not as a declaration.
                     `Execution-agent: none` reads the same way (AH-137).
    """
    agents = declared_agents(body)
    if agents:
        # Normalise a legacy `agent:` prefix out of the tracked record. History
        # is not rewritten; the classification beside it is simply written
        # correctly.
        return "declared", agents[0]
    body = trailer_block(body)
    if not exempt:
        return "none-declared", ""
    match = AI_COAUTHOR_RE.search(body)
    if match:
        # The old trailer names the model in full ("Claude Fable 5"), so read all
        # of it rather than just the vendor word. A coarser value would throw
        # away attribution the history actually contains.
        model = "-".join(match.group(1).split()).lower()
        return "inferred", model
    return "unknown", ""


# One path per line. The separator class stops the capture at a comma or
# semicolon, because two commits on 2026-09-19 listed two records on one
# line and `\S+` swallowed the trailing comma, so a record that was there
# read as absent and the governing-actions report said T was missing.
RECORD_LINE_RE = re.compile(r"^Record:\s*([^\s,;]+)", re.MULTILINE)

# What a sentence adds after a record name. Two commits on 2026-09-21 wrote
# `Record: ai/records/20260921-base-case-rc11.` with a full stop, and the
# capture above kept it: `brief` found no commit for the record, `accept
# --record` had nothing to cover, and the report read the record as absent.
# A record id ends in a word character, so trailing punctuation is never
# part of the name.
RECORD_TRAILING = "/.,;:)"


def record_ref(text: str) -> str:
    """A record reference as a commit body or a person writes it, as a name."""
    return (text or "").strip().rstrip(RECORD_TRAILING)


def record_links(rev_range: str) -> list[dict]:
    """Which commits in a range name a trace record, and whether it exists.

    `draft-message` writes a `Record: ai/records/<id>` line into the commit body.
    That line is the join from a commit to the record of the session that
    produced it; without it a reader has to guess from dates. Pre-rule commits
    are skipped, as everywhere else.
    """
    log = git("log", "--format=%H%x00%B%x1e", rev_range, check=True)
    rows = []
    for entry in log.split("\x1e"):
        if not entry.strip():
            continue
        sha, _, body = entry.strip().partition("\x00")
        if is_exempt(sha):
            continue
        match = RECORD_LINE_RE.search(body)
        record = (record_ref(match.group(1)) or None) if match else None
        # The same reading as `queue`, `brief` and the report: a bare id is
        # ai/records/<id> (AH-136).
        record = record_key(record) if record else None
        exists = bool(record) and pathlib.Path(record).is_dir() and (pathlib.Path(record) / "evidence.json").exists()
        rows.append({"commit": sha, "record": record, "record_exists": exists})
    return rows


def check_range(rev_range: str) -> tuple[int, int, list[str], int]:
    """Read commit messages over a range, skipping pre-rule history.

    Returns (checked, exempt, problems, untrailed). One implementation so the
    publish script and a hand-run `verify-range` cannot disagree about what a
    message claims.
    `untrailed` counts post-rule commits whose trailers declare no machine (no
    execution trailer, or `Execution-agent: none`): commits a person typed,
    reported as a count and never as a problem.
    """
    log = git("log", "--format=%H%x00%B%x1e", rev_range, check=True)
    checked, exempt, problems, untrailed = 0, 0, [], 0
    for entry in log.split("\x1e"):
        if not entry.strip():
            continue
        sha, _, body = entry.strip().partition("\x00")
        if is_exempt(sha):
            exempt += 1
            continue
        checked += 1
        if not declared_agents(body):
            untrailed += 1
        for problem in commit_message_problems(body):
            problems.append(f"{sha[:8]}  {problem}")
    return checked, exempt, problems, untrailed


def cmd_backfill(args: argparse.Namespace) -> int:
    """Classify existing history without rewriting a single commit.

    Rewriting history to add trailers would need a rebase, which this project
    forbids and which would destroy the record it is trying to describe. So the
    attribution for past commits lives beside them, in a tracked file, marked as
    inferred rather than declared.

    An unreadable range is an execution error, and the file is replaced in one
    rename: a mistyped range exited 0 and emptied the tracked file (AH-129).
    """
    log = git("log", "--format=%H%x00%ad%x00%s%x00%B%x1e", "--date=short", args.range or "HEAD",
              check=True)
    rows, counts = [], {}
    for entry in log.split("\x1e"):
        if not entry.strip():
            continue
        sha, _, rest = entry.strip().partition("\x00")
        date, _, rest = rest.partition("\x00")
        subject, _, body = rest.partition("\x00")
        status, agent = classify(body, is_exempt(sha))
        counts[status] = counts.get(status, 0) + 1
        rows.append({"commit": sha, "date": date, "subject": subject,
                     "execution_agent": agent or None, "basis": status})

    out = pathlib.Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + ".tmp")
    tmp.write_text("".join(json.dumps(row) + "\n" for row in rows), encoding="utf-8", newline="\n")
    os.replace(tmp, out)

    print(f"{len(rows)} commits classified -> {out}")
    for status in ("declared", "inferred", "unknown", "none-declared"):
        if status in counts:
            print(f"  {status:>13}  {counts[status]}")
    if counts.get("unknown"):
        print("\n`unknown` is honest, not a gap to be filled by guessing. Set one "
              "by hand only if you actually know.")
    if counts.get("none-declared"):
        print("`none-declared` is a post-rule commit with no trailer: no machine "
              "declared itself, so it reads as typed by a person.")
    return 0


def cmd_verify_range(args: argparse.Namespace) -> int:
    """Report on every commit message in a range. Used at publish time and by hand.

    Report-only: it exits non-zero for an unreadable range and for nothing
    else. A false claim is printed so it is on the record; a commit with no
    trailer is counted as one a person typed. Blocking either would only stop
    the person, which is what the removed commit hook did.
    """
    checked, exempt, bad, untrailed = check_range(args.range)
    if checked == 0 and exempt == 0:
        print(f"no commits in {args.range}")
        return 0
    summary = f"{checked} commit message(s) read over {args.range}"
    if exempt:
        summary += f" ({exempt} exempt, predating the rule at {project_epoch('policy_epoch', POLICY_EPOCH)[:8]})"
    print(summary)
    if untrailed:
        print(f"  {untrailed} carry no execution trailer: read as typed by a person "
              f"(a count, not a problem)")
    links = record_links(args.range)
    if links:
        linked = sum(1 for row in links if row["record_exists"])
        dangling = sum(1 for row in links if row["record"] and not row["record_exists"])
        note = f"{linked} of {len(links)} name a trace record that exists"
        if dangling:
            note += f"; {dangling} name a record that is absent"
        print(f"  {note} (a count, not a failure: the governing-actions report reads it)")
    for line in bad:
        print(f"  {line}")
    if bad:
        print(f"\n{len(bad)} message(s) reported above. Nothing is blocked; see AGENTS.md.")
    elif checked:
        print("none claims AI authorship")
    return 0


def git(*args: str, check: bool = False) -> str:
    result = subprocess.run(["git", *args], capture_output=True, text=True,
                            encoding="utf-8", errors="replace")
    if check and result.returncode:
        raise ValueError(f"git {args[0]} failed: {result.stderr.strip()}")
    return result.stdout.strip()


# --- Review status: reviewed, reviewed by a model, or not reviewed -----------
#
# The third governing principle asks that acceptance be a distinct, recorded,
# accountable act by an actor independent of production. It does not ask that
# anything be blocked, and two earlier attempts here got that wrong: the first
# refused to publish an unaccepted state, the second refused to record a
# reviewer whose name read like a model. Both mistook the control for a bouncer.
#
# The control is honesty about status. Any published work sits in one of
# four states, and the record says which:
#
#   not reviewed          nobody has looked. A normal, publishable state.
#   reviewed by a model   a model raised objections over it. Useful, and not
#                         acceptance on its own: a favorable critique is not a
#                         decision (paper, Section 4).
#   accepted by a person  a named person took responsibility for it.
#   accepted by a delegated actor
#                         an agent, process or person independent of production,
#                         authorized by a named researcher, examined the evidence
#                         and recorded the decision. The researcher remains
#                         accountable for the delegation and for relying on the
#                         work (paper, Section 4; DECISIONS.md 2026-09-13). An
#                         actor that executed the work is not independent, so
#                         its attempt is recorded as self-review, not acceptance.
#
# Until 2026-09-13 the record allowed acceptance by a person only. The paper's
# move from coding to AI-assisted work generalized the accepting actor, and the
# repository, being the paper's demonstration, follows it.
#
# Nothing here refuses input. An agent may commit, an agent may review, and work
# may publish in any of the four states. What must never happen is that a
# reader cannot tell which state something is in, because that is when unreviewed
# work passes as accepted work.

ACCEPTANCES = pathlib.Path("ai/records/acceptances.jsonl")

# Commits at or before this one predate the review record and are reported as
# such rather than as a backlog.

# Used to CLASSIFY a reviewer, never to reject one. A name that reads like a
# model is recorded as model review, the conservative reading. A name that does
# not is recorded as `unknown`, never as a person: until 2026-09-15 every
# unrecognized name became "accepted by a person", so an adopter's local model
# called "deepseek" would have accepted work on a person's behalf.
MACHINE_NAMES = re.compile(
    r"\b(claude|gpt|opus|sonnet|haiku|fable|mythos|codex|gemini|llama|mistral|"
    r"kimi|glm|qwen|deepseek|grok|copilot|cursor|cline|devin|bot|model|agent)\b",
    re.I,
)
REVIEW_KINDS = ("human", "delegated", "agent", "unknown")
DECISIONS = ("accept", "return", "refuse")
SELF_REVIEW_DECISION = "self-review, not acceptance"
# A delegation is the researcher's name together with the words that
# authorized it (agentic_review.py, AH-154). A new delegated decision recorded
# without the words reads "not stated" and is advisory, as such a review run is.
AUTHORITY_NOT_STATED = "not stated"
NO_AUTHORITY_DECISION = "delegation with no authority stated, not acceptance"


def reviewer_kind(reviewer: str, declared: str | None = None) -> str:
    """'human', 'agent' or 'unknown'. A declared kind wins.

    Without a declaration a model-like name is classified as an agent and any
    other name as unknown. Nothing infers a person: acceptance by a person is a
    declared act (`--person`), because an inferred acceptance is the state
    conflation the record exists to prevent.
    """
    if declared in ("agent", "human"):
        return declared
    return "agent" if MACHINE_NAMES.search(reviewer or "") else "unknown"


# A CLI states a dated or bracketed model id where a trailer states the short
# one, and both name the same actor.
ID_BRACKET = re.compile(r"\[[^\[\]]*\]\s*$")
ID_DATE = re.compile(r"-\d{8}$")


def actor_id(name: str) -> str:
    """One model id as both sides of the comparison state it.

    A CLI reports `claude-haiku-4-5-20251001` or `claude-opus-5[1m]` where a
    trailer states `claude-haiku-4-5` or `claude-opus-5`, and those are the same
    actor. Case, a trailing bracketed suffix and a trailing eight-digit date come
    off; nothing else does, so this never matches by prefix or by lineage. It is
    for comparing only: a row records each id as it was given.
    """
    return ID_DATE.sub("", ID_BRACKET.sub("", name.strip()).strip()).casefold()


def load_acceptances() -> list[dict]:
    return read_registry(ACCEPTANCES, validate_acceptances)


def review_index() -> dict[str, list[dict]]:
    """Every review event, keyed by the commit it covers."""
    index: dict[str, list[dict]] = {}
    for row in load_acceptances():
        for sha in row.get("covers", []):
            index.setdefault(sha, []).append(row)
    return index


def reviewable_commits() -> list[str]:
    """Commits reachable from HEAD after the acceptance baseline set at install.

    The baseline (`accept_epoch`) is written once by the project's setup and is
    never advanced by an acceptance, so a commit never leaves this window
    because someone accepted it.
    """
    epoch = project_epoch("accept_epoch", ACCEPT_EPOCH)
    # A baseline this clone does not hold (a shallow clone of the research
    # repository) is an unreadable history, not an empty one; read quietly it
    # said nothing was waiting beside unaccepted work (AH-131).
    return [ln for ln in git("rev-list", f"{epoch}..HEAD", check=True).splitlines() if ln]


ACCEPTING_KINDS = ("human", "delegated")
STATE_LABELS = {
    "accepted-by-person": "accepted by a person",
    "accepted-delegated": "accepted by a delegated actor",
    "returned": "returned for correction",
    "refused": "refused",
    "model-reviewed": "reviewed by a model",
    "undeclared-actor": "reviewed by an undeclared actor",
    "unreviewed": "not reviewed",
}


# When two decisions on one commit carry the same second, the stricter stands:
# acceptance is never inferred from an ambiguity. A person's acceptance comes
# before a delegated one only so that a tie reads the same in every clone.
STRICTER_FIRST = {"refuse": 0, "return": 1, "accept": 2}
KIND_FIRST = {"human": 0, "delegated": 1}


def event_time(event: dict) -> dt.datetime | None:
    """The row's `at` as a UTC time, or None when it does not read as one."""
    text = event.get("at")
    if not isinstance(text, str) or not text.strip():
        return None
    text = text.strip()
    if text[-1:] in ("Z", "z"):
        text = text[:-1] + "+00:00"
    try:
        when = dt.datetime.fromisoformat(text)
    except ValueError:
        return None
    return when.replace(tzinfo=dt.timezone.utc) if when.tzinfo is None else when.astimezone(dt.timezone.utc)


def standing_decision(events: list[dict]) -> tuple[dict | None, bool]:
    """The decision by an accepting actor that stands over one commit, and
    whether it was chosen from conflicting decisions made in the same second.

    The latest decision stands, by its `at` and not by its place in the file:
    acceptances.jsonl is union-merged, so row order is whoever merged last, and
    the same accept and return read differently in two clones (AH-135). A row
    whose `at` does not read as a time was written before this mattered and is
    read first, in file order, as it always was. Decisions sharing the latest
    second are resolved by STRICTER_FIRST, never by position, and the second
    value says so. A self-review row is never a decision, whatever its kind.
    """
    accepting = [e for e in events
                 if e.get("kind") in ACCEPTING_KINDS and not e.get("self_review")]
    timed = [(event_time(e), e) for e in accepting]
    stamped = [(when, e) for when, e in timed if when is not None]
    if not stamped:
        return (accepting[-1] if accepting else None), False
    latest = max(when for when, _ in stamped)
    tied = [e for when, e in stamped if when == latest]
    tied.sort(key=lambda e: (STRICTER_FIRST.get(e.get("decision") or "accept", 0),
                             KIND_FIRST.get(e.get("kind"), 2),
                             json.dumps(e, sort_keys=True)))
    return tied[0], len({e.get("decision") or "accept" for e in tied}) > 1


def commit_state_detail(sha: str, index: dict[str, list[dict]]) -> str:
    """One of the STATE_LABELS keys for this commit.

    The latest decision by an accepting actor (a person or a delegated actor)
    wins, so work returned and then accepted reads as accepted, and work
    accepted and then refused reads as refused; `standing_decision` says which
    is latest. Without any accepting event, a model review or a self-review
    reads as model-reviewed and an event by an actor whose kind was never
    declared reads as undeclared-actor, which is not acceptance.
    """
    events = index.get(sha, [])
    standing, _ = standing_decision(events)
    if standing:
        decision = standing.get("decision") or "accept"
        if decision == "accept":
            return "accepted-by-person" if standing["kind"] == "human" else "accepted-delegated"
        if decision == "return":
            return "returned"
        if decision == "refuse":
            return "refused"
    if any(e.get("kind") == "agent" or e.get("self_review") for e in events):
        return "model-reviewed"
    if events:
        return "undeclared-actor"
    return "unreviewed"


def recorded_from_words(sha: str, index: dict[str, list[dict]]) -> bool:
    """Whether the decision that stands for this commit was typed by an agent
    from the person's words. The state is the same, accepted by a person; this
    says who was at the keyboard, which `review-status` counts separately."""
    latest, _ = standing_decision(index.get(sha, []))
    return bool(latest and latest.get("recorded_by"))


def accepted_own_work(sha: str, index: dict[str, list[dict]]) -> bool:
    """Whether the decision that stands for this commit is a person's acceptance
    of a commit that person typed: its git author, with no execution trailer.
    The state is the same, accepted by a person; `review-status` counts it
    apart, because the producer is not the accepter for people either."""
    latest, _ = standing_decision(index.get(sha, []))
    return bool(latest and latest.get("kind") == "human"
                and (latest.get("decision") or "accept") == "accept"
                and sha in (latest.get("own_work") or []))


def commit_state(sha: str, index: dict[str, list[dict]]) -> str:
    """'accepted', 'returned', 'refused', 'model-reviewed', 'undeclared-actor' or 'unreviewed'.

    Acceptance by a person and delegated acceptance both count as accepted;
    `commit_state_detail` keeps them apart for reporting.
    """
    detail = commit_state_detail(sha, index)
    return "accepted" if detail.startswith("accepted") else detail


def default_batch(kind: str, index: dict[str, list[dict]]) -> list[str]:
    """The commits a review of this kind covers when no range is given.

    A person's acceptance is the act a model review is waiting for, so the human
    default is every reviewable commit no person has accepted, the
    model-reviewed ones included. Selecting only unreviewed commits, which this
    did until 2026-09-07, meant a model review silently removed work from the
    batch the person was about to accept. A model keeps the narrower default of
    untouched commits, so a second reviewer starts where the first stopped.

    The kind comes from a declared flag or from the reviewer's name. That
    classifies the record; it authenticates nobody and shows no independence.
    """
    if kind in ACCEPTING_KINDS:
        return [c for c in reviewable_commits() if commit_state(c, index) != "accepted"]
    return [c for c in reviewable_commits() if commit_state(c, index) == "unreviewed"]


# Named after what was searched. The two defaults look at different sets, so a
# bare "nothing to review" would report one of them as if it were both.
EMPTY_BATCH = {
    "human": "nothing awaiting a person's acceptance since the review record began",
    "delegated": "nothing awaiting acceptance since the review record began",
    "agent": "nothing unreviewed since the review record began",
    "unknown": "nothing unreviewed since the review record began",
}


def _describe(sha: str) -> str:
    return f"{sha[:12]}  {git('log', '-1', '--format=%s', sha)}"


def cmd_accept(args: argparse.Namespace) -> int:
    """Record a review over a run of commits, or over one trace record.

    Refuses nothing; classifies everything. With `--record <id>` the covered
    commits are the ones whose body names that record, which is the unit a
    person actually reads (`queue` and `brief` above). With `--through <sha>`
    they are only those that are that commit or its ancestors: the version the
    brief showed, so a commit that lands after the person read it stays out.
    """
    person = bool(getattr(args, "person", False))
    reviewer = (args.by or "").strip()
    if not reviewer and person:
        # A person should not have to type their own name to accept their own
        # project's work; git already knows it. The actor kind is still
        # declared, by --person, and is never read off the name.
        reviewer = git("config", "user.name").strip()
    if not reviewer:
        print("name a reviewer with --by (a person, or the model that reviewed); "
              "with --person, git config user.name is used when --by is absent",
              file=sys.stderr)
        return 1

    authorized_by = (getattr(args, "authorized_by", "") or "").strip()
    authority = (getattr(args, "authority", "") or "").strip()
    record = record_ref(getattr(args, "record", ""))
    decision = (getattr(args, "decision", "") or "accept").strip().lower()
    if record and args.range:
        print("--record and --range name two different batches. Choose one.",
              file=sys.stderr)
        return 1
    if sum((bool(args.agent), bool(authorized_by), person)) > 1:
        print("--agent records advisory model review; --authorized-by records a "
              "delegated acceptance; --person records a person's own decision. "
              "Choose one.", file=sys.stderr)
        return 1
    if decision not in DECISIONS:
        print(f"--decision must be one of {', '.join(DECISIONS)}", file=sys.stderr)
        return 1
    if args.agent and decision != "accept":
        print("a model review raises objections; it records no accept, return or "
              "refuse decision. Use --person or --authorized-by for a decision.",
              file=sys.stderr)
        return 1
    recorded_by = (getattr(args, "recorded_by", "") or "").strip()
    words = (getattr(args, "words", "") or "").strip()
    if recorded_by and not person:
        print("--recorded-by records a person's own decision from their words; "
              "it goes with --person and --by <the person's name>.", file=sys.stderr)
        return 1
    if recorded_by and not words:
        print("an agent recording a person's decision keeps the words the person "
              "decided in: pass --words \"...\" verbatim.", file=sys.stderr)
        return 1
    if recorded_by and actor_id(reviewer) == actor_id(recorded_by):
        print("--recorded-by names the agent at the keyboard and --by the person "
              "who decided; they are two actors.", file=sys.stderr)
        return 1
    if authority and not authorized_by:
        print("--authority keeps the words that authorized a delegated decision; it goes "
              "with --authorized-by <the researcher who gave them>.", file=sys.stderr)
        return 1
    through_given = (getattr(args, "through", "") or "").strip()
    through = ""
    if through_given:
        through = git("rev-parse", "--verify", "--quiet", f"{through_given}^{{commit}}")
        if not through:
            # An abbreviation two commits share names neither (4949c1c F3); say
            # so, rather than that it names none.
            shared = ([ln for ln in git("rev-parse", f"--disambiguate={through_given}").splitlines()
                       if ln and git("cat-file", "-t", ln) == "commit"]
                      if re.fullmatch(r"[0-9a-fA-F]{4,39}", through_given) else [])
            if len(shared) > 1:
                print(f"--through {through_given} is ambiguous: {len(shared)} commits in this "
                      "repository begin with it; pass more of the commit the brief showed.",
                      file=sys.stderr)
                return 1
            print(f"--through {through_given} names no commit in this repository; pass the "
                  "commit the brief showed.", file=sys.stderr)
            return 1
    if authorized_by:
        kind, kind_basis = "delegated", "declared"
    elif person:
        kind, kind_basis = "human", "declared"
    elif args.agent:
        kind, kind_basis = "agent", "declared"
    else:
        kind = reviewer_kind(reviewer)
        kind_basis = "inferred from the name" if kind == "agent" else "not declared"

    if record:
        target = record_path(record)
        shas = record_commits(str(target))
        if not shas:
            print(f"no commit in the acceptance window names {target}", file=sys.stderr)
            return 1
    elif args.range:
        shas = [ln for ln in git("rev-list", args.range).splitlines() if ln]
        if not shas:
            print(f"no commits in {args.range}", file=sys.stderr)
            return 1
    else:
        shas = default_batch(kind, review_index())
        if not shas:
            print(EMPTY_BATCH[kind])
            return 0

    # A decision covers the version the person saw. The record's commits are
    # read when the decision is recorded, so without a bound a commit that
    # landed after the person read the brief would be covered by a decision
    # made before it existed. --through keeps the commits that are the named
    # commit or its ancestors, and the rest stay where they were.
    later = []
    if through:
        kept = set(reached_from(through, shas))
        later = [sha for sha in shas if sha not in kept]
        shas = [sha for sha in shas if sha in kept]
        if not shas:
            print(f"none of the {len(later)} commit(s) is {through[:12]} or an ancestor of it; "
                  "nothing recorded.", file=sys.stderr)
            return 1

    shas = list(reversed(shas))  # oldest first, the order a reviewer reads them
    later = list(reversed(later))
    bodies = {sha: git("log", "-1", "--format=%B", sha) for sha in shas}
    producers = sorted({agent for sha in shas for agent in declared_agents(bodies[sha])})
    # `GPT-6-ASTRA`, `gpt-6-astra[1m]` and `gpt-6-astra-20260101` are one
    # producer (actor_id); the row still records every id as it was given.
    produced_it = actor_id(reviewer) in {actor_id(p) for p in producers}
    # Selection, not only execution: an actor the covered records' decisions
    # name as having selected a choice took part in producing the work, as
    # agentic_review.py already reads it for its reviewer. A person's own
    # selection, recorded as a person's, is direction rather than production,
    # so it does not make that person's decision a self-review.
    read_from = ([record_path(record)] if record else
                 [record_path(r) for sha in shas for r in commit_records(bodies[sha])])
    selectors = record_selectors(read_from)
    # A decision row whose `selected_by` names the deciding person and states
    # no kind (d530637 F3) is read as that person's own choice, as one recorded
    # as a person's is, and the row says it was read so; a kind-less name that
    # reads like a model's stays a selector, as before.
    unstated_own = sorted({name for name, selector_kind in selectors
                           if kind == "human" and selector_kind == "unknown"
                           and actor_id(name) == actor_id(reviewer)
                           and reviewer_kind(name) != "agent"})
    selected_it = actor_id(reviewer) in {actor_id(name) for name, selector_kind in selectors
                                         if not (kind == "human" and selector_kind == "human")
                                         and not (selector_kind == "unknown" and name in unstated_own)}

    # Independence is definitional: an actor that executed any covered commit,
    # or selected a choice in its record, cannot accept it, declared a
    # delegated actor or a person. Until AH-134 only a delegated actor was
    # checked, so `--person --by gpt-9` over work gpt-9 executed read as a
    # person's acceptance. The match is on the execution trailers and the
    # recorded selectors, never on whether the name reads like a model. The
    # attempt is recorded, as self-review, so the state is never confused with
    # acceptance, and the kind it was declared as is kept beside it.
    declared_kind = kind
    downgraded = kind in ACCEPTING_KINDS and (produced_it or selected_it)
    # A delegation without the words that authorized it is recorded, reads
    # "authority not stated", and is advisory, as agentic_review.py records
    # such a run (AH-154). Rows written before --authority existed carry no
    # `authority` field and read as they always did.
    unauthorized = declared_kind == "delegated" and not authority
    if downgraded or unauthorized:
        kind = "agent"

    def stated(value: str, default: str) -> str:
        return (value or "").strip() or default

    scope = (args.scope or "").strip()
    if record and not scope:
        scope = f"brief of {record_path(record).name}"
    row = {
        "kind": kind,
        "kind_basis": kind_basis,
        "reviewer": reviewer,
        "at": dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "covers": shas,
        "count": len(shas),
        "scope": scope,
        "producer_agents": producers,
        # The selectors the covered records' decisions name, compared with the
        # accepting actor as the producers are.
        "selecting_actors": sorted({name for name, _ in selectors}),
        # An agent reviewing work it produced is the weakest reading of all, and
        # the record says so rather than pretending otherwise.
        "self_review": kind == "agent" and (produced_it or selected_it),
    }
    if kind in ACCEPTING_KINDS or downgraded or unauthorized:
        # What the paper asks an accepting actor to record: the work
        # examined (covers), the evidence considered, unresolved objections, its
        # decision, and the production roles it considered when calling itself
        # independent. The independence entry is a declaration: the tool reads
        # execution trailers and the recorded selectors, and cannot see who
        # proposed the work.
        row.update({
            "criteria": stated(getattr(args, "criteria", ""), "nothing stated"),
            "evidence": stated(getattr(args, "evidence", ""), "nothing stated"),
            "objections": stated(getattr(args, "objections", ""), "none stated"),
            "decision": (SELF_REVIEW_DECISION if downgraded else
                         NO_AUTHORITY_DECISION if unauthorized else decision),
            "independence": {
                "execution_producers": producers,
                "declared": stated(getattr(args, "independence", ""), "nothing stated"),
            },
        })
    else:
        # What a model or an undeclared actor stated is kept as advisory. It
        # was dropped without a word until AH-138, so a return and its
        # objection typed without --person vanished. It is never an operative
        # `decision`: only a person or a delegated actor decides.
        for field in ("criteria", "evidence", "objections"):
            if stated(getattr(args, field, ""), ""):
                row[field] = stated(getattr(args, field, ""), "")
        if stated(getattr(args, "independence", ""), ""):
            row["independence"] = {"execution_producers": producers,
                                   "declared": stated(getattr(args, "independence", ""), "")}
    if decision != "accept" and (kind not in ACCEPTING_KINDS or downgraded):
        row["decision_stated"] = decision
    if downgraded or unauthorized:
        row["declared_kind"] = declared_kind
    if authorized_by:
        row["authorized_by"] = authorized_by
        # The authorization's words, verbatim, so the limits of the delegation
        # can be read where the decision is.
        row["authority"] = authority or AUTHORITY_NOT_STATED
    if words:
        # The decision as the person stated it. With `recorded_by`, the person
        # said it to an agent, in chat or aloud, and the agent typed this
        # command in the person's name: the decision is the person's, the
        # keystroke is the agent's, and the row says both.
        row["words"] = words
    if recorded_by and downgraded:
        # Kept, but not as `recorded_by`: that field says a person's decision
        # was typed by an agent, and a self-review is no person's decision.
        row["recorded_by_stated"] = recorded_by
    elif recorded_by:
        row["recorded_by"] = recorded_by
    if record:
        # The commits are still listed in `covers`, which is what every reader
        # of this file joins on. This names the record they were read as.
        row["record"] = str(record_path(record)).replace("\\", "/")
    if through:
        # The version the decision was bound to. `covers` already says which
        # commits it reached; this says the bound was stated, not computed at
        # the moment of recording. Rows written without it are read as before.
        row["through"] = through
    if unstated_own and kind == "human":
        row["selection_note"] = (f"a choice in the covered records names {', '.join(unstated_own)} "
                                 "as its selector with no kind stated; read as the deciding "
                                 "person's own choice, which is direction, not production")
    if kind == "human":
        # The producer is not the accepter, for people too. A covered commit
        # this person typed (its git author, with no execution trailer) is
        # still the person's decision, never refused or downgraded; the row
        # names those commits so that `review-status` can say the person
        # decided about their own work. Rows written before this have no such
        # field and read as before.
        me = " ".join(reviewer.split()).casefold()
        own = [sha for sha in shas if not declared_agents(bodies[sha])
               and " ".join(git("log", "-1", "--format=%an", sha).split()).casefold() == me]
        if own:
            row["own_work"] = own
    finding, ledger_fault = None, ""
    if decision == "return" and kind in ACCEPTING_KINDS and not downgraded:
        # A return is a finding. The objection the person already stated is the
        # label, the person is the raiser, and the fix and its recheck are
        # recorded on that row, which is where E starts. A ledger that cannot
        # be read or written must not cost the person their recorded return,
        # so the fault is reported and the decision is written anyway.
        try:
            finding = return_finding(row, reviewer, record, shas, recorded_by,
                                     getattr(args, "severity", "") or "",
                                     getattr(args, "objects", None))
            row["defect"] = finding["id"]
        except Exception as exc:  # noqa: BLE001
            ledger_fault = f"{type(exc).__name__}: {exc}"
    ACCEPTANCES.parent.mkdir(parents=True, exist_ok=True)
    with ACCEPTANCES.open("a", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(row) + "\n")

    verb = {"accept": "accepted", "return": "returned", "refuse": "refused"}[decision]
    if unauthorized and not downgraded:
        verb = "reviewed (advisory: authority not stated)"
    elif kind == "agent":
        verb = "reviewed (model)"
    elif kind == "unknown":
        verb = "reviewed (actor kind not declared)"
    under = f" under {authorized_by}'s authority" if kind == "delegated" else ""
    of_record = f" of {row['record']}" if record else ""
    print(f"{reviewer} {verb} {row['count']} commit(s){of_record}{under} at {row['at']}:\n")
    for sha in shas:
        print(f"  {_describe(sha)}")
    if through:
        print(f"\nBound by --through to {through[:12]}: the covered commits are it and its ancestors.")
        if later:
            print(f"{len(later)} later commit(s) are not covered by this decision; any nobody "
                  "has accepted stay waiting in queue:")
            for sha in later:
                print(f"  {_describe(sha)}")
    else:
        # What the recording agent compares with the commit the brief showed.
        print(f"\nThe newest commit covered is {shas[-1][:12]}.")
        if record:
            print("If the brief the person read showed an earlier one, this decision also covers")
            print("commits that landed after it; --through <the commit the brief showed> binds")
            print("a decision to the version the person saw.")
    if "selection_note" in row:
        print(f"\nNote: {row['selection_note']}.")
    if downgraded:
        took_part = " and ".join(part for part, did in (
            ("executed commit(s) in this batch", produced_it),
            ("selected a choice recorded in its trace record(s)", selected_it)) if did)
        print(f"\nNOT independent: {reviewer} {took_part}, so it")
        print("cannot accept them. Recorded as self-review, not as acceptance.")
        if unauthorized:
            print(f"Authority not stated: --authorized-by names {authorized_by}, and no")
            print("authorization was given in --authority.")
        if recorded_by:
            print(f"Typed by {recorded_by} from the words {words!r}, which the row keeps;")
            print("a self-review is no person's decision.")
    elif kind == "delegated":
        print(f"\nRecorded as a delegated decision: {decision}. "
              f"{authorized_by} remains accountable")
        print("for the delegation and for relying on the work.")
        print(f"Authority, verbatim: {authority}")
        for field in ("criteria", "evidence"):
            if row[field] == "nothing stated":
                print(f"No {field} stated. Recorded as-is; the accepting actor is asked to")
                print("record what it examined, so this entry can be revisited.")
    elif unauthorized:
        print(f"\nAuthority not stated: --authorized-by names {authorized_by}, and no authorization")
        print("was given; its words go in --authority, verbatim. A delegation is the researcher's")
        print("name together with those words, so this is recorded as advisory review, not as a")
        print("delegated decision, and the row says authority not stated.")
    elif kind == "human":
        print(f"\nRecorded as a person's decision: {decision}.")
        if row.get("own_work"):
            print(f"{reviewer} is the git author of {len(row['own_work'])} covered commit(s) with no "
                  "execution trailer:")
            print("the person decided about their own work. It stays a person's decision; the row")
            print("names those commits in own_work, and review-status counts them.")
        if recorded_by:
            print(f"Recorded by {recorded_by} from {reviewer}'s words: {words!r}")
            executed = sum(1 for p in producers if actor_id(p) == actor_id(recorded_by))
            if executed:
                print(f"{recorded_by} also executed covered commit(s); the decision is the")
                print("person's and the keystroke is the agent's, and the row says both.")
    elif kind == "agent":
        print("\nRecorded as model review, which raises objections and does not")
        print("carry accountability. Acceptance is a separate act by an authorized")
        print("actor independent of production.")
        if row["self_review"]:
            print("Flagged as self-review: this model also produced or selected the work.")
    else:
        print("\nRecorded with the actor kind NOT DECLARED. This is not acceptance.")
        print("Pass --person, --agent or --authorized-by to say who reviewed.")
    if "decision_stated" in row:
        why = ("a self-review decides nothing" if downgraded else
               "a delegation with no authority stated decides nothing" if unauthorized else
               "only a person (--person) or a delegated actor (--authorized-by) decides")
        print(f"The stated decision, {decision}, is kept in the row as decision_stated and is")
        print(f"not recorded as a decision: {why}, so no ledger row was opened.")
    advisory = [f for f in ("objections", "evidence", "criteria", "independence") if f in row]
    if advisory and kind not in ACCEPTING_KINDS and not (downgraded or unauthorized):
        print(f"Kept as advisory: {', '.join(advisory)}.")
    if kind in ACCEPTING_KINDS and row["independence"]["declared"] == "nothing stated":
        print("No independence declaration. Only execution trailers and the selectors in the")
        print("record's decisions were compared; participation in proposing the work is not")
        print("visible here.")
    if decision != "accept" and kind in ACCEPTING_KINDS:
        print(f"The covered work is {verb}; it stays unaccepted until a later decision accepts it.")
    if finding:
        print(f"Opened ledger row {finding['id']} from the objection, raised by {reviewer}: "
              f"the fix is marked there and the recheck, in the raiser's words, verifies it.")
        if finding.get("objects"):
            print(f"It lists the {len(finding['objects'])} object(s) the person named, each "
                  "verified by its own passing recheck.")
    elif ledger_fault:
        print(f"The return is recorded; the ledger row could not be opened: {ledger_fault}. "
              "Open it with defect_ledger.py open once the ledger reads.")
    print(f"\nRecorded in {ACCEPTANCES}.")
    return 0


def return_finding(row: dict, reviewer: str, record: str, shas: list[str],
                   recorded_by: str, severity: str, objects: list[str] | None = None) -> dict:
    """Open the ledger row a return implies, from the objection as the person stated it.

    The row has the shape `defect_ledger.py open` writes: the objection is the
    label, the person is the raiser, the record the return covered is the
    affected record. The severity is the person's when stated and medium
    otherwise, which the note says. The outputs the defect reaches are listed
    only when the person named them (`--object`); none is inferred from the
    commits. Nothing here decides anything about the work; it records that a
    person sent it back, so that the fix and its recheck have a row to land on.
    """
    import defect_ledger as dl
    objections = (row.get("objections") or "").strip()
    label = objections if objections and objections != "none stated" else "returned with no objection stated"
    if record:
        affected = [str(record_path(record)).replace("\\", "/")]
    else:
        affected = sorted({r for sha in shas for r in commit_records(git("log", "-1", "--format=%B", sha))})
    note = f"returned by {reviewer} at {row['at']} over {len(shas)} commit(s)"
    if recorded_by:
        note += f", recorded by {recorded_by} from the person's words"
    if not severity:
        note += "; severity medium by default, not stated by the person"
    extra = {"returned": {"by": reviewer, "at": row["at"], "covers": shas,
                          "record": affected[0] if record else None,
                          "words": row.get("words"), "recorded_by": recorded_by or None}}
    path = dl.ledger_path()
    rows = dl.load(path)
    finding = dl.open_finding(rows, label, severity or "medium", by=reviewer, note=note,
                              affected=affected or None, extra=extra, objects=objects)
    dl.save(rows, path)
    return finding


def cmd_review_status(args: argparse.Namespace) -> int:
    """Say what has been reviewed, by whom, and what has not. Never blocks."""
    index = review_index()
    states = {key: [] for key in STATE_LABELS}
    for sha in reviewable_commits():
        states[commit_state_detail(sha, index)].append(sha)

    total = sum(len(v) for v in states.values())
    if total == 0:
        print("review status: no commits since the review record began")
        return 0

    print(f"review status over {total} commit(s) since the record began:")
    for key, label in STATE_LABELS.items():
        if states[key] or key in ("accepted-by-person", "accepted-delegated",
                                  "model-reviewed", "unreviewed"):
            print(f"  {label:<32}{len(states[key]):3d}")
        if key == "accepted-by-person":
            from_words = sum(1 for sha in states[key] if recorded_from_words(sha, index))
            if from_words:
                print(f"    of which an agent recorded from the person's words {from_words:3d}")
            # The producer is not the accepter, for people too: a commit the
            # person typed and then accepted stays accepted by a person, and is
            # counted here so that it is never read as independent acceptance.
            own = sum(1 for sha in states[key] if accepted_own_work(sha, index))
            if own:
                print(f"    of which the person accepted their own work {own:3d}")
    same_second = sum(1 for key in states for sha in states[key]
                      if standing_decision(index.get(sha, []))[1])
    if same_second:
        print(f"\n{same_second} commit(s) carry conflicting decisions made in the same second; the")
        print("stricter one stands (refuse over return over accept), whatever the order of the")
        print(f"rows in {ACCEPTANCES}, so every clone reads the same state.")

    for label, key in (("not reviewed", "unreviewed"),
                       ("reviewed by a model only", "model-reviewed"),
                       ("reviewed by an undeclared actor only", "undeclared-actor"),
                       ("returned for correction", "returned"),
                       ("refused", "refused")):
        shas = list(reversed(states[key]))
        if not shas:
            continue
        print(f"\n{label}:")
        for sha in shas[: args.limit]:
            print(f"  {_describe(sha)}")
        if len(shas) > args.limit:
            print(f"  ... and {len(shas) - args.limit} more")

    if states["unreviewed"] or states["model-reviewed"] or states["undeclared-actor"]:
        print("\nThis is a report. Work publishes in any of these states; what the")
        print("record keeps apart is which declared state each commit is in.")
        print('\n  python3 scripts/trace_record.py accept --person --by "Your Full Name" \\')
        print('      --scope "what you reviewed"')
        print('  python3 scripts/trace_record.py accept --by "<actor>" \\')
        print('      --authorized-by "Your Full Name" --authority "<your words, verbatim>" \\')
        print('      --evidence <what it examined>')
    return 0


# --- The acceptance queue: what is waiting, and what one record holds -------
#
# `review-status` answers "what stands where" over every commit at once. Asked
# "what should I accept?", it printed 434 unaccepted commits and left the
# reader to work out which of them needed them, which is not a question a
# person can answer by reading a list that long.
#
# So the unit of acceptance becomes the trace record, which is the object that
# already holds the human's words, the agent's choices and the checks. A commit
# joins its record through the `Record: ai/records/<id>` line in its body, the
# same join `trace_report.py` reads.
#
#   queue            the records with commits nobody has accepted, newest first
#   brief <id>       one record on one screen, assembled from its own files
#   accept --record  covers exactly that record's commits
#
# Nothing here blocks, nothing here accepts, and the label triages rather than
# decides: `needs you` says a person's judgment is likely to be wanted, and is
# never a claim that `routine` work is approved.

MANIFEST_PATH = "starter/export-manifest.json"
MANIFEST_VERSION_RE = re.compile(r'^\+\s*"version":\s*"')
QUEUE_LABELS = ("needs you", "routine")
NO_CHOICES_REASON = "no choices recorded"


def _trace_report():
    """The governing-actions report, imported lazily.

    `trace_report` imports this module at its top, so importing it at this
    module's top would be circular. Reading its INSTRUCTION_PATHS rather than
    copying the tuple keeps one definition of what counts as an instruction.
    """
    directory = str(pathlib.Path(__file__).resolve().parent)
    if directory not in sys.path:
        sys.path.insert(0, directory)
    import trace_report
    return trace_report


def queue_paths() -> tuple[str, ...]:
    """The paths whose change asks for a person: instructions, and the manuscript."""
    return tuple(_trace_report().INSTRUCTION_PATHS) + MANUSCRIPT_PATHS


# The manuscript is watched with the standing instructions and said apart from
# them: a change to it is shared text the coauthors rely on, not an instruction
# every later session works under (rc22; queue and brief said the latter of both).
MANUSCRIPT_PATHS = ("paper/",)


def is_manuscript(path: str) -> bool:
    """Whether a changed file is part of the manuscript rather than an instruction."""
    return any(path == p.rstrip("/") or path.startswith(p) for p in MANUSCRIPT_PATHS)


def commit_records(body: str) -> list[str]:
    """Every trace record a commit body names, in order, without repeats.

    `trace_report` reads the first `Record:` line per commit. A commit can
    carry two, so every line is read here; a second record after a comma on one
    line is not captured, exactly as there. Each is in its canonical form
    (`record_key`), so a bare id and the full path group as one record.
    """
    found = []
    for match in RECORD_LINE_RE.finditer(body or ""):
        record = record_ref(match.group(1))
        if record and record_key(record) not in found:
            found.append(record_key(record))
    return found


def _log_rows(shas: list[str], with_files: bool = False) -> list[dict]:
    """Subject, date, body and optionally files for the given commits.

    One `git log` per two hundred commits rather than one per commit. A merge
    is compared with its first parent, the branch that received it, as the
    governing-actions report does.
    """
    rows, fmt = [], "%x1e%H%x00%P%x00%as%x00%s%x00%B%x00"
    for start in range(0, len(shas), 200):
        chunk = [s for s in shas[start:start + 200] if s]
        if not chunk:
            continue
        options = ["log", "--no-walk=unsorted", f"--format={fmt}"]
        if with_files:
            options.append("--name-only")
        for entry in git(*options, *chunk, check=True).split("\x1e"):
            if not entry.strip():
                continue
            sha, _, rest = entry.partition("\x00")
            parents, _, rest = rest.partition("\x00")
            date, _, rest = rest.partition("\x00")
            subject, _, rest = rest.partition("\x00")
            body, _, files = rest.partition("\x00")
            row = {"commit": sha.strip(), "date": date.strip(),
                   "subject": subject.strip(), "body": body}
            if with_files:
                paths = [ln.strip() for ln in files.splitlines() if ln.strip()]
                if len(parents.split()) > 1:
                    paths = [ln.strip() for ln in git("diff", "--name-only",
                                                      parents.split()[0], row["commit"],
                                                      check=True).splitlines() if ln.strip()]
                row["files"] = paths
            rows.append(row)
    return rows


def record_path(record: str) -> pathlib.Path:
    """`20260921-thing`, `ai/records/20260921-thing` and this repository's
    absolute path to it name the same record, read as `ai/records/20260921-thing`.

    Every reader of a `Record:` line goes through here (AH-136): two commits
    name a record by its bare id, and `queue` counted them while `brief`,
    `accept --record`, `verify-range` and the report found no commit or no
    record. A path anywhere else, a staging directory or another checkout,
    stays as written, so a draft is never read as the record it may become.
    """
    text = record_ref(record)
    path = pathlib.Path(text)
    if len(path.parts) == 1:
        return pathlib.Path("ai/records") / text
    if path.is_absolute():
        try:
            return path.resolve().relative_to(pathlib.Path.cwd().resolve())
        except (OSError, ValueError):
            return path
    return path


def record_key(record: str) -> str:
    """The one text form of a record reference, for joining and grouping."""
    return record_path(record).as_posix()


def record_commits(record: str, shas: list[str] | None = None) -> list[str]:
    """The commits in the acceptance window whose body names this record.

    Newest first, the order `rev-list` gives, so the caller reverses it the way
    a range is reversed.
    """
    wanted = record_key(record)
    pool = reviewable_commits() if shas is None else shas
    return [row["commit"] for row in _log_rows(pool)
            if wanted in commit_records(row["body"])]


def reached_from(bound: str, shas: list[str], window: bool = False) -> list[str]:
    """The given commits that are `bound` or an ancestor of it, in their order.

    With `window`, only the commits after the acceptance baseline are walked,
    which answers the same for commits inside the window and reads far less.
    """
    spec = f"{project_epoch('accept_epoch', ACCEPT_EPOCH)}..{bound}" if window else bound
    reach = set(git("rev-list", spec, check=True).splitlines())
    return [sha for sha in shas if sha in reach]


def version_bound(shas: list[str]) -> tuple[str, bool]:
    """The commit that names the version a person reads: the newest of these
    commits when every other one is its ancestor, and HEAD otherwise.

    `shas` is newest first, as `record_commits` gives it. A decision recorded
    with `accept --through <bound>` covers these commits and none that lands
    after them. When the commits sit on more than one line of history (two
    branches merged), no one of them reaches the rest, so the bound is the
    commit checked out, which reaches all of them; the second value says so.
    """
    if len(shas) < 2 or len(reached_from(shas[0], shas, window=True)) == len(shas):
        return shas[0], False
    return git("rev-parse", "HEAD", check=True), True


def record_turns(record: pathlib.Path) -> list[dict]:
    """The human turns of a record, or an empty list when it is not on disk."""
    path = record / "evidence.json"
    if not path.exists():
        return []
    try:
        evidence = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return []
    turns = evidence.get("turns") if isinstance(evidence, dict) else None
    return [t for t in turns if isinstance(t, dict)] if isinstance(turns, list) else []


def record_rows(record: pathlib.Path, name: str) -> list[dict]:
    """One JSONL member of a record, skipping lines that do not parse."""
    path = record / name
    if not path.exists():
        return []
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            row = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(row, dict):
            rows.append(row)
    return rows


def trimmed(text: str, width: int) -> str:
    """One line, collapsed, cut at `width` with the cut declared."""
    flat = " ".join((text or "").split())
    return flat if len(flat) <= width else flat[: width - 3].rstrip() + "..."


def agent_selections(record: pathlib.Path) -> int:
    """Choices the record says an agent selected."""
    count = 0
    for row in record_rows(record, "decisions.jsonl"):
        selector = row.get("selected_by")
        if isinstance(selector, dict) and selector.get("kind") == "agent":
            count += 1
    return count


def record_selectors(records: list[pathlib.Path]) -> list[tuple[str, str]]:
    """Each actor these records' decisions name in `selected_by`, with the kind
    the row declares, in the order first met.

    Every row with a named selector counts, as agentic_review.py reads it for
    its reviewer; a record not on disk names nobody.
    """
    out: list[tuple[str, str]] = []
    for record in dict.fromkeys(records):
        for row in record_rows(record, "decisions.jsonl"):
            selector = row.get("selected_by")
            if not isinstance(selector, dict):
                continue
            name = str(selector.get("name") or "").strip()
            pair = (name, str(selector.get("kind") or "unknown"))
            if name and pair not in out:
                out.append(pair)
    return out


NOT_OWNER_SPEAKERS = {"unattributed", "unknown", "?"}


def record_owners(record: pathlib.Path) -> tuple[list[str], str]:
    """Who owns the record's work, and on what basis.

    The owners its decision rows name, when any does; else the people whose
    turns it cites, in summary.md or as a choice's human input, leaving out a
    turn coverage.json excludes; else none, and the basis reads "not stated".
    Nothing is inferred from who committed or who spoke most.
    """
    rows = record_rows(record, "decisions.jsonl")
    named = [o.strip() for row in rows for o in (row.get("owners") or [])
             if isinstance(o, str) and o.strip()]
    if named:
        return list(dict.fromkeys(named)), "decision rows"
    cited = set()
    summary = record / "summary.md"
    if summary.exists():
        try:
            cited |= {f"T{n}" for n in TURN_REF_RE.findall(summary.read_text(encoding="utf-8"))}
        except OSError:
            pass
    cited |= {t for row in rows for t in (row.get("human_inputs") or []) if isinstance(t, str)}
    cited -= excluded_turns(record)
    speakers = [str(t.get("speaker")).strip() for t in record_turns(record)
                if t.get("id") in cited and isinstance(t.get("speaker"), str)
                and t["speaker"].strip() and t["speaker"].strip() not in NOT_OWNER_SPEAKERS
                and t.get("speaker_kind", "human") == "human"]
    if speakers:
        return list(dict.fromkeys(speakers)), "speakers of the cited turns"
    return [], "not stated"


def owners_text(owners: list[str], basis: str) -> str:
    """One cell: the names, with the basis when it is not the decision rows."""
    if not owners:
        return "not stated"
    names = ", ".join(owners)
    return names if basis == "decision rows" else f"{names} ({basis})"


def intake_citations(record_id: str) -> int:
    """Intake rows that name this record as their authority or material.

    The id is matched whole: a hyphen, a letter, a digit or an underscore on
    either side makes it part of a longer id, so a row citing
    `20260922-accept-from-words-postcheck` does not cite
    `20260922-accept-from-words` (AH-142).
    """
    try:
        rows = load_jsonl(INTAKE)
    except (OSError, json.JSONDecodeError):
        return 0
    whole = re.compile(rf"(?<![A-Za-z0-9_-]){re.escape(record_id)}(?![A-Za-z0-9_-])")
    return sum(1 for row in rows
               if isinstance(row, dict) and whole.search(json.dumps(row, ensure_ascii=False)))


def changes_kit_version(sha: str) -> bool:
    """True when this commit changes the kit's released version."""
    diff = git("show", "--format=", "--unified=0", sha, "--", MANIFEST_PATH)
    return any(MANIFEST_VERSION_RE.match(line) for line in diff.splitlines())


def defect_rows_naming(record: pathlib.Path) -> list[dict]:
    """The ledger rows whose `affected` names this record, by path or by id."""
    try:
        import defect_ledger as dl
        rows = dl.load(dl.ledger_path())
    except (OSError, ValueError, json.JSONDecodeError, ImportError):
        return []
    here, name = str(record).replace("\\", "/").rstrip("/"), record.name
    out = []
    for row in rows:
        if not isinstance(row, dict):
            continue
        affected = row.get("affected") or []
        if any(isinstance(a, str) and (a.replace("\\", "/").rstrip("/") in (here, name)
                                       or a.replace("\\", "/").rstrip("/").endswith("/" + name))
               for a in affected):
            out.append(row)
    return out


def awaiting_recheck(rows: list[dict]) -> list[dict]:
    """Fixed rows nobody has rechecked: a repair claim with no event that states an
    outcome behind it. An event whose outcome is `not stated` is kept on the row
    and is not a recheck, so it does not clear the row from here. A row that lists
    the objects the defect reaches waits until each of them has its own passing
    recheck, so one rechecked table does not clear it."""
    def rechecked(row: dict) -> bool:
        return any(isinstance(e, dict) and str(e.get("outcome", "")).strip().lower() in ("pass", "fail")
                   for e in (row.get("verifications") or []))
    return [r for r in rows if r.get("state") == "fixed"
            and (not rechecked(r) or bool(object_coverage(r)[1]))]


def object_coverage(row: dict) -> tuple[list[str], list[str]]:
    """The row's objects split into rechecked and still waiting, from the ledger's
    own reading; two empty lists for a row that lists none, or without the ledger."""
    try:
        import defect_ledger as dl
    except ImportError:
        return [], []
    return dl.object_coverage(row) if dl.row_objects(row) else ([], [])


def objects_rechecked(row: dict) -> str:
    """'1 of 3 objects rechecked', or '' for a row that lists no objects."""
    done, waiting = object_coverage(row)
    total = len(done) + len(waiting)
    return f"{len(done)} of {total} objects rechecked" if total else ""


def e_waiting() -> dict:
    """What E is waiting on across the whole project: fixed ledger rows with no
    recheck, fixed rows that list objects not all rechecked (under
    `fixed_objects_awaiting_recheck`, present only when there is one), closed
    rows no sweep closed and no recheck reached, closed by hand or before the
    kit recorded how (under `closed_without_recheck`, present only when there is
    one), and adoptions with no later-run observation. Counts and ids, no
    judgment."""
    try:
        import defect_ledger as dl
        ledger = [r for r in dl.load(dl.ledger_path()) if isinstance(r, dict)]
        closed = [r.get("id", "?") for r in ledger if dl.closed_without_recheck(r)]
    except (OSError, ValueError, json.JSONDecodeError, ImportError):
        ledger, closed = [], []
    pending = awaiting_recheck(ledger)
    rechecks = [r.get("id", "?") for r in pending if not objects_rechecked(r)]
    # A row that lists the objects the defect reaches is counted per object,
    # apart from the rows above, whose meaning stays what it was.
    by_object = []
    for r in pending:
        done, left = object_coverage(r)
        if done or left:
            by_object.append({"id": r.get("id", "?"), "rechecked": len(done),
                              "objects": len(done) + len(left)})
    try:
        transitions = [t for t in load_jsonl(TRANSITIONS) if isinstance(t, dict)]
    except (OSError, json.JSONDecodeError):
        transitions = []
    # A link written at adoption time, with no observer, is counted with the
    # rows that have no link at all: nobody has said what the run showed.
    adoptions = [t.get("id", "?") for t in transitions
                 if t.get("kind") == "default-adoption" and t.get("decision", "adopt") == "adopt"
                 and not t.get("later_run_kind")]
    waiting = {"fixed_awaiting_recheck": rechecks, "adoptions_awaiting_observation": adoptions}
    if by_object:
        waiting["fixed_objects_awaiting_recheck"] = by_object
    if closed:
        waiting["closed_without_recheck"] = closed
    return waiting


def e_waiting_sentence(waiting: dict) -> str:
    rechecks, adoptions = waiting["fixed_awaiting_recheck"], waiting["adoptions_awaiting_observation"]
    by_object = waiting.get("fixed_objects_awaiting_recheck") or []
    closed = waiting.get("closed_without_recheck") or []
    if not rechecks and not adoptions and not by_object and not closed:
        return ("E is waiting on nothing: no fixed or hand-closed ledger row lacks a recheck and no "
                "adoption lacks a later-run observation.")

    def listed(ids: list[str], sep: str = ", ") -> str:
        shown = sep.join(ids[:6])
        return shown + (f" and {len(ids) - 6} more" if len(ids) > 6 else "")
    parts = []
    if rechecks:
        parts.append(f"{len(rechecks)} fixed ledger row(s) with no recheck ({listed(rechecks)})")
    if by_object:
        counts = [f"{r['id']}: {r['rechecked']} of {r['objects']} objects rechecked" for r in by_object]
        parts.append(f"{len(by_object)} fixed ledger row(s) with objects still to recheck "
                     f"({listed(counts, '; ')})")
    if closed:
        parts.append(f"{len(closed)} ledger row(s) closed other than by a sweep, with no recheck "
                     f"({listed(closed)})")
    if adoptions:
        parts.append(f"{len(adoptions)} adoption(s) with no later-run observation ({listed(adoptions)})")
    return "E is waiting on " + " and ".join(parts) + "."


def standing_returns(rows: list[dict]) -> list[str]:
    """The returns and refusals that stand on these commits, one reason each.

    The latest decision by an accepting actor on a commit is the one that
    stands, as `commit_state_detail` reads it, so a later acceptance of the
    same commits ends a return. A return names the ledger row it opened, which
    the acceptance row carries as `defect`.
    """
    index = review_index()
    standing = []
    for row in rows:
        latest, _ = standing_decision(index.get(row["commit"], []))
        if latest and latest.get("decision") in ("return", "refuse") and latest not in standing:
            standing.append(latest)
    reasons = []
    for event in standing:
        verb = "returned" if event["decision"] == "return" else "refused"
        reason = f"{verb} by {event.get('reviewer') or 'an unnamed actor'}"
        if event.get("defect"):
            reason += f", ledger row {event['defect']} opened from the objection"
        reasons.append(reason)
    return reasons


def queue_label(record: pathlib.Path, rows: list[dict]) -> tuple[str, list[str]]:
    """`needs you` with its reasons, or `routine`. A triage, never a decision.

    Seven triggers, each of them a thing a person is the right reader of: the
    latest decision on its commits is a return or a refusal, a standing
    instruction or the manuscript changed, the kit's version changed, an agent
    selected a consequential choice, the record logs no choice at all, outside
    material entered citing this record, or a fix on a ledger row that names
    it awaits a recheck.
    """
    # First, so the decision already made is never the part a long cell cuts.
    reasons = standing_returns(rows)
    watched = queue_paths()
    touched = sorted({f for row in rows for f in row.get("files", [])
                      if any(f == p.rstrip("/") or f.startswith(p) for p in watched)})
    # Standing instructions and the manuscript are two reasons, so neither is
    # said in the other's words.
    for group, lead in (([f for f in touched if not is_manuscript(f)], "changes "),
                        ([f for f in touched if is_manuscript(f)], "changes the manuscript: ")):
        if not group:
            continue
        listed = ", ".join(group[:3])
        if len(group) > 3:
            listed += f" and {len(group) - 3} more"
        reasons.append(f"{lead}{listed}")
    if any(changes_kit_version(row["commit"]) for row in rows):
        reasons.append(f"a release: the version changes in {MANIFEST_PATH}")
    selections = agent_selections(record)
    if selections:
        reasons.append(f"{selections} consequential choice(s) an agent selected")
    if not record_rows(record, "decisions.jsonl"):
        # A record that logs no choice says nothing about who chose what, which
        # is not the same as an agent having chosen nothing; it is never routine.
        reasons.append(NO_CHOICES_REASON)
    citations = intake_citations(record.name)
    if citations:
        reasons.append(f"{citations} intake row(s) cite this record")
    pending = awaiting_recheck(defect_rows_naming(record))
    if pending:
        reasons.append(f"{len(pending)} ledger row(s) fixed and awaiting a recheck")
    if reasons:
        return "needs you", reasons
    return "routine", ["no return or refusal, no instruction or manuscript change, no release, "
                       "choices recorded and none agent-selected, no intake, no fix awaiting a recheck"]


# --- The decision table: three sentences per waiting record --------------------
#
# A person deciding reads one sentence on what the decision is, one on what
# hangs on it, and one on where it comes from. Every sentence here comes
# from the record's own files, from git or from the registries; the agent adds
# in chat what only reading tells, and nothing here recommends.

def summary_title(record: pathlib.Path) -> str:
    """The record's own one-line title, without a leading date, or empty."""
    path = record / "summary.md"
    if not path.exists():
        return ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# "):
            return re.sub(r"^\d{4}-\d{2}-\d{2}:\s*", "", line[2:].strip())
    return ""


def _sentence(text: str) -> str:
    flat = " ".join((text or "").split()).rstrip(".")
    if not flat:
        return ""
    return flat[0].upper() + flat[1:] + "."


# Paths whose size says nothing about substance: the record files, frozen
# evidence, and generated JSON such as manifests, registries and check output.
BULK_PATHS = ("ai/records/", "sources/coding/")
BULK_SUFFIXES = (".json", ".jsonl")


def _bulk(path: str) -> bool:
    return path.startswith(BULK_PATHS) or path.endswith(BULK_SUFFIXES)


def _lines_changed(shas: list[str]) -> dict[str, int]:
    """Lines added plus removed per commit, outside the bulk paths, in one git
    call per two hundred commits. A record or evidence commit is large in
    bytes and small in substance, so those files do not count."""
    out = {sha: 0 for sha in shas}
    for start in range(0, len(shas), 200):
        chunk = [s for s in shas[start:start + 200] if s]
        if not chunk:
            continue
        text = git("log", "--no-walk=unsorted", "--format=%x1e%H", "--numstat", *chunk)
        for entry in text.split("\x1e"):
            if not entry.strip():
                continue
            sha, _, body = entry.strip().partition("\n")
            total = 0
            for line in body.splitlines():
                parts = line.split("\t")
                if len(parts) == 3 and not _bulk(parts[2]):
                    total += sum(int(p) for p in parts[:2] if p.isdigit())
            out[sha.strip()] = total
    return out


def main_commit(rows: list[dict]) -> dict | None:
    """The commit that did most of the work: the most lines changed outside the
    record files, the oldest on a tie. Its subject is the author's own one-line
    account of the work, which is what a person decides about."""
    if not rows:
        return None
    changed = _lines_changed([row["commit"] for row in rows])
    oldest_first = list(reversed(rows))
    return max(oldest_first, key=lambda row: changed.get(row["commit"], 0))


def decision_sentence(record: pathlib.Path, rows: list[dict]) -> str:
    """The decision, stated so that it stands on its own: the work the main
    commit's subject describes, with the count of the others beside it. It says
    what the decision is rather than pointing at another decision. A
    record's title can name the session rather than the work, so the commit
    subject leads; and "Accept or return this:" is not repeated in front of
    every row, because the table's own heading says what the rows are."""
    count = "one commit" if len(rows) == 1 else f"{len(rows)} commits"
    main = main_commit(rows)
    lead = (main or {}).get("subject", "")
    if not lead:
        return _sentence(f"{count} naming this record, with no subject to read")
    others = "" if len(rows) == 1 else f", with {len(rows) - 1} more commit{'s' if len(rows) > 2 else ''} beside it"
    return _sentence(f"{trimmed(lead, 150)}{others}")


def hangs_on_sentence(record: pathlib.Path, rows: list[dict], reasons: list[str],
                      label: str) -> str:
    """Consequences and dependencies, in one sentence, from the label's reasons
    and from the transition rows that touch the record's commits.

    A transition row carries a decision, and every kind permits return and
    refuse, so completed wording is reserved for a row that records adopt or
    promote. A returned or refused row says what was decided instead.
    """
    parts = []
    for reason in reasons:
        if reason.startswith(("returned by ", "refused by ")):
            parts.append(reason)
        elif reason.startswith("changes the manuscript: "):
            parts.append(reason + ", the shared text the coauthors rely on")
        elif reason.startswith("changes "):
            parts.append(reason + ", which every later session works under")
        elif reason.startswith("a release"):
            parts.append("a release, so every installed project receives it on its next update")
        elif "an agent selected" in reason:
            count = int(reason.split()[0])
            parts.append(f"{count} choice{'s' if count != 1 else ''} in it "
                         f"{'were' if count != 1 else 'was'} the agent's, not a person's")
        elif reason == NO_CHOICES_REASON:
            parts.append("it logs no choice, so what was chosen in it, and by whom, is not on record")
        elif "intake row(s)" in reason:
            # A row may return or refuse what it names, so it is not said to admit (rc22).
            parts.append(reason.replace("cite this record", "record a decision on outside material under it"))
        elif "awaiting a recheck" in reason:
            pending = awaiting_recheck(defect_rows_naming(record))
            for r in pending[:2]:
                fixer = r.get("fixed_by") or "an unnamed fixer"
                raiser = r.get("opened_by") or "its raiser"
                count = objects_rechecked(r)
                parts.append(f"{r.get('id', '?')} is fixed by {fixer} and awaits a recheck by {raiser}"
                             + (f" ({count})" if count else ""))
            if len(pending) > 2:
                parts.append(f"and {len(pending) - 2} more fixed row(s) await a recheck")
    shas = {row["commit"] for row in rows}
    try:
        transitions = [t for t in load_jsonl(TRANSITIONS) if isinstance(t, dict)]
    except (OSError, json.JSONDecodeError):
        transitions = []
    here = str(record).replace("\\", "/")
    for t in transitions:
        covers = set(t.get("commits") or [])
        if covers & shas:
            kind, tid = t.get("kind", "?"), t.get("id", "?")
            decision = t.get("decision") or "nothing stated"
            into = t.get("destination") or "the manuscript"
            if kind == "default-adoption" and decision == "adopt":
                later = t.get("later_run", "nothing stated")
                if later and later != "nothing stated":
                    observer = LATER_RUN_OBSERVERS.get(t.get("later_run_kind"))
                    tail = f", observed by {observer}" if observer else ", stated without an observation"
                    parts.append(f"adopted as {tid}, whose later run is {pathlib.Path(later).name}{tail}")
                else:
                    parts.append(f"adopted as {tid}, with no later run recorded yet")
            elif kind == "default-adoption" and decision == "return":
                parts.append(f"returned before adoption, recorded as {tid}")
            elif kind == "default-adoption" and decision == "refuse":
                parts.append(f"refused adoption, recorded as {tid}")
            elif kind == "promotion" and decision == "promote":
                parts.append(f"entered {into} as {tid}")
            elif kind == "promotion" and decision == "return":
                parts.append(f"returned before entering {into}, recorded as {tid}")
            elif kind == "promotion" and decision == "refuse":
                parts.append(f"refused entry to {into}, recorded as {tid}")
            else:
                parts.append(f"{kind} {tid} covers it, decision {decision}")
            # A returned or refused object that is in paper/ anyway is said.
            parts.extend(refused_yet_in_paper(t, sorted(covers & shas)))
        elif t.get("kind") == "default-adoption" and (t.get("later_run") or "").replace("\\", "/") == here:
            tid, decision = t.get("id", "?"), t.get("decision") or "nothing stated"
            if decision == "adopt":
                parts.append(f"it is the later run {tid} relies on")
            else:
                parts.append(f"it is the later run {tid} names, whose decision is {decision}")
    if not parts:
        body = "nothing else recorded depends on it" if label == "routine" else "; ".join(reasons)
    else:
        shown = parts[:4]
        if len(parts) > 4:
            shown.append(f"and {len(parts) - 4} more")
        body = "; ".join(shown)
    return _sentence(f"{label}: {body}")


def excluded_turns(record: pathlib.Path | None) -> set[str]:
    """The turn ids coverage.json marks excluded, and nothing for a record that
    keeps no manifest or one that cannot be read."""
    if record is None:
        return set()
    path = record / "coverage.json"
    if not path.exists():
        return set()
    try:
        manifest = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return set()
    entries = manifest.get("turns")
    if not isinstance(entries, list):
        return set()
    return {entry["turn"] for entry in entries
            if isinstance(entry, dict) and entry.get("status") == "excluded"
            and isinstance(entry.get("turn"), str)}


def origin_sentence(turns: list[dict], rows: list[dict], on_disk: bool,
                    decisions: list[dict] | None = None,
                    record: pathlib.Path | None = None) -> str:
    """Where it comes from: the first human turn the record's decisions cite,
    verbatim and trimmed, else the first turn coverage.json does not exclude. A
    transcript can carry an earlier phase whose turns the record only cites as
    recorded elsewhere, and a postcheck record excludes those turns rather than
    citing them, so quoting the first turn of the file would quote a question
    nothing here answers. A record that excludes every turn names the first and
    says so instead of quoting it."""
    if turns:
        cited = [t for d in (decisions or []) for t in (d.get("human_inputs") or []) if isinstance(t, str)]
        first = next((t for t in turns if t.get("id") in cited), None)
        if first is None:
            excluded = excluded_turns(record)
            kept = next((t for t in turns if t.get("id") not in excluded), None)
            if kept is None:
                first = turns[0]
                return (f"{first.get('id', 'T1')}, {first.get('speaker', 'unknown')}: "
                        "coverage.json excludes every turn here, so none is quoted.")
            first = kept
        return (f"{first.get('id', 'T1')}, {first.get('speaker', 'unknown')}: "
                f'"{trimmed(first.get("text", ""), 110)}"')
    if not on_disk:
        return "The commits name it, but the record is not in this tree."
    return f"No turns on disk; the oldest commit is dated {rows[-1]['date']}." if rows else "No turns on disk."


ALTERNATIVE_RE = re.compile(r"\balternatives?\s+not\s+taken:?\s*", re.IGNORECASE)


def _unstopped(text: str) -> str:
    """Without one trailing full stop, so a clause can continue; an ellipsis
    the trim adds later is left alone."""
    text = " ".join((text or "").split())
    return text[:-1] if text.endswith(".") and not text.endswith("...") else text


def agent_choices(record: pathlib.Path) -> list[str]:
    """Each choice the record says an agent selected, as the record states it:
    the question, what was chosen, and what was not when the row names it, so
    that a reader knows what the agent decided between.
    Nothing is inferred; a row that names no alternative says so."""
    out = []
    for n, row in enumerate(record_rows(record, "decisions.jsonl"), 1):
        selector = row.get("selected_by")
        if not (isinstance(selector, dict) and selector.get("kind") == "agent"):
            continue
        rid = row.get("id") or f"D{n}"
        question = trimmed(row.get("question") or "(no question recorded)", 90)
        parts = ALTERNATIVE_RE.split(row.get("choice") or "", maxsplit=1)
        chosen = trimmed(_unstopped(parts[0] or "(no choice recorded)"), 130)
        if len(parts) > 1 and parts[1].strip():
            out.append(f"{rid} {question} Chose {chosen}; not {trimmed(_unstopped(parts[1]), 110)}.")
        else:
            out.append(f"{rid} {question} Chose {chosen} (no alternative named).")
    return out


def agent_choices_sentence(record: pathlib.Path) -> str:
    """The agent's choices, or, when it selected none, what the rows do record.

    An absence of agent-selected rows is not human selection: the vocabulary
    also holds joint and unknown selectors, and a proposed row nobody selected.
    A person's choice is claimed only where every row records a human selector
    and selected status.
    """
    items = agent_choices(record)
    if not items:
        rows = record_rows(record, "decisions.jsonl")
        if not rows:
            return "None recorded."
        human = joint_or_unknown = proposed = 0
        for row in rows:
            selector = row.get("selected_by")
            kind = selector.get("kind") if isinstance(selector, dict) else None
            if row.get("status") != "selected":
                proposed += 1
            elif kind == "human":
                human += 1
            else:
                joint_or_unknown += 1
        if human == len(rows):
            return "None; every recorded choice was a person's."
        counts = []
        if human:
            counts.append(f"{human} a person's")
        if joint_or_unknown:
            counts.append(f"{joint_or_unknown} with a joint or unknown selector")
        if proposed:
            counts.append(f"{proposed} proposed, not selected")
        return "None agent-selected; " + "; ".join(counts) + "."
    shown = items[:4]
    if len(items) > 4:
        shown.append(f"And {len(items) - 4} more in decisions.jsonl.")
    return " ".join(shown)


def _cell(text: str) -> str:
    return " ".join((text or "").split()).replace("|", "\\|")


def queue_table(entries: list[dict]) -> list[str]:
    """The waiting records as a Markdown table a person can read in chat,
    numbered so the person can answer by number."""
    out = ["| # | record | the work to accept or return | what hangs on it | what the agent chose | where it comes from | owners |",
           "| --- | --- | --- | --- | --- | --- | --- |"]
    for n, e in enumerate(entries, 1):
        out.append(f"| {n} | {_cell(e['id'])} | {_cell(e['decision'])} | {_cell(e['hangs_on'])} | "
                   f"{_cell(e['agent_choices'])} | {_cell(e['origin'])} | "
                   f"{_cell(owners_text(e['owners'], e['owner_basis']))} |")
    return out


def queue_entries(limit: int | None = None) -> dict:
    """The records with commits not currently accepted, newest first; returned
    and refused work stays here until a later decision accepts it."""
    index = review_index()
    # The same selection `accept` makes for a person with no --range: every
    # commit in the window that no person and no delegated actor has accepted.
    unaccepted = default_batch("human", index)
    rows = _log_rows(unaccepted, with_files=True)
    order, groups, without = [], {}, []
    for row in rows:
        named = commit_records(row["body"])
        if not named:
            without.append(row)
            continue
        for record in named:
            if record not in groups:
                groups[record] = []
                order.append(record)
            groups[record].append(row)
    entries = []
    for record in order:
        commits = groups[record]
        path = record_path(record)
        turns = record_turns(path)
        label, reasons = queue_label(path, commits)
        on_disk = (path / "evidence.json").exists()
        owners, owner_basis = record_owners(path)
        entries.append({
            "id": path.name,
            "path": str(path).replace("\\", "/"),
            "on_disk": on_disk,
            "date": commits[0]["date"],
            "first_words": trimmed(turns[0]["text"], 80) if turns else "",
            "turns": len(turns),
            "commits": [row["commit"] for row in commits],
            "count": len(commits),
            "label": label,
            "reasons": reasons,
            "decision": decision_sentence(path, commits),
            "hangs_on": hangs_on_sentence(path, commits, reasons, label),
            "agent_choices": agent_choices_sentence(path),
            "origin": origin_sentence(turns, commits, on_disk, record_rows(path, "decisions.jsonl"), path),
            # Whose work it is: the decision rows' owners, else the speakers of
            # the turns the record cites, else none, with the basis "not stated".
            "owners": owners,
            "owner_basis": owner_basis,
        })
    shown = entries if limit is None else entries[:limit]
    # The bound is read as the brief reads it (4949c1c F2): over every commit
    # naming the record, accepted ones included, so the listing and the JSON
    # name the commit the brief's version line names. Read from the waiting
    # commits alone, it named an older one when the newest was already accepted.
    naming: dict[str, list[str]] = {}
    for row in (_log_rows(reviewable_commits()) if shown else []):
        for record in commit_records(row["body"]):
            naming.setdefault(record, []).append(row["commit"])
    for record, entry in zip(order, shown):
        # The version the row shows, for `accept --record <id> --through`. The
        # table keeps to its sentences; the listing and the JSON carry it.
        entry["through"] = version_bound(naming.get(record) or entry["commits"])[0]
    return {"records": shown, "records_total": len(entries),
            "needs_you": sum(1 for e in entries if e["label"] == "needs you"),
            "routine": sum(1 for e in entries if e["label"] == "routine"),
            "unaccepted_commits": len(rows),
            "commits_without_a_record": len(without),
            # Named, not only counted, so every agent shows the person the same
            # commits: given a bare count, one model listed them from git and
            # another said nothing was waiting (agent-parity matrix, 2026-10-15).
            "commits_without_a_record_list": [unrecorded_commit(row) for row in without],
            "e_waiting": e_waiting(),
            "meaning": "a label triages; it never accepts, and `routine` is not approval"}


